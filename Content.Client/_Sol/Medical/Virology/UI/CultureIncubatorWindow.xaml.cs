using Content.Shared._Sol.Medical.Virology;
using Content.Shared.Chemistry.Reagent;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;
using FancyWindow = Content.Client.UserInterface.Controls.FancyWindow;

namespace Content.Client._Sol.Medical.Virology.UI;

[GenerateTypedNameReferences]
public sealed partial class CultureIncubatorWindow : FancyWindow
{
    [Dependency] private readonly IGameTiming _timing = default!;
    [Dependency] private readonly IPrototypeManager _prototypes = default!;

    public event Action? OnStart;
    public event Action? OnRetrieve;
    public event Action? OnEjectAll;
    public event Action<NetEntity>? OnEjectSample;

    private CultureIncubatorBoundUserInterfaceState? _lastState;

    public CultureIncubatorWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        StartButton.OnPressed += _ => OnStart?.Invoke();
        RetrieveButton.OnPressed += _ => OnRetrieve?.Invoke();
        EjectAllButton.OnPressed += _ => OnEjectAll?.Invoke();
    }

    public void UpdateState(CultureIncubatorBoundUserInterfaceState state)
    {
        _lastState = state;
        ApplyState(state);
    }

    private void ApplyState(CultureIncubatorBoundUserInterfaceState state)
    {
        var reagentName = _prototypes.TryIndex<ReagentPrototype>(state.NutrientReagent, out var reagent)
            ? reagent.LocalizedName
            : state.NutrientReagent;

        NutrientLabel.Text = Loc.GetString("sol-culture-incubator-ui-nutrient",
            ("amount", state.NutrientAmount.ToString("F1")),
            ("max", state.NutrientMax.ToString("F0")),
            ("reagent", reagentName));

        CostLabel.Text = Loc.GetString("sol-culture-incubator-ui-cost",
            ("cost", state.EstimatedNutrientCost.ToString("F1")),
            ("count", state.Samples.Length),
            ("max", state.MaxSamples));

        SampleList.RemoveAllChildren();
        var canEject = state.Powered && !state.Busy && !state.HasFinished;
        foreach (var sample in state.Samples)
        {
            var detail = string.IsNullOrEmpty(sample.Detail)
                ? Loc.GetString("sol-bioterror-sample-genetics-none")
                : sample.Detail;

            var text = Loc.GetString("sol-culture-incubator-ui-sample-entry",
                ("label", sample.Label),
                ("quality", sample.Quality.ToString("F2")),
                ("detail", detail),
                ("contaminated", sample.Contaminated));

            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 6,
                HorizontalExpand = true,
            };

            row.AddChild(new Label
            {
                Text = text,
                HorizontalExpand = true,
                ClipText = true,
            });

            var ejectButton = new Button
            {
                Text = Loc.GetString("sol-culture-incubator-ui-eject"),
                Disabled = !canEject,
            };
            var entity = sample.Entity;
            ejectButton.OnPressed += _ => OnEjectSample?.Invoke(entity);
            row.AddChild(ejectButton);
            SampleList.AddChild(row);
        }

        if (state.Samples.Length == 0)
        {
            SampleList.AddChild(new Label
            {
                Text = Loc.GetString("sol-culture-incubator-ui-samples-empty"),
            });
        }

        UpdateProgress(state);
        UpdateControls(state);
    }

    private void UpdateProgress(CultureIncubatorBoundUserInterfaceState state)
    {
        if (state.Busy && state.CycleEndsAt > state.CycleStartedAt)
        {
            var total = (state.CycleEndsAt - state.CycleStartedAt).TotalSeconds;
            var remaining = Math.Max(0, (state.CycleEndsAt - _timing.CurTime).TotalSeconds);
            var progress = total > 0 ? 1f - remaining / total : 1f;
            ProgressLabel.Text = Loc.GetString("sol-culture-incubator-ui-progress",
                ("remaining", TimeSpan.FromSeconds(remaining).ToString(@"mm\:ss")),
                ("percent", (progress * 100f).ToString("F0")));
        }
        else if (state.HasFinished)
        {
            ProgressLabel.Text = Loc.GetString("sol-culture-incubator-ui-ready");
        }
        else
        {
            ProgressLabel.Text = string.Empty;
        }
    }

    private void UpdateControls(CultureIncubatorBoundUserInterfaceState state)
    {
        var canInteract = state.Powered && !state.Busy && !state.HasFinished;
        StartButton.Disabled = !canInteract || state.Samples.Length == 0
            || state.NutrientAmount < state.EstimatedNutrientCost;
        StartButton.Visible = !state.Busy && !state.HasFinished;
        RetrieveButton.Visible = state.HasFinished;
        RetrieveButton.Disabled = !state.HasFinished;
        EjectAllButton.Disabled = !canInteract || state.Samples.Length == 0;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_lastState is { Busy: true })
            UpdateProgress(_lastState);
    }
}
