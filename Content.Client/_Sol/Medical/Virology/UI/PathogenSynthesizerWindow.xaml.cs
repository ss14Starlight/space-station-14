using Content.Shared._Sol.Medical.Virology;
using Content.Shared.Chemistry.Reagent;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;
using System.Linq;
using FancyWindow = Content.Client.UserInterface.Controls.FancyWindow;

namespace Content.Client._Sol.Medical.Virology.UI;

[GenerateTypedNameReferences]
public sealed partial class PathogenSynthesizerWindow : FancyWindow
{
    [Dependency] private readonly IGameTiming _timing = default!;
    [Dependency] private readonly IPrototypeManager _prototypes = default!;

    public event Action? OnStart;
    public event Action? OnClearSelection;
    public event Action? OnSubstratePressed;
    public event Action<NetEntity>? OnToggleGene;

    private PathogenSynthesizerBoundUserInterfaceState? _lastState;

    public PathogenSynthesizerWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        StartButton.OnPressed += _ => OnStart?.Invoke();
        ClearButton.OnPressed += _ => OnClearSelection?.Invoke();
        SubstrateButton.OnPressed += _ => OnSubstratePressed?.Invoke();
        ForecastCollapsible.BodyVisible = true;
    }

    public void UpdateState(PathogenSynthesizerBoundUserInterfaceState state)
    {
        _lastState = state;
        ApplyState(state);
    }

    private void ApplyState(PathogenSynthesizerBoundUserInterfaceState state)
    {
        var reagentName = _prototypes.TryIndex<ReagentPrototype>(state.StabilizerReagent, out var reagent)
            ? reagent.LocalizedName
            : state.StabilizerReagent;

        StabilizerLabel.Text = Loc.GetString("sol-pathogen-synth-ui-stabilizer",
            ("amount", state.StabilizerAmount.ToString("F1")),
            ("max", state.StabilizerMax.ToString("F0")),
            ("needed", state.StabilizerNeeded.ToString("F0")),
            ("reagent", reagentName));

        SubstrateLabel.Text = state.HasSubstrate
            ? Loc.GetString("sol-pathogen-synth-ui-substrate-loaded", ("name", state.SubstrateName ?? ""))
            : Loc.GetString("sol-pathogen-synth-ui-substrate-empty");

        SubstrateButton.Text = state.HasSubstrate
            ? Loc.GetString("sol-pathogen-synth-ui-substrate-eject")
            : Loc.GetString("sol-pathogen-synth-ui-substrate-insert");
        SubstrateButton.Disabled = state.Busy;

        BudgetLabel.Text = Loc.GetString("sol-pathogen-synth-ui-budget",
            ("used", state.BudgetUsed),
            ("max", state.MaxBudget));

        TimeLabel.Text = Loc.GetString("sol-pathogen-synth-ui-time",
            ("seconds", state.EstimatedSeconds.ToString("F0")));

        ErrorLabel.Text = state.ValidationError ?? string.Empty;
        ErrorLabel.Visible = !string.IsNullOrEmpty(state.ValidationError);

        GeneGrid.RemoveAllChildren();
        foreach (var gene in state.Genes)
        {
            var button = new Button
            {
                Text = Loc.GetString("sol-pathogen-synth-ui-gene-button",
                    ("label", gene.Label),
                    ("cost", gene.BudgetCost),
                    ("selected", gene.Selected)),
                ToggleMode = true,
                Pressed = gene.Selected,
                Disabled = state.Busy,
                HorizontalExpand = true,
            };
            var entity = gene.Entity;
            button.OnPressed += _ => OnToggleGene?.Invoke(entity);
            GeneGrid.AddChild(button);
        }

        if (state.Genes.Length == 0)
        {
            GeneGrid.AddChild(new Label
            {
                Text = Loc.GetString("sol-pathogen-synth-ui-genes-empty"),
            });
        }

        ApplyForecast(state.Forecast);
        UpdateProgress(state);
        StartButton.Disabled = !state.CanStart;
        ClearButton.Disabled = state.Busy || state.Genes.All(g => !g.Selected);
    }

    private void ApplyForecast(PathogenSynthesizerForecastState? forecast)
    {
        var hasForecast = forecast != null;
        ForecastEmptyLabel.Visible = !hasForecast;
        ForecastTransmissionLabel.Visible = hasForecast;
        ForecastStagesLabel.Visible = hasForecast;
        ForecastSymptomsLabel.Visible = hasForecast;
        ForecastOrgansLabel.Visible = hasForecast;
        ForecastTreatmentsLabel.Visible = hasForecast;
        ForecastStatsLabel.Visible = hasForecast;

        if (forecast == null)
            return;

        ForecastTransmissionLabel.Text = Loc.GetString("sol-pathogen-synth-ui-forecast-transmission",
            ("value", forecast.Transmission));
        ForecastStagesLabel.Text = Loc.GetString("sol-pathogen-synth-ui-forecast-stages",
            ("incubation", forecast.Incubation),
            ("symptomatic", forecast.Symptomatic),
            ("critical", forecast.Critical),
            ("recovery", forecast.Recovery));
        ForecastSymptomsLabel.Text = Loc.GetString("sol-pathogen-synth-ui-forecast-symptoms",
            ("value", forecast.Symptoms));
        ForecastOrgansLabel.Text = Loc.GetString("sol-pathogen-synth-ui-forecast-organs",
            ("value", forecast.Organs));
        ForecastTreatmentsLabel.Text = Loc.GetString("sol-pathogen-synth-ui-forecast-treatments",
            ("value", forecast.Treatments));
        ForecastStatsLabel.Text = Loc.GetString("sol-pathogen-synth-ui-forecast-stats",
            ("infectivity", forecast.Infectivity),
            ("lethality", forecast.Lethality),
            ("sterilant", forecast.Sterilant));
    }

    private void UpdateProgress(PathogenSynthesizerBoundUserInterfaceState state)
    {
        if (state.Busy && state.CycleEndsAt > state.CycleStartedAt)
        {
            var total = (state.CycleEndsAt - state.CycleStartedAt).TotalSeconds;
            var remaining = Math.Max(0, (state.CycleEndsAt - _timing.CurTime).TotalSeconds);
            var progress = total > 0 ? 1f - remaining / total : 1f;
            ProgressLabel.Text = Loc.GetString("sol-pathogen-synth-ui-progress",
                ("remaining", TimeSpan.FromSeconds(remaining).ToString(@"mm\:ss")),
                ("percent", (progress * 100f).ToString("F0")));
        }
        else
        {
            ProgressLabel.Text = string.Empty;
        }
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_lastState is { Busy: true })
            UpdateProgress(_lastState);
    }
}
