using Content.Shared._Sol.Medical.Allergy;
using Content.Shared.Preferences;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Sol.Medical.Allergy.UI;

[GenerateTypedNameReferences]
public sealed partial class AllergyEntry : PanelContainer
{
    public event Action<ProtoId<AllergyPrototype>, bool, AllergySeverity>? OnChanged;

    public ProtoId<AllergyPrototype> AllergyId => _allergy.ID;
    public bool IsSelected => AllergyCheckbox.Pressed;
    public AllergySeverity Severity { get; private set; }

    private readonly AllergyPrototype _allergy;
    private bool _isUpdating;

    private static readonly AllergySeverity[] IntensityOrder =
    [
        AllergySeverity.Mild,
        AllergySeverity.Moderate,
        AllergySeverity.Severe,
        AllergySeverity.Anaphylaxis,
    ];

    public AllergyEntry(AllergyPrototype allergy)
    {
        RobustXamlLoader.Load(this);
        _allergy = allergy;
        Severity = allergy.DefaultSeverity;

        AllergyNameLabel.Text = Loc.GetString(allergy.Name);
        AllergyDescriptionLabel.SetMessage(Loc.GetString(allergy.Description));

        for (var i = 0; i < IntensityOrder.Length; i++)
        {
            IntensityButton.AddItem(HumanoidCharacterProfile.FormatSeverity(IntensityOrder[i]), i);
        }

        SelectIntensity(Severity);
        AllergyCheckbox.OnToggled += OnCheckboxToggled;
        IntensityButton.OnItemSelected += OnIntensitySelected;
    }

    public void SetState(bool selected, AllergySeverity severity, bool locked = false)
    {
        _isUpdating = true;
        AllergyCheckbox.Pressed = selected;
        AllergyCheckbox.Disabled = locked;
        IntensityButton.Visible = selected;
        IntensityButton.Disabled = locked;
        SelectIntensity(severity);
        UpdateSelectedStyle();

        AllergyNameLabel.Text = locked
            ? Loc.GetString("cd-allergies-editor-innate-entry", ("name", Loc.GetString(_allergy.Name)))
            : Loc.GetString(_allergy.Name);

        _isUpdating = false;
    }

    private void OnCheckboxToggled(BaseButton.ButtonToggledEventArgs args)
    {
        if (_isUpdating)
            return;

        IntensityButton.Visible = args.Pressed;
        UpdateSelectedStyle();
        OnChanged?.Invoke(AllergyId, args.Pressed, Severity);
    }

    private void OnIntensitySelected(OptionButton.ItemSelectedEventArgs args)
    {
        IntensityButton.SelectId(args.Id);
        if (_isUpdating)
            return;

        Severity = IntensityOrder[args.Id];
        if (AllergyCheckbox.Pressed)
            OnChanged?.Invoke(AllergyId, true, Severity);
    }

    private void SelectIntensity(AllergySeverity severity)
    {
        Severity = severity;
        var index = Array.IndexOf(IntensityOrder, severity);
        if (index < 0)
            index = 0;
        IntensityButton.SelectId(index);
    }

    private void UpdateSelectedStyle()
    {
        if (AllergyCheckbox.Pressed)
            AddStyleClass("TraitsEntrySelected");
        else
            RemoveStyleClass("TraitsEntrySelected");
    }
}
