using System.Linq;
using System.Numerics;
using Content.Client._Starlight.UserInterface.Controls;
using Content.Client.UserInterface.Controls;
using Content.Shared._Starlight.CCVar;
using Robust.Client.AutoGenerated;
using Robust.Client.Input;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.Timing;

namespace Content.Client.UserInterface.Systems.MenuBar.Widgets
{
    [GenerateTypedNameReferences]
    public sealed partial class GameTopMenuBar : UIWidget
    {
        #region Starlight
        [Dependency] private IConfigurationManager _cfg = default!;
        [Dependency] private IInputManager _input = default!;

        public static readonly BarLayoutEntry[] LayoutEntries =
        [
            new("EscapeButton", "game-hud-open-escape-menu-button-tooltip"),
            new("GuidebookButton", "game-hud-open-guide-menu-button-tooltip"),
            new("CharacterButton", "game-hud-open-character-menu-button-tooltip"),
            new("EmotesButton", "game-hud-open-emotes-menu-button-tooltip"),
            new("CraftingButton", "game-hud-open-crafting-menu-button-tooltip"),
            new("ActionButton", "game-hud-open-actions-menu-button-tooltip"),
            new("LanguageButton", "language-menu-open-tooltip"),
            new("AdminButton", "game-hud-open-admin-menu-button-tooltip"),
            new("AHelpButton", "ui-options-function-open-a-help"),
            new("SandboxButton", "game-hud-open-sandbox-menu-button-tooltip"),
            new("ReportBugButton", "game-hud-open-bug-report-window-button-tooltip"),
            new("AchievementButton", "game-hud-open-achievement-menu-button-tooltip"),
        ];

        private string _keyHints = "Hold";
        private readonly List<MenuButton> _buttons = new();
        #endregion

        public GameTopMenuBar()
        {
            RobustXamlLoader.Load(this);
            IoCManager.InjectDependencies(this); // Starlight

            // Starlight-start
            _buttons.AddRange(Bar.Children.OfType<MenuButton>());
            foreach (var button in _buttons)
            {
                button.IconScale = new Vector2(0.45f, 0.45f);
                button.ShowKey = false;
            }

            Bar.Setup();
            _cfg.OnValueChanged(StarlightCCVars.MenuBarLayout, layout => Bar.SetPlacements(BarLayout.Parse(layout)), true);
            _cfg.OnValueChanged(StarlightCCVars.MenuBarKeyHints, mode => _keyHints = mode, true);
            // Starlight-end
        }

        #region Starlight

        protected override void ExitedTree()
        {
            base.ExitedTree();
            _cfg.UnsubValueChanged(StarlightCCVars.MenuBarLayout, layout => Bar.SetPlacements(BarLayout.Parse(layout)));
            _cfg.UnsubValueChanged(StarlightCCVars.MenuBarKeyHints, mode => _keyHints = mode);
        }

        protected override void FrameUpdate(FrameEventArgs args)
        {
            base.FrameUpdate(args);

            var show = _keyHints switch
            {
                "Always" => true,
                "Hold" => _input.IsKeyDown(Keyboard.Key.Alt),
                _ => false,
            };

            foreach (var button in _buttons)
                button.KeyHint = show;
        }
        #endregion
    }
}
