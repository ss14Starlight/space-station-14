using System.Numerics;
using Content.Client.Stylesheets;
using Content.Client.UserInterface.Systems.Chat.Widgets;
using Content.Shared._Sol.CCVar;
using Content.Shared._Starlight.CCVar;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;

namespace Content.Client.UserInterface.Screens;

[GenerateTypedNameReferences]
public sealed partial class SeparatedChatGameScreen : InGameScreen
{
    public const string StyleClassChatContainer = "ChatContainer";
    public const string StyleClassChatOutput = "ChatOutput";

    [Dependency] private IConfigurationManager _cfg = default!; // Starlight / Sol

    private const float SidePanelCollapsedHeight = 32f;
    private const float SidePanelDefaultExpandedHeight = 220f;
    private const float SidePanelExpandedMinHeight = 83f;

    private float _sidePanelExpandedHeight = SidePanelDefaultExpandedHeight;
    private bool _sidePanelSplitInitialized;
    private bool? _pendingSidePanelExpanded;
    private bool _applyingCVarFromUi;

    public SeparatedChatGameScreen()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        AutoscaleMaxResolution = new Vector2i(1080, 770);

        SetAnchorPreset(ScreenContainer, LayoutPreset.Wide);
        SetAnchorPreset(ViewportContainer, LayoutPreset.Wide);
        SetAnchorPreset(MainViewport, LayoutPreset.Wide);
        SetAnchorAndMarginPreset(Inventory, LayoutPreset.BottomLeft, margin: 5);
        SetAnchorAndMarginPreset(TopLeftContainer, LayoutPreset.TopLeft, margin: 10);
        SetAnchorAndMarginPreset(Ghost, LayoutPreset.BottomWide, margin: 80);
        SetAnchorAndMarginPreset(Hotbar, LayoutPreset.BottomWide, margin: 5);
        SetAnchorAndMarginPreset(Alerts, LayoutPreset.CenterRight, margin: 10);

        ScreenContainer.OnSplitResizeFinished += () =>
            OnChatResized?.Invoke(new Vector2(ScreenContainer.SplitFraction, 0));

        ViewportContainer.OnResized += ResizeActionContainer;

        SidePanel.OnExpansionChanged += OnSidePanelExpansionChanged;
        ChatSideSplit.OnSplitResized += OnChatSideSplitResized;

        // Sol: restore remembered expanded height / expand preference.
        _sidePanelExpandedHeight = Math.Max(
            _cfg.GetCVar(SolCCVars.SeparatedChatSideExpandedHeight),
            SidePanelExpandedMinHeight);

        _cfg.OnValueChanged(SolCCVars.SeparatedChatSideExpandedHeight, OnExpandedHeightCVarChanged);
        _cfg.OnValueChanged(SolCCVars.SeparatedChatSideExpanded, OnSidePanelExpandedCVarChanged);

        var startExpanded = _cfg.GetCVar(SolCCVars.SeparatedChatSideExpanded);
        SidePanel.SetExpandedState(startExpanded, notify: false);

        if (ChatSideSplit.Size.Y > 0)
            ApplySidePanelExpansion(startExpanded);
        else
            _pendingSidePanelExpanded = startExpanded;

        ChatSideSplit.OnResized += () =>
        {
            if (_sidePanelSplitInitialized || ChatSideSplit.Size.Y <= 0)
                return;

            _sidePanelSplitInitialized = true;

            if (_pendingSidePanelExpanded.HasValue)
            {
                ApplySidePanelExpansion(_pendingSidePanelExpanded.Value);
                _pendingSidePanelExpanded = null;
                return;
            }

            ApplySidePanelExpansion(SidePanel.IsExpanded);
        };

        //starlight
        _cfg.OnValueChanged(StarlightCCVars.ChatSeparatedMinWidth, SetMinimumChatWidth, true);
        //starlight end
    }

    //starlight
    private void SetMinimumChatWidth(int width)
    {
        SeparatedChatPanel.MinWidth = width;
        //TODO: Theres a issue where the actual UI doesnt get re measured so theres some wackyness here, but its not a huge deal
    }
    //starlight end

    private void OnSidePanelExpansionChanged(bool expanded)
    {
        SetExpandedCVar(expanded);

        if (ChatSideSplit.Size.Y <= 0)
        {
            _pendingSidePanelExpanded = expanded;
            return;
        }

        ApplySidePanelExpansion(expanded);
    }

    private void OnExpandedHeightCVarChanged(float height)
    {
        if (_applyingCVarFromUi)
            return;

        _sidePanelExpandedHeight = Math.Max(height, SidePanelExpandedMinHeight);

        if (!SidePanel.IsExpanded || ChatSideSplit.Size.Y <= 0)
            return;

        ApplySidePanelExpansion(true);
    }

    private void OnSidePanelExpandedCVarChanged(bool expanded)
    {
        if (_applyingCVarFromUi)
            return;

        if (SidePanel.IsExpanded == expanded)
            return;

        SidePanel.SetExpandedState(expanded, notify: false);

        if (ChatSideSplit.Size.Y <= 0)
        {
            _pendingSidePanelExpanded = expanded;
            return;
        }

        ApplySidePanelExpansion(expanded);
    }

    private void ApplySidePanelExpansion(bool expanded)
    {
        var splitWidth = ChatSideSplit.SplitWidth;

        if (expanded)
        {
            if (ChatSideSplit.Size.Y <= 0)
            {
                _pendingSidePanelExpanded = true;
                return;
            }

            var panelHeight = Math.Max(_sidePanelExpandedHeight, SidePanelExpandedMinHeight);
            ChatSideSplit.SplitCenter = GetSidePanelSplitCenter(panelHeight, splitWidth);
            return;
        }

        if (ChatSideSplit.Size.Y > 0)
        {
            var currentHeight = GetSidePanelHeight(ChatSideSplit.SplitCenter);
            if (currentHeight > SidePanelCollapsedHeight + 1)
            {
                _sidePanelExpandedHeight = currentHeight;
                SetExpandedHeightCVar(_sidePanelExpandedHeight);
            }
        }

        ChatSideSplit.SplitCenter = GetSidePanelSplitCenter(SidePanelCollapsedHeight, splitWidth);
    }

    private void OnChatSideSplitResized()
    {
        if (!SidePanel.IsExpanded)
            return;

        var panelHeight = GetSidePanelHeight(ChatSideSplit.SplitCenter);
        if (panelHeight <= SidePanelCollapsedHeight + 8)
            return;

        if (Math.Abs(_sidePanelExpandedHeight - panelHeight) < 0.5f)
            return;

        _sidePanelExpandedHeight = panelHeight;
        SetExpandedHeightCVar(_sidePanelExpandedHeight);
    }

    private void SetExpandedCVar(bool expanded)
    {
        _applyingCVarFromUi = true;
        _cfg.SetCVar(SolCCVars.SeparatedChatSideExpanded, expanded);
        _applyingCVarFromUi = false;
    }

    private void SetExpandedHeightCVar(float height)
    {
        _applyingCVarFromUi = true;
        _cfg.SetCVar(SolCCVars.SeparatedChatSideExpandedHeight, height);
        _applyingCVarFromUi = false;
    }

    private float GetSidePanelHeight(float splitCenter) =>
        splitCenter - ChatSideSplit.SplitWidth / 2f;

    private static float GetSidePanelSplitCenter(float panelHeight, float splitWidth) =>
        panelHeight + splitWidth / 2f;

    private void ResizeActionContainer()
    {
        float indent = 20;
        Actions.ActionsContainer.MaxGridWidth = ViewportContainer.Size.X - indent;
    }

    public override ChatBox ChatBox => GetWidget<ChatBox>()!;

    public override void SetChatSize(Vector2 size)
    {
        ScreenContainer.ResizeMode = SplitContainer.SplitResizeMode.RespectChildrenMinSize;
    }
}
