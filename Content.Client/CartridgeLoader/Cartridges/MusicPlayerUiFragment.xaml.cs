namespace Content.Client.CartridgeLoader.Cartridges
{
    [GenerateTypedNameReferences]
    public sealed partial class MusicPlayerUiFragment : BoxContainer
    {
        [Dependency] private readonly IResourceManager _resourceManager = default!;
        [Dependency] private readonly IEntityManager _entityManager = default!;
        public MusicPlayerSystem? MusicSystem => _entityManager?.System<MusicPlayerSystem>();
        private static readonly ISawmill Log = Logger.GetSawmill("music-player");

        public event Action? OnPlayPressed;
        public event Action? OnPausePressed;
        public event Action? OnStopPressed;
        public event Action<int>? OnTrackSelected;
        public event Action<float>? OnSeekRequested;
        public event Action<float>? OnVolumeChanged;
        public event Action? OnSkipPressed;
        public event Action? OnShufflePressed;

        private readonly List<string> _trackPaths = new();
        private readonly List<string> _trackNames = new();
        private bool _isUpdatingSlider = false;
        private readonly Dictionary<string, Attribution> musicPlayerAttributions = new();
        private readonly Dictionary<string, Attribution> lobbyAttributions = new();

        public MusicPlayerUiFragment()
        {
            RobustXamlLoader.Load(this);
            IoCManager.InjectDependencies(this);

            LoadAttributions();
            VolumeSlider.OnValueChanged += HandleVolumeSliderChanged;
            ProgressSlider.OnValueChanged += HandleProgressSliderChanged;
            PlayButton.OnPressed += HandlePlayButtonPressed;
            PauseButton.OnPressed += HandlePauseButtonPressed;
            StopButton.OnPressed += HandleStopButtonPressed;
            ShuffleButton.OnPressed += HandleShuffleButtonPressed;
            SkipButton.OnPressed += HandleSkipButtonPressed;
            PopulateTrackList();
        }

        private void HandleVolumeSliderChanged(Robust.Client.UserInterface.Controls.Range obj)
            => OnVolumeChanged?.Invoke(obj.Value);

        private void HandleProgressSliderChanged(Robust.Client.UserInterface.Controls.Range obj)
        {
            if (!_isUpdatingSlider)
                OnSeekRequested?.Invoke(obj.Value);
        }

        private void HandlePlayButtonPressed(BaseButton.ButtonEventArgs args)
        {
            var musicSystem = MusicSystem;
            if (musicSystem == null) return;
            if (musicSystem.PausedPosition > 0)
                musicSystem.ResumeTrack();
            else
                OnPlayPressed?.Invoke();
        }

        private void HandlePauseButtonPressed(BaseButton.ButtonEventArgs args) => OnPausePressed?.Invoke();
        private void HandleStopButtonPressed(BaseButton.ButtonEventArgs args) => OnStopPressed?.Invoke();
        private void HandleSkipButtonPressed(BaseButton.ButtonEventArgs args) => OnSkipPressed?.Invoke();
        private void HandleShuffleButtonPressed(BaseButton.ButtonEventArgs args) => OnShufflePressed?.Invoke();

        public void UpdateUI()
        {
            var musicSystem = MusicSystem;
            if (musicSystem == null) return;

            var isPlaying = musicSystem.IsPlaying;
            var position = musicSystem.CurrentPlaybackPosition;
            var duration = musicSystem.CurrentTrackDuration;

            _isUpdatingSlider = true;
            ProgressSlider.MaxValue = duration > 0 ? duration : 1;
            ProgressSlider.Value = duration > 0 ? position : 0;
            _isUpdatingSlider = false;

            CurrentTime.Text = FormatTime(position);
            TotalTime.Text = FormatTime(duration);

            NowPlaying.Text = isPlaying && !string.IsNullOrEmpty(musicSystem.CurrentTrackName)
                ? $"♪ {musicSystem.CurrentTrackName}"
                : "Now Playing: (none)";

            PlayButton.Disabled = isPlaying;
            PauseButton.Disabled = !isPlaying && musicSystem.PausedPosition == 0;
            StopButton.Disabled = !isPlaying && musicSystem.PausedPosition == 0;
        }

        public void UpdateProgress(float currentTime, float totalTime)
        {
            _isUpdatingSlider = true;
            CurrentTime.Text = FormatTime(currentTime);
            TotalTime.Text = FormatTime(totalTime);
            ProgressSlider.MaxValue = totalTime > 0 ? totalTime : 1;
            ProgressSlider.Value = totalTime > 0 ? currentTime : 0;
            _isUpdatingSlider = false;
        }

        public void UpdateNowPlaying(string trackName, bool isPlaying)
        {
            NowPlaying.Text = isPlaying && !string.IsNullOrEmpty(trackName)
                ? $"♪ {trackName}"
                : "Now Playing: (none)";
        }

        public void UpdatePlaybackButtons(bool isPlaying)
        {
            PlayButton.Disabled = isPlaying;
            PauseButton.Disabled = !isPlaying;
            StopButton.Disabled = !isPlaying;
        }

        public string GetTrackPath(int index)
            => index >= 0 && index < _trackPaths.Count ? _trackPaths[index] : "";

        public string GetTrackName(int index)
            => index >= 0 && index < _trackNames.Count ? _trackNames[index] : "Unknown Track";

        public int GetSelectedTrackIndex()
        {
            var selectedItems = TrackList.GetSelected();
            return selectedItems.Any() ? TrackList.IndexOf(selectedItems.First()) : -1;
        }

        private string FormatTime(float seconds)
        {
            if (seconds <= 0) return "0:00";
            var minutes = (int)(seconds / 60);
            var secs = (int)(seconds % 60);
            return $"{minutes}:{secs:00}";
        }

        private void LoadAttributions()
        {
            var musicPlayerAttribs = LoadAttributions("/Audio/MusicPlayer/attributions.yml");
            var lobbyAttribs = LoadAttributions("/Audio/Lobby/attributions.yml");
            foreach (var kvp in musicPlayerAttribs)
                musicPlayerAttributions[kvp.Key] = kvp.Value;
            foreach (var kvp in lobbyAttribs)
                lobbyAttributions[kvp.Key] = kvp.Value;
        }

        private void PopulateTrackList()
        {
            ScanFolderForMusic("/Audio/MusicPlayer", musicPlayerAttributions);
            ScanFolderForMusic("/Audio/Lobby", lobbyAttributions);
            var musicSystem = MusicSystem;
            musicSystem?.SetPlaylist(_trackPaths, _trackNames);
        }

        private Dictionary<string, Attribution> LoadAttributions(string attributionsPath)
        {
            var attributions = new Dictionary<string, Attribution>();
            try
            {
                if (_resourceManager.TryContentFileRead(attributionsPath, out var stream))
                {
                    using var reader = new System.IO.StreamReader(stream);
                    var content = reader.ReadToEnd();
                    var lines = content.Split('\n');
                    string? currentArtist = null;
                    string? currentFile = null;
                    foreach (var line in lines)
                    {
                        var trimmed = line.Trim();
                        if (trimmed.StartsWith("- files: [\""))
                        {
                            var start = trimmed.IndexOf("[\"") + 2;
                            var end = trimmed.IndexOf("\"]");
                            if (start > 1 && end > start)
                                currentFile = trimmed.Substring(start, end - start);
                        }
                        else if (trimmed.StartsWith("artist: "))
                            currentArtist = trimmed.Substring(8).Trim();
                        else if (trimmed.StartsWith("license:") && currentFile != null && currentArtist != null)
                        {
                            var fileName = GetFileNameWithoutExtension(currentFile);
                            var title = FormatFileName(fileName);
                            attributions[fileName] = new Attribution
                            {
                                Title = title,
                                Artist = currentArtist
                            };
                            currentFile = null;
                            currentArtist = null;
                        }
                    }
                }
            }
            catch { }
            return attributions;
        }

        private void ScanFolderForMusic(string folderPath, Dictionary<string, Attribution> attributions)
        {
            foreach (var attributionEntry in attributions)
            {
                var fileName = attributionEntry.Key;
                var filePath = $"{folderPath}/{fileName}.ogg";
                if (_resourceManager.ContentFileExists(filePath))
                {
                    var displayName = GetTrackDisplayName(fileName, attributions);
                    _trackPaths.Add(filePath);
                    _trackNames.Add(displayName);
                    TrackList.AddItem(displayName);
                }
            }
        }

        private string GetFileNameWithoutExtension(string filename)
        {
            if (string.IsNullOrEmpty(filename)) return "";
            var lastDotIndex = filename.LastIndexOf('.');
            return lastDotIndex > 0 ? filename.Substring(0, lastDotIndex) : filename;
        }

        private string GetTrackDisplayName(string fileName, Dictionary<string, Attribution> attributions)
        {
            if (attributions.TryGetValue(fileName, out var attribution))
            {
                var title = attribution.Title;
                var artist = attribution.Artist;
                if (!string.IsNullOrEmpty(title) && !string.IsNullOrEmpty(artist))
                    return $"{title} - {artist}";
                else if (!string.IsNullOrEmpty(title))
                    return title;
                else if (!string.IsNullOrEmpty(artist))
                    return artist;
            }
            return FormatFileName(fileName);
        }

        private string FormatFileName(string fileName)
        {
            var formatted = fileName.Replace('_', ' ');
            return TitleCase(formatted);
        }

        private string TitleCase(string input)
        {
            if (string.IsNullOrEmpty(input)) return input;
            var result = new System.Text.StringBuilder();
            bool capitalizeNext = true;
            for (int i = 0; i < input.Length; i++)
            {
                char c = input[i];
                if (char.IsWhiteSpace(c))
                {
                    result.Append(c);
                    capitalizeNext = true;
                }
                else if (capitalizeNext)
                {
                    result.Append(char.ToUpper(c));
                    capitalizeNext = false;
                }
                else
                {
                    result.Append(char.ToLower(c));
                }
            }
            return result.ToString();
        }

        private class Attribution
        {
            public string Title { get; set; } = "";
            public string Artist { get; set; } = "";
        }

        public void UpdateState(MusicPlayerUiState state)
        {
            if (state.CurrentTrack != null)
                NowPlaying.Text = $"Now Playing: {state.CurrentTrack}";

            PlayButton.Disabled = state.IsPlaying;
            PauseButton.Disabled = !state.IsPlaying;

            if (!_isUpdatingSlider)
            {
                VolumeSlider.Value = state.Volume;
                ProgressSlider.MaxValue = state.Duration > 0 ? state.Duration : 1;
                ProgressSlider.Value = state.Duration > 0 ? state.Position : 0;
            }
        }

        public void HandleSeek(float position)
        {
            _isUpdatingSlider = true;
            if (ProgressSlider != null)
                ProgressSlider.Value = position;
            _isUpdatingSlider = false;
        }

        public void UpdateShuffleButton(bool enabled)
        {
            ShuffleButton.Modulate = enabled ? Color.FromHex("#4caf50") : Color.White;
        }
    }
}