using System.Numerics;
using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Content.Shared.Pinpointer;
using Robust.Shared.Map;
using Robust.Shared.Timing;

namespace Content.Client.Pinpointer.UI;

[GenerateTypedNameReferences]
public sealed partial class StationMapWindow : FancyWindow
{
    [Dependency] private IEntityManager _entMan = default!;

    private readonly List<StationMapBeaconControl> _buttons = new();
    #region Starlight
    private EntityUid? _mapOwner;
    private EntityUid? _lastRefreshedMapUid;
    private float _mapUpdateTimer;
    private const float MapUpdateInterval = 0.5f;
    #endregion

    public StationMapWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        FilterBar.OnTextChanged += (bar) => OnFilterChanged(bar.Text);
    }

    // Starlight - start
    public void Set(EntityUid? trackedEntity, EntityUid mapOwner)
    {
        _mapOwner = mapOwner;
        NavMapScreen.Owner = mapOwner;

        if (trackedEntity != null)
            NavMapScreen.TrackedCoordinates.Add(new EntityCoordinates(trackedEntity.Value, Vector2.Zero), (true, Color.Cyan));

        UpdateMap(GetMapToDisplay(mapOwner));
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        _mapUpdateTimer += args.DeltaSeconds;
        if (_mapUpdateTimer >= MapUpdateInterval)
        {
            _mapUpdateTimer -= MapUpdateInterval;

            if (_mapOwner is { } owner)
                NavMapScreen.MapUid = GetMapToDisplay(owner, NavMapScreen.MapUid); // Starlight
        }

        if (_lastRefreshedMapUid != NavMapScreen.MapUid)
            UpdateMapState();
    }

    private EntityUid? GetMapToDisplay(EntityUid owner, EntityUid? previousMapUid = null) // Starlight
    {
        if (!_entMan.TryGetComponent<StationMapComponent>(owner, out var stationMap))
            return null;

        if (stationMap.TargetGrid is { } targetGrid)
            return targetGrid;

        if (stationMap.InitializeWithStation ||
            !_entMan.TryGetComponent<TransformComponent>(owner, out var xform))
        {
            return null;
        }

        return xform.GridUid ?? previousMapUid; // Starlight
    }

    private void UpdateMap(EntityUid? mapUid)
    {
        NavMapScreen.MapUid = mapUid;
        UpdateMapState();
    }

    private void UpdateMapState()
    {
        NavMapScreen.ForceNavMapUpdate();
        var mapUid = NavMapScreen.MapUid;
        _lastRefreshedMapUid = mapUid;

        StationName.Text = _entMan.TryGetComponent<MetaDataComponent>(mapUid, out var mapMetaData)
            ? mapMetaData.EntityName
            : Loc.GetString("station-map-unknown-station");

        UpdateBeaconList(mapUid);
    }
    // Starlight - end

    public void OnFilterChanged(string newFilter)
    {
        foreach (var button in _buttons)
        {
            button.Visible = string.IsNullOrEmpty(newFilter) || (
                !string.IsNullOrEmpty(button.Label) &&
                button.Label.Contains(newFilter, StringComparison.OrdinalIgnoreCase)
            );
        };
    }

    public void UpdateBeaconList(EntityUid? mapUid)
    {
        BeaconButtons.Children.Clear();
        _buttons.Clear();

        if (!mapUid.HasValue)
            return;

        if (!_entMan.TryGetComponent<NavMapComponent>(mapUid, out var navMap))
            return;

        foreach (var beacon in navMap.Beacons.Values)
        {
            var button = new StationMapBeaconControl(mapUid.Value, beacon);

            button.OnPressed += NavMapScreen.CenterToCoordinates;

            _buttons.Add(button);
        }

        _buttons.Sort();

        foreach (var button in _buttons)
            BeaconButtons.AddChild(button);
    }
}
