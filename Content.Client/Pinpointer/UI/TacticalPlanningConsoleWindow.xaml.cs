using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared.Pinpointer;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Pinpointer.UI;

#region Starlight
/// <summary>
/// Owns the console controls and annotation selection; the bound UI owns synchronization.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class TacticalPlanningConsoleWindow : FancyWindow
{
    private readonly List<TacticalPlanAnnotation> _annotations = new();
    private int? _selectedId;
    private bool _planFull;
    private bool _canEdit;

    public event Action<TacticalPlanAnnotationKind, List<Vector2>>? AnnotationAdded;
    public event Action<int>? AnnotationErased;
    public event Action<Color>? ColorSelected;
    public event Action? PlanReset;
    public Color InkColor => NavMapScreen.InkColor;

    public TacticalPlanningConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        PlanningTabs.SetTabTitle(0, Loc.GetString("tactical-planning-console-tools-tab"));
        PlanningTabs.SetTabTitle(1, Loc.GetString("tactical-planning-console-details-tab"));
        NavMapScreen.AnnotationAdded += (kind, points) => AnnotationAdded?.Invoke(kind, points);
        NavMapScreen.AnnotationErased += EraseAt;
        NavMapScreen.AnnotationInspected += SelectAt;

        SelectTool.OnPressed += _ => SetTool(TacticalPlanTool.Select);
        DrawTool.OnPressed += _ => SetTool(TacticalPlanTool.Draw);
        EraseTool.OnPressed += _ => SetTool(TacticalPlanTool.Erase);

        RedInk.OnPressed += _ => ChooseInk(Color.FromHex("#FF0000"));
        BlueInk.OnPressed += _ => ChooseInk(Color.FromHex("#38AEE8"));
        YellowInk.OnPressed += _ => ChooseInk(Color.FromHex("#EFC54A"));
        VioletInk.OnPressed += _ => ChooseInk(Color.FromHex("#AA7CDE"));
        CustomColorPicker.SelectorType = ColorSelectorSliders.ColorSelectorType.Hsv;
        CustomColorPicker.OnColorChanged += color => ChooseInk(color, false);
        LayoutContainer.SetAnchorPreset(CustomColorPicker, LayoutContainer.LayoutPreset.Wide);
        // The slider control has no Disabled property; a transparent blocker prevents
        // color changes until the first authoritative snapshot arrives.
        LayoutContainer.SetAnchorPreset(ColorPickerBlocker, LayoutContainer.LayoutPreset.Wide);
        ColorPickerBlocker.MouseFilter = MouseFilterMode.Stop;
        ResetPlan.OnPressed += _ =>
        {
            if (_canEdit)
                PlanReset?.Invoke();
        };

        SetTool(TacticalPlanTool.Select);
        SetInk(Color.OrangeRed);
    }

    public void Set(string stationName, EntityUid? gridUid)
    {
        StationName.Text = stationName;
        NavMapScreen.MapUid = gridUid;
        NavMapScreen.ForceNavMapUpdate();
    }

    public void SetSyndicatePalette(bool syndicate)
    {
        NavMapScreen.SetSyndicatePalette(syndicate);
    }

    public void SetAnnotations(List<TacticalPlanAnnotation> annotations)
    {
        _annotations.Clear();
        _annotations.AddRange(annotations);
        RefreshAnnotations();
    }

    public void AddAnnotation(TacticalPlanAnnotation annotation)
    {
        if (!_annotations.Exists(existing => existing.Id == annotation.Id))
            _annotations.Add(annotation);
        RefreshAnnotations();
    }

    public void RemoveAnnotation(int id)
    {
        _annotations.RemoveAll(annotation => annotation.Id == id);
        RefreshAnnotations();
    }

    public void SetPlanFull(bool isFull)
    {
        _planFull = isFull;
        ResetPlan.Visible = isFull;
        RefreshAnnotations();
    }

    public void SetConnectionStatus(string? status, bool canEdit)
    {
        ConnectionStatus.Text = status ?? string.Empty;
        ConnectionStatus.Visible = status != null;
        _canEdit = canEdit;
        NavMapScreen.CanEdit = canEdit;
        SetTool(NavMapScreen.Tool);
        RedInk.Disabled = !canEdit;
        BlueInk.Disabled = !canEdit;
        YellowInk.Disabled = !canEdit;
        VioletInk.Disabled = !canEdit;
        CustomColorPicker.Modulate = canEdit ? Color.White : Color.Gray;
        ColorPickerBlocker.Visible = !canEdit;
        ResetPlan.Disabled = !canEdit;
    }

    private void RefreshAnnotations()
    {
        NavMapScreen.SetAnnotations(_annotations);
        AnnotationCount.Text = Loc.GetString(_planFull
                ? "tactical-planning-console-count-full"
                : "tactical-planning-console-count",
            ("count", _annotations.Count));

        if (_selectedId != null)
        {
            var selected = _annotations.Find(annotation => annotation.Id == _selectedId);
            if (selected != null)
                ShowDetails(selected);
            else
                ClearSelection();
        }
    }

    private void SetTool(TacticalPlanTool tool)
    {
        NavMapScreen.Tool = tool;
        SelectTool.Disabled = tool == TacticalPlanTool.Select;
        DrawTool.Disabled = !_canEdit || tool == TacticalPlanTool.Draw;
        EraseTool.Disabled = !_canEdit || tool == TacticalPlanTool.Erase;
    }

    public void SetInk(Color color, bool updatePicker = true)
    {
        NavMapScreen.InkColor = color;
        InkPreview.PanelOverride = new StyleBoxFlat { BackgroundColor = color };
        InkHex.Text = color.ToHex();
        if (updatePicker)
            CustomColorPicker.Color = color;
    }

    private void ChooseInk(Color color, bool updatePicker = true)
    {
        if (!_canEdit)
            return;

        // The picker has already updated itself during a drag; do not reset every slider.
        SetInk(color, updatePicker);
        ColorSelected?.Invoke(color);
    }

    private void SelectAt(Vector2 position)
    {
        var selected = NavMapScreen.FindAnnotation(position);
        if (selected == null)
        {
            ClearSelection();
            return;
        }

        _selectedId = selected.Id;
        NavMapScreen.SelectAnnotation(selected.Id);
        ShowDetails(selected);
        PlanningTabs.CurrentTab = 1;
    }

    private void EraseAt(Vector2 position)
    {
        if (!_canEdit)
            return;

        var selected = NavMapScreen.FindAnnotation(position);
        if (selected != null)
            AnnotationErased?.Invoke(selected.Id);
    }

    private void ShowDetails(TacticalPlanAnnotation annotation)
    {
        var kind = Loc.GetString(annotation.Kind == TacticalPlanAnnotationKind.Dot
            ? "tactical-planning-console-dot"
            : "tactical-planning-console-drawing");
        Details.Text = Loc.GetString("tactical-planning-console-details", ("kind", kind),
            ("author", annotation.Author));
    }

    private void ClearSelection()
    {
        _selectedId = null;
        NavMapScreen.SelectAnnotation(null);
        Details.Text = Loc.GetString("tactical-planning-console-select-hint");
    }
}
#endregion
