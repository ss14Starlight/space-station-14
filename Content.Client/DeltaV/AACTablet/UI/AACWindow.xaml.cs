using System;
using System.Collections.Generic;
using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared.DeltaV.QuickPhrase;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared;
using Robust.Shared.Configuration;
using Robust.Shared.Prototypes;

namespace Content.Client.DeltaV.AACTablet.UI;

[GenerateTypedNameReferences]
public sealed partial class AACWindow : FancyWindow
{
    #region Starlight Fields
    /// <summary>
    /// Fixed width of every phrase button. Rows fill left to right; extra window width adds columns.
    /// </summary>
    private const int ButtonWidth = 180;

    /// <summary>
    /// Space between buttons, both horizontally and vertically.
    /// </summary>
    private const int ButtonSeparation = 6;

    /// <summary>
    /// Margin around each group's button grid.
    /// </summary>
    private const int GridMargin = 10;

    /// <summary>
    /// Width reserved for the scroll bar and tab panel padding when working out how many columns fit.
    /// </summary>
    private const int ScrollbarAllowance = 20;

    private readonly ILocalizationManager _loc;
    private readonly IConfigurationManager _cfg;
    private readonly List<PhraseEntry> _allPhrases = new();
    private readonly List<GridContainer> _buttonGrids = new();

    private readonly List<LocId> _tabKeys = new();
    private LocId? _selectedTab;
    private bool _isRebuildingTabs;

    private string _builtCultureName = string.Empty;

    private string _currentFilter = string.Empty;
    private int _columns = 4;

    /// <summary>
    /// A phrase together with its localized labels, so searching and rendering use the exact same strings.
    /// </summary>
    private sealed record PhraseEntry(QuickPhrasePrototype Prototype, string Text, string Group, string Tab);

    #endregion

    private readonly IPrototypeManager _prototypeManager;
    public event Action<string>? PhraseButtonPressed;

    public AACWindow(AACBoundUserInterface ui, IPrototypeManager prototypeManager)
    {
        RobustXamlLoader.Load(this);
        _prototypeManager = prototypeManager;

        //Starlight-start: AAC search bar edit.
        WindowBody.OnTabChanged += OnTabChanged;

        _loc = IoCManager.Resolve<ILocalizationManager>();
        _cfg = IoCManager.Resolve<IConfigurationManager>();

        RefreshPhraseLabels();

        SearchBar.OnTextChanged += OnSearchTextChanged;
        SearchBar.OnTextEntered += _ => SearchBar.ReleaseKeyboardFocus();

        // Build all tabs initially
        RebuildTabs();
        //Starlight-end
    }

    #region Starlight
    protected override void Resized()
    {
        base.Resized();

        var columns = CalculateColumns();
        if (columns == _columns)
            return;

        _columns = columns;
        foreach (var grid in _buttonGrids)
        {
            grid.Columns = _columns;
        }
    }

    private void OnLanguageChanged(string _)
    {
        RefreshPhraseLabels();
        RebuildTabs();
    }

    private void RefreshPhraseLabels()
    {
        _allPhrases.Clear();
        _allPhrases.AddRange(
            _prototypeManager.EnumeratePrototypes<QuickPhrasePrototype>()
                .Select(p => new PhraseEntry(
                    p,
                    _loc.GetString(p.Text),
                    _loc.GetString(p.Group),
                    _loc.GetString(p.Tab)))
                .ToList());
        
        _builtCultureName = _cfg.GetCVar(CVars.LocCultureName); //Set the language being used
    }

    /// <summary>
    /// Works out how many fixed-width buttons fit side by side in the current tab area.
    /// </summary>
    private int CalculateColumns()
    {
        var available = WindowBody.Width - ScrollbarAllowance - (GridMargin * 2);
        var columns = (int) ((available + ButtonSeparation) / (ButtonWidth + ButtonSeparation));
        return Math.Max(1, columns);
    }

    private void OnSearchTextChanged(LineEdit.LineEditEventArgs obj)
    {
        _currentFilter = obj.Text ?? string.Empty;
        RebuildTabs();
    }

    private void OnTabChanged(int index)
    {
        if (_isRebuildingTabs)
            return;

        if (index >= 0 && index < _tabKeys.Count)
            _selectedTab = _tabKeys[index];
    }

    private void RebuildTabs()
    {
        _isRebuildingTabs = true;
        try // Swap to try/finally block so I don't have to remember to set _rebuildingTabs to false when returning
        {
            if (WindowBody.ChildCount > 0)
                WindowBody.CurrentTab = 0; // Reset while the old children still exist.
            WindowBody.RemoveAllChildren(); // Yeet.
            _buttonGrids.Clear();
            _tabKeys.Clear();

            var query = _currentFilter.Trim();
            var isFiltering = query.Length > 0;

            var filtered = isFiltering
                ? _allPhrases.Where(p =>
                        p.Text.Contains(query, StringComparison.CurrentCultureIgnoreCase)
                        || p.Group.Contains(query, StringComparison.CurrentCultureIgnoreCase)
                        || p.Tab.Contains(query, StringComparison.CurrentCultureIgnoreCase))
                    .ToList()
                : _allPhrases;

            if (filtered.Count == 0)
            {
                AddEmptyResultsTab(query);
                return;
            }

            var tabs = filtered
                .GroupBy(p => p.Prototype.Tab)
                .OrderBy(t => t.First().Tab, StringComparer.CurrentCulture);

            foreach (var tab in tabs)
            {
                _tabKeys.Add(tab.Key);

                var groups = tab
                    .GroupBy(p => p.Prototype.Group.Id)
                    .OrderBy(g => g.Min(p => p.Prototype.GroupOrder))
                    .ThenBy(g => g.First().Group, StringComparer.CurrentCulture);

                var scroll = new ScrollContainer
                {
                    HScrollEnabled = false,
                    VerticalExpand = true,
                    HorizontalExpand = true,
                    MouseFilter = MouseFilterMode.Pass
                };
                scroll.AddChild(CreateBoxContainerForTab(groups));
                WindowBody.AddChild(scroll);
                WindowBody.SetTabTitle(WindowBody.ChildCount - 1, tab.First().Tab);
            }

            if (isFiltering)
            {
                // Auto-select the first tab when you're filtering
                WindowBody.CurrentTab = 0;
                return;
            }

            // Restore the tab you had selected if you aren't filtering anymore
            if (_selectedTab is { } selected
                && _tabKeys.IndexOf(selected) is var index and >= 0)
            {
                WindowBody.CurrentTab = index;
            }
            else
            {
                WindowBody.CurrentTab = 0;
            }
        }
        finally
        {
            _isRebuildingTabs = false;
        }
    }

    private void AddEmptyResultsTab(string query)
    {
        var emptyLabel = new Label
        {
            Text = Loc.GetString("aac-window-search-no-results", ("query", query)),
            HorizontalAlignment = HAlignment.Center,
            Margin = new Thickness(10, 20)
        };

        var emptyBox = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            VerticalExpand = true,
            HorizontalExpand = true
        };
        emptyBox.AddChild(emptyLabel);

        var emptyScroll = new ScrollContainer { HorizontalExpand = true, VerticalExpand = true };
        emptyScroll.AddChild(emptyBox);
        WindowBody.AddChild(emptyScroll);
        WindowBody.SetTabTitle(0, Loc.GetString("aac-window-search-tab"));
    }

    protected override void Dispose(bool disposing)
    {
        if (disposing)
        {   
            WindowBody.OnTabChanged -= OnTabChanged;
        }

        base.Dispose(disposing);
    }

    protected override void Opened()
    {
        base.Opened();

        _cfg.OnValueChanged(CVars.LocCultureName, OnLanguageChanged); //Subscribe to language changes when the window opens

        if (_builtCultureName != _cfg.GetCVar(CVars.LocCultureName))
        { //Check against the last culture we built with, and rebuild if the language has changed
            RefreshPhraseLabels();
            RebuildTabs();
        }
    }

    protected override void ExitedTree()
    {
        _cfg.UnsubValueChanged(CVars.LocCultureName, OnLanguageChanged); //Stop listening to language changes when the window is closed/is no longer in the tree
        base.ExitedTree();
    }

    #endregion

    //Starlight: Use IEnumerable group of string to PhraseEntry for localization
    private BoxContainer CreateBoxContainerForTab(IEnumerable<IGrouping<string, PhraseEntry>> groups)
    {
        var boxContainer = new BoxContainer
        {
            HorizontalExpand = true,
            MouseFilter = MouseFilterMode.Pass, //Starlight: Ignore mouse filter for window resize
            Orientation = BoxContainer.LayoutOrientation.Vertical
        };

        foreach (var group in groups)
        {
            //Starlight-start: Create localized header here, then pass off to CreateButtonContainerForGroup
            var header = new Label
            {
                Text = group.First().Group,
                Margin = new Thickness(GridMargin, GridMargin, GridMargin, 0),
                StyleClasses = { "LabelBig" }
            };

            boxContainer.AddChild(header);
            boxContainer.AddChild(CreateButtonContainerForGroup(group));
            //Starlight-end
        }

        return boxContainer;
    }

    //Starlight: Switch List<QuickPhrasePrototype> to IEnumerable<PhraseEntry> for localizing phrases
    private GridContainer CreateButtonContainerForGroup(IEnumerable<PhraseEntry> phrases)
    {
        //Starlight-start: Dynamically size the GridContainer based on number of rows
        var buttonContainer = new GridContainer
        {
            Margin = new Thickness(GridMargin),
            HorizontalAlignment = HAlignment.Left,
            MouseFilter = MouseFilterMode.Pass, //Don't let it eat the mouse so that resizing mouse stuff renders properly
            HSeparationOverride = ButtonSeparation,
            VSeparationOverride = ButtonSeparation,
            Columns = _columns
        };

        foreach (var phrase in phrases.OrderBy(p => p.Text, StringComparer.CurrentCulture))
        {
            var button = CreatePhraseButton(phrase.Text, phrase.Prototype.StyleClass);
            var id = phrase.Prototype.ID;
            button.OnPressed += _ => OnPhraseButtonPressed(id);
            buttonContainer.AddChild(button);
        }

        _buttonGrids.Add(buttonContainer); //Store which grids we've made for use later
        //Starlight-end
        return buttonContainer;
    }

    private static Button CreatePhraseButton(string text, string styleClass)
    {
        //Starlight-start: Remove GetButtonWidth(), set MinWidth and MaxWidth, then VerticalExpand the buttons
        var phraseButton = new Button
        {
            Access = AccessLevel.Public,
            MinWidth = ButtonWidth,
            MaxWidth = ButtonWidth,
            ClipText = false,
            // Fill the row height so every button in a row lines up, even if one wraps to more lines.
            VerticalExpand = true,
            //Starlight-end
            StyleClasses = { styleClass }
        };

        var buttonLabel = new RichTextLabel
        {
            Margin = new Thickness(0, 5),
            HorizontalAlignment = HAlignment.Center, //Starlight: Center the text so low character length buttons look nice
            StyleClasses = { "WhiteText" }
        };

        buttonLabel.SetMessage(text);
        phraseButton.AddChild(buttonLabel);
        return phraseButton;
    }

    private void OnPhraseButtonPressed(string phraseId)
    {
        PhraseButtonPressed?.Invoke(phraseId);
    }

    //Starlight: Removed PopulateGui(), GetButtonWidth(), and CreateButtonContainer() methods as they are not needed in this implementation
}
