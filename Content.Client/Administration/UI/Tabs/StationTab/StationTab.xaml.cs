using System.Linq;
using Content.Client.Administration.Systems;
using Content.Shared._Nix.Administration;
using Content.Shared._Starlight.SecureTerminal;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.Administration.UI.Tabs.StationTab;

[GenerateTypedNameReferences]
public sealed partial class StationTab : Control
{
    private static readonly string[] AlertOrder =
    [
        "green", "blue", "yellow", "orange", "violet", "red",
        "gamma", "psi", "delta", "epsilon", "omega", "theta"
    ];

    private static readonly HashSet<string> OperationalAlerts =
    [
        "green", "blue", "yellow", "orange", "violet", "red"
    ];

    [Dependency] private IEntityManager _entityManager = default!;
    [Dependency] private IPrototypeManager _prototypes = default!;

    private readonly AdminSystem _adminSystem;
    private NixAdminStationAlertData? _station;
    private List<NixAdminAlertLevelData> _alerts = new();
    private readonly List<SecureCommandTerminalRequestPrototype> _secureActions;
    private NixAdminAlertLevelData? _selectedAlert;
    private SecureCommandTerminalRequestPrototype? _selectedSecureAction;

    public StationTab()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        _adminSystem = _entityManager.System<AdminSystem>();
        _adminSystem.NixAdminAlertSnapshot += OnSnapshot;
        _adminSystem.NixAdminAlertResult += OnResult;
        _adminSystem.NixAdminSecureActionResult += OnSecureActionResult;

        AlertOption.OnItemSelected += args =>
        {
            AlertOption.SelectId(args.Id);
            SelectAlert(args.Id);
        };
        SecureActionOption.OnItemSelected += args =>
        {
            SecureActionOption.SelectId(args.Id);
            SelectSecureAction(args.Id);
        };
        ConfirmSecureCheckBox.OnToggled += _ => UpdateSecureButton();
        RefreshButton.OnPressed += _ => RequestSnapshot();
        ApplyButton.OnPressed += _ => ApplyAlert();
        ExecuteSecureButton.OnPressed += _ => ExecuteSecureAction();
        ApplyButton.Disabled = true;

        _secureActions = _prototypes.EnumeratePrototypes<SecureCommandTerminalRequestPrototype>()
            .OrderBy(action => action.SortOrder)
            .ThenBy(action => Loc.GetString(action.Name))
            .ToList();
        PopulateSecureActions();

        RequestSnapshot();
    }

    private void RequestSnapshot()
    {
        StatusLabel.Text = Loc.GetString("administration-ui-station-tab-loading");
        _adminSystem.RequestNixAdminAlerts();
    }

    private void OnSnapshot(NixAdminAlertSnapshotEvent snapshot)
    {
        _station = snapshot.Stations.FirstOrDefault();
        if (_station == null)
        {
            CurrentAlertLabel.Text = Loc.GetString("administration-ui-station-tab-no-stations");
            AlertOption.Clear();
            ApplyButton.Disabled = true;
            return;
        }

        PopulateAlerts();
        StatusLabel.Text = string.Empty;
    }

    private void PopulateAlerts()
    {
        AlertOption.Clear();
        _selectedAlert = null;
        ApplyButton.Disabled = true;
        AlertDescriptionLabel.Text = Loc.GetString("administration-ui-station-tab-select-alert");

        if (_station == null)
            return;

        LockAlertCheckBox.Pressed = _station.Locked;
        CurrentAlertLabel.Text = Loc.GetString("administration-ui-station-tab-current",
            ("level", LocalizedAlertName(_station.CurrentLevel)),
            ("id", _station.CurrentLevel.ToUpperInvariant()));

        _alerts = _station.Levels.OrderBy(level => AlertSortIndex(level.Id)).ToList();
        foreach (var alert in _alerts)
        {
            var category = OperationalAlerts.Contains(alert.Id)
                ? Loc.GetString("administration-ui-station-tab-category-operational")
                : Loc.GetString("administration-ui-station-tab-category-special");
            AlertOption.AddItem($"[{category}] {LocalizedAlertName(alert.Id)} ({alert.Id.ToUpperInvariant()})");
        }
    }

    private void SelectAlert(int index)
    {
        _selectedAlert = index >= 0 && index < _alerts.Count ? _alerts[index] : null;
        ApplyButton.Disabled = _selectedAlert == null;
        if (_selectedAlert == null)
            return;

        var announcementId = $"alert-level-{_selectedAlert.Id}-announcement";
        AlertDescriptionLabel.Text = Loc.TryGetString(announcementId, out var announcement)
            ? announcement
            : Loc.GetString("administration-ui-station-tab-no-description");
    }

    private void ApplyAlert()
    {
        if (_station == null || _selectedAlert == null)
            return;

        ApplyButton.Disabled = true;
        StatusLabel.Text = Loc.GetString("administration-ui-station-tab-applying");
        _adminSystem.SendNixAdminAlertCommand(_station.Station, _selectedAlert.Id, LockAlertCheckBox.Pressed);
    }

    private void OnResult(NixAdminAlertResultEvent result)
    {
        StatusLabel.Text = result.Success
            ? Loc.GetString("administration-ui-station-tab-success",
                ("level", LocalizedAlertName(result.Level)))
            : Loc.GetString("administration-ui-station-tab-failed");
        ApplyButton.Disabled = _selectedAlert == null;
    }

    private void PopulateSecureActions()
    {
        SecureActionOption.Clear();
        foreach (var action in _secureActions)
            SecureActionOption.AddItem(Loc.GetString(action.Name));
        UpdateSecureButton();
    }

    private void SelectSecureAction(int index)
    {
        _selectedSecureAction = index >= 0 && index < _secureActions.Count ? _secureActions[index] : null;
        ConfirmSecureCheckBox.Pressed = false;
        SecureDescriptionLabel.Text = _selectedSecureAction == null
            ? Loc.GetString("administration-ui-station-tab-secure-select")
            : Loc.GetString(_selectedSecureAction.Description);
        UpdateSecureButton();
    }

    private void ExecuteSecureAction()
    {
        if (_selectedSecureAction == null || !ConfirmSecureCheckBox.Pressed)
            return;

        ExecuteSecureButton.Disabled = true;
        StatusLabel.Text = Loc.GetString("administration-ui-station-tab-secure-executing");
        _adminSystem.SendNixAdminSecureAction(_selectedSecureAction.ID);
    }

    private void OnSecureActionResult(NixAdminSecureActionResultEvent result)
    {
        StatusLabel.Text = Loc.GetString(result.Success
            ? "administration-ui-station-tab-secure-success"
            : "administration-ui-station-tab-secure-failed");
        ConfirmSecureCheckBox.Pressed = false;
        UpdateSecureButton();
    }

    private void UpdateSecureButton()
    {
        ExecuteSecureButton.Disabled = _selectedSecureAction == null || !ConfirmSecureCheckBox.Pressed;
    }

    private static int AlertSortIndex(string id)
    {
        var index = Array.IndexOf(AlertOrder, id);
        return index < 0 ? int.MaxValue : index;
    }

    private static string LocalizedAlertName(string id)
    {
        return Loc.TryGetString($"alert-level-{id}", out var name) ? name : id;
    }

    protected override void Dispose(bool disposing)
    {
        _adminSystem.NixAdminAlertSnapshot -= OnSnapshot;
        _adminSystem.NixAdminAlertResult -= OnResult;
        _adminSystem.NixAdminSecureActionResult -= OnSecureActionResult;
        base.Dispose(disposing);
    }
}
