using Robust.Shared.Utility;

namespace Content.Client.Administration.UI.Tabs.AdminAudioTab;

[GenerateTypedNameReferences]
public sealed partial class AdminAudioTab : Control
{
    private const int MaximumDisplayedResults = 500;

    [Dependency] private IEntityManager _entityManager = default!;
    [Dependency] private IConfigurationManager _configuration = default!;
    [Dependency] private IFileDialogManager _fileDialogs = default!;
    [Dependency] private IResourceManager _resources = default!;
    [Dependency] private IClientNetManager _network = default!;
    [Dependency] private ITransferManager _transferManager = default!;

    private readonly AdminSystem _adminSystem;
    private readonly List<string> _audioPaths;
    private string? _selectedPath;
    private string? _pendingUploadPath;
    private ResPath _pendingUploadRelative;
    private byte[]? _pendingUploadData;
    private string? _preparedUploadPath;
    private bool _uploadInProgress;

    public AdminAudioTab()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        _adminSystem = _entityManager.System<AdminSystem>();
        _audioPaths = _resources.ContentFindFiles("/Audio/")
            .Select(path => path.ToString())
            .Where(path => path.EndsWith(".ogg", StringComparison.OrdinalIgnoreCase) ||
                           path.EndsWith(".wav", StringComparison.OrdinalIgnoreCase))
            .Where(IsCuratedAudioPath)
            .Distinct()
            .OrderBy(path => path.ToLowerInvariant())
            .ToList();

        VolumeSlider.MinValue = 0;
        VolumeSlider.MaxValue = 100;
        VolumeSlider.Value = 100;

        SearchLineEdit.OnTextChanged += _ => PopulateAudioList();
        VolumeSlider.OnValueChanged += slider =>
            VolumeValueLabel.Text = $"{MathF.Round(slider.Value)}%";
        PlayButton.OnPressed += _ => PlaySelected();
        StopAllButton.OnPressed += _ => StopAll();
        SelectLocalButton.OnPressed += _ => SelectLocalAudio();
        PrepareLocalButton.OnPressed += _ => PrepareLocalAudio();
        PlayLocalButton.OnPressed += _ => PlayPreparedAudio();
        _adminSystem.NixAdminAudioResult += OnAudioResult;

        PopulateAudioList();
        UpdatePlayButton();
        UpdateLocalButtons();
    }

    private void PopulateAudioList()
    {
        AudioCategories.RemoveAllChildren();
        _selectedPath = null;
        SelectedPathLabel.Text = Loc.GetString("administration-ui-audio-tab-no-selection");

        var filter = SearchLineEdit.Text.Trim();
        var matches = _audioPaths
            .Where(path => string.IsNullOrEmpty(filter) ||
                           path.Contains(filter, StringComparison.OrdinalIgnoreCase))
            .ToList();

        foreach (var group in matches.Take(MaximumDisplayedResults).GroupBy(AudioCategory))
        {
            var entries = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                HorizontalExpand = true,
                Margin = new Thickness(12, 2, 0, 4)
            };

            foreach (var path in group)
            {
                var button = new Button
                {
                    Text = path["/Audio/".Length..],
                    HorizontalExpand = true,
                    TextAlign = Label.AlignMode.Left
                };
                button.OnPressed += _ => SelectPackagedAudio(path);
                entries.AddChild(button);
            }

            var body = new CollapsibleBody { HorizontalExpand = true };
            body.AddChild(entries);
            AudioCategories.AddChild(new Collapsible(
                Loc.GetString($"administration-ui-audio-tab-category-{group.Key}"),
                body)
            {
                HorizontalExpand = true,
                BodyVisible = !string.IsNullOrEmpty(filter)
            });
        }

        ResultsLabel.Text = Loc.GetString("administration-ui-audio-tab-results",
            ("shown", Math.Min(matches.Count, MaximumDisplayedResults)),
            ("total", matches.Count));
        UpdatePlayButton();
    }

    private void SelectPackagedAudio(string path)
    {
        _selectedPath = path;
        SelectedPathLabel.Text = path;
        UpdatePlayButton();
    }

    private void PlaySelected()
    {
        if (_selectedPath == null)
            return;

        var volume = (byte) Math.Clamp((int) MathF.Round(VolumeSlider.Value), 0, 100);
        _adminSystem.SendNixAdminAudioCommand(NixAdminAudioAction.Play, _selectedPath, volume);
        StatusLabel.Text = Loc.GetString("administration-ui-audio-tab-status-requesting");
    }

    private void StopAll()
    {
        _adminSystem.SendNixAdminAudioCommand(NixAdminAudioAction.StopAll);
        StatusLabel.Text = Loc.GetString("administration-ui-audio-tab-status-requesting");
    }

    private async void SelectLocalAudio()
    {
        if (_uploadInProgress)
            return;

        var filters = new FileDialogFilters(new FileDialogFilters.Group("ogg", "wav", "mp3"));
        var (file, name) = await _fileDialogs.GetFileAndName(filters, FileAccess.Read);
        await using var selectedFile = file;
        if (selectedFile == null || name == null)
            return;

        var extensionIndex = name.LastIndexOf('.');
        var extension = extensionIndex >= 0 ? name[extensionIndex..].ToLowerInvariant() : string.Empty;
        if (extension is not ".ogg" and not ".wav" and not ".mp3")
        {
            StatusLabel.Text = Loc.GetString("administration-ui-audio-tab-upload-format-error");
            return;
        }

        var limitMb = _configuration.GetCVar(CVars.ResourceUploadingLimitMb);
        if (limitMb > 0f && selectedFile.Length * SharedNetworkResourceManager.BytesToMegabytes > limitMb)
        {
            StatusLabel.Text = Loc.GetString("administration-ui-audio-tab-upload-too-large", ("limit", limitMb));
            return;
        }

        _pendingUploadRelative = new ResPath($"Audio/_Nix/AdminUploads/{Guid.NewGuid():N}{extension}");
        _pendingUploadPath = $"/Uploaded/{_pendingUploadRelative}";
        _pendingUploadData = selectedFile.CopyToArray();
        _preparedUploadPath = null;
        var separatorIndex = Math.Max(name.LastIndexOf('/'), name.LastIndexOf('\\'));
        UploadFileLabel.Text = separatorIndex >= 0 ? name[(separatorIndex + 1)..] : name;
        StatusLabel.Text = Loc.GetString("administration-ui-audio-tab-local-selected");
        UpdateLocalButtons();
    }

    private void PrepareLocalAudio()
    {
        if (_uploadInProgress || _pendingUploadPath == null || _pendingUploadData == null)
            return;

        if (!_configuration.GetCVar(CVars.ResourceUploadingEnabled))
        {
            StatusLabel.Text = Loc.GetString("administration-ui-audio-tab-upload-disabled");
            return;
        }

        _uploadInProgress = true;
        UpdateLocalButtons();
        StatusLabel.Text = Loc.GetString("administration-ui-audio-tab-upload-preparing");
        _adminSystem.SendNixAdminAudioCommand(
            NixAdminAudioAction.PrepareUpload,
            _pendingUploadPath);
    }

    private void PlayPreparedAudio()
    {
        if (_preparedUploadPath == null)
            return;

        var volume = (byte) Math.Clamp((int) MathF.Round(VolumeSlider.Value), 0, 100);
        _adminSystem.SendNixAdminAudioCommand(NixAdminAudioAction.Play, _preparedUploadPath, volume);
        StatusLabel.Text = Loc.GetString("administration-ui-audio-tab-status-requesting");
    }

    private void OnAudioResult(NixAdminAudioResultEvent result)
    {
        switch (result.Result)
        {
            case NixAdminAudioResult.UploadReady when result.Path == _pendingUploadPath && _pendingUploadData != null:
                var data = _pendingUploadData;
                var relative = _pendingUploadRelative;
                StatusLabel.Text = Loc.GetString("administration-ui-audio-tab-upload-distributing");
                UploadRuntimeResource(relative, data);
                break;
            case NixAdminAudioResult.Playing:
                StatusLabel.Text = Loc.GetString("administration-ui-audio-tab-status-playing",
                    ("file", DisplayPath(result.Path)),
                    ("volume", result.VolumePercent));
                break;
            case NixAdminAudioResult.Prepared:
                _preparedUploadPath = result.Path;
                _uploadInProgress = false;
                StatusLabel.Text = Loc.GetString("administration-ui-audio-tab-upload-prepared");
                UpdateLocalButtons();
                break;
            case NixAdminAudioResult.Stopped:
                StatusLabel.Text = Loc.GetString("administration-ui-audio-tab-status-stopped");
                break;
            case NixAdminAudioResult.InvalidPath:
                StatusLabel.Text = Loc.GetString("administration-ui-audio-tab-status-invalid-path");
                FailUploadIfNeeded(result.Path);
                break;
            case NixAdminAudioResult.UploadRejected:
                StatusLabel.Text = Loc.GetString("administration-ui-audio-tab-upload-rejected");
                FailUploadIfNeeded(result.Path);
                break;
        }
    }

    private void FailUploadIfNeeded(string path)
    {
        if (path != _pendingUploadPath)
            return;

        _uploadInProgress = false;
        UpdateLocalButtons();
    }

    private async void UploadRuntimeResource(ResPath relative, byte[] data)
    {
        try
        {
            if (_network.ServerChannel is not { } channel)
                throw new InvalidOperationException("Not connected to a server.");

            await using var transfer = _transferManager.StartTransfer(channel, new TransferStartInfo
            {
                MessageKey = "TransferKeyNetworkUpload"
            });

            var pathBytes = Encoding.UTF8.GetBytes(relative.CanonPath);
            var lengthBytes = new byte[4];

            BinaryPrimitives.WriteUInt32LittleEndian(lengthBytes, (uint) pathBytes.Length);
            await transfer.WriteAsync(lengthBytes);

            BinaryPrimitives.WriteUInt32LittleEndian(lengthBytes, (uint) data.Length);
            await transfer.WriteAsync(lengthBytes);
            await transfer.WriteAsync(pathBytes);
            await transfer.WriteAsync(data);
            await transfer.WriteAsync(new byte[] { 0 });
        }
        catch (Exception)
        {
            StatusLabel.Text = Loc.GetString("administration-ui-audio-tab-upload-api-error");
            _uploadInProgress = false;
            UpdateLocalButtons();
        }
    }

    private static string DisplayPath(string path)
    {
        return path.StartsWith("/Uploaded/Audio/_Nix/AdminUploads/", StringComparison.Ordinal)
            ? Loc.GetString("administration-ui-audio-tab-local-file")
            : path;
    }

    private static string AudioCategory(string path)
    {
        if (path.Contains("/Announcements/", StringComparison.OrdinalIgnoreCase))
            return "announcements";
        if (path.Contains("/Ambience/", StringComparison.OrdinalIgnoreCase))
            return "ambience";
        if (path.Contains("/StationEvents/", StringComparison.OrdinalIgnoreCase))
            return "station-events";
        if (path.Contains("/Effects/", StringComparison.OrdinalIgnoreCase))
            return "effects";
        return "misc";
    }

    private static bool IsCuratedAudioPath(string path)
    {
        return path.Contains("/Announcements/", StringComparison.OrdinalIgnoreCase) ||
               path.Contains("/Ambience/", StringComparison.OrdinalIgnoreCase) ||
               path.Contains("/Effects/", StringComparison.OrdinalIgnoreCase) ||
               path.Contains("/StationEvents/", StringComparison.OrdinalIgnoreCase) ||
               path.StartsWith("/Audio/Misc/", StringComparison.OrdinalIgnoreCase) ||
               path.StartsWith("/Audio/_Starlight/Misc/", StringComparison.OrdinalIgnoreCase);
    }

    private void UpdatePlayButton()
    {
        PlayButton.Disabled = _selectedPath == null;
    }

    private void UpdateLocalButtons()
    {
        SelectLocalButton.Disabled = _uploadInProgress;
        PrepareLocalButton.Disabled = _uploadInProgress || _pendingUploadData == null;
        PlayLocalButton.Disabled = _uploadInProgress || _preparedUploadPath == null;
    }

    protected override void Dispose(bool disposing)
    {
        _adminSystem.NixAdminAudioResult -= OnAudioResult;
        base.Dispose(disposing);
    }
}
