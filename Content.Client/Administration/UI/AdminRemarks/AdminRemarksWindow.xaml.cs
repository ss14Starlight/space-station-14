using System.Linq;
using Content.Client.Administration.UI.Notes;
using Content.Client.UserInterface.Controls;
using Content.Shared.Administration.Notes;
using Content.Shared.Database;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Administration.UI.AdminRemarks;

[GenerateTypedNameReferences]
public sealed partial class AdminRemarksWindow : FancyWindow
{
    [Dependency] private IEntitySystemManager _entitySystem = default!;
    private readonly SpriteSystem _sprites;
    private readonly Dictionary<(int, NoteType), Control> _inputs = new(); // Starlight-edit: the card holding the line

    public AdminRemarksWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _sprites = _entitySystem.GetEntitySystem<SpriteSystem>();
    }

    public void SetNotes(Dictionary<(int, NoteType), SharedAdminNote> notes)
    {
        foreach (var (id, input) in _inputs)
        {
            if (notes.ContainsKey(id))
                continue;
            NotesContainer.RemoveChild(input);
            _inputs.Remove(id);
        }

        foreach (var note in notes.Values.OrderByDescending(note => note.CreatedAt))
        {
            // Starlight-start: each line on a card
            if (_inputs.TryGetValue((note.Id, note.NoteType), out var card))
            {
                foreach (var child in card.Children)
                {
                    if (child is AdminNotesLine line)
                        line.UpdateNote(note);
                }
                continue;
            }

            card = new PanelContainer
            {
                StyleClasses = { "TraitsEntryPanel" },
                Children = { new AdminNotesLine(_sprites, note) { Margin = new Thickness(8, 6) } },
            };
            NotesContainer.AddChild(card);
            _inputs[(note.Id, note.NoteType)] = card;
            // Starlight-end
        }

        // Starlight-start: an empty window says so instead of being a blank box
        EmptyLabel.Visible = _inputs.Count == 0;
        NotesScroll.Visible = _inputs.Count > 0;
        CountLabel.Text = _inputs.Count > 0 ? _inputs.Count.ToString() : string.Empty;
        // Starlight-end
    }
}
