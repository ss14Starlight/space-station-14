using Content.Client._Starlight.UserInterface;
using Content.Client.UserInterface.Systems.Bwoink;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Administration.UI.Bwoink
{
    /// <summary>
    /// This window connects to a BwoinkSystem channel. BwoinkSystem manages the rest.
    /// </summary>
    [GenerateTypedNameReferences]
    public sealed partial class BwoinkWindow : DefaultWindow
    {
        public BwoinkWindow()
        {
            RobustXamlLoader.Load(this);
            AddPopOutButton(); // Starlight

            OnOpen += () =>
            {
                Bwoink.ChannelSelector.StopFiltering();
                Bwoink.PopulateList();
            };
        }

        #region Starlight
        private void AddPopOutButton()
        {
            if (CloseButton.Parent is not { } header)
                return;

            var button = new TextureButton
            {
                StyleClasses = { PopOutExtensions.PopOutButtonStyleClass },
                VerticalAlignment = VAlignment.Center,
                ToolTip = Loc.GetString("ui-pop-out"),
                Margin = new Thickness(0, 0, 6, 0),
            };
            header.AddChild(button);
            button.SetPositionInParent(header.ChildCount - 2);
            button.OnPressed += _ => IoCManager.Resolve<IUserInterfaceManager>().GetUIController<AHelpUIController>().PopOut();
        }
        #endregion
    }
}
