using System.Linq;
using Content.Shared.Preferences;
using Content.Shared.Roles;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Player;
using Robust.Shared.Prototypes;

namespace Content.Client.Lobby.UI;

/// <summary>
/// A panel that shows a preview of the selected character in the lobby, including their name, job, and sprite.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class LobbyCharacterPreviewPanel : Control
{
    [Dependency] private IClientPreferencesManager _preferences = default!;
    [Dependency] private IPrototypeManager _prototypeManager = default!;
    [Dependency] private ISharedPlayerManager _playerManager = default!;

    /// <summary>
    /// <see cref="LobbyState"/> needs to register events on this button, so provide a property to access it publicly.
    /// </summary>
    public Button CharacterSetupButton => CharacterSetup;

    #region Starlight
    private bool _previewInitialized;
    #endregion

    public LobbyCharacterPreviewPanel()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        JobPriorities.OnPressed += _ => UserInterfaceManager.GetUIController<LobbyUIController>().OpenJobPrioritiesWindow(); // Starlight-edit
    }

    public void SetLoaded(bool value)
    {
        Loaded.Visible = value;
        Unloaded.Visible = !value;
    }

    #region Starlight

    /// <summary>
    /// Refresh the selected character summary
    /// </summary>
    public void Refresh()
    {
        if (_preferences.Preferences is not { } prefs)
            return;

        // Not in the constructor: UI screens are built at startup, before entity systems exist.
        if (!_previewInitialized)
        {
            ProfilePreviewSpriteView.Initialize(_preferences, _prototypeManager, _playerManager);
            _previewInitialized = true;
        }

        JobPrototype? highJob = null;
        HumanoidCharacterProfile? profile = null;

        var high = prefs.JobPriorities.FirstOrDefault(p => p.Value == JobPriority.High).Key;
        if (high != default && _prototypeManager.TryIndex(high, out highJob))
            profile = prefs.GetAllEnabledProfilesForJob(high).Values.FirstOrDefault();

        // Then the first enabled character, then any: the card should show someone if there is anyone.
        var characters = prefs.Characters.Values.OfType<HumanoidCharacterProfile>().ToList();
        profile ??= characters.FirstOrDefault(p => p.Enabled) ?? characters.FirstOrDefault();

        if (profile == null)
        {
            ProfilePreviewSpriteView.ClearPreview();
            CharacterName.Text = Loc.GetString("lobby-character-preview-panel-no-character");
            CharacterJob.Text = string.Empty;
            return;
        }

        ProfilePreviewSpriteView.LoadPreview(profile, highJob);
        CharacterName.Text = profile.Name;
        CharacterJob.Text = highJob != null
            ? Loc.GetString("lobby-character-preview-panel-high-job", ("job", highJob.LocalizedName))
            : Loc.GetString("lobby-character-preview-panel-no-high-job");
    }

    #endregion
}
