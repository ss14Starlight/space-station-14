using System.Linq;
using System.Numerics;
using Content.Client._Starlight.Stylesheets;
using Content.Client.Stylesheets;
using Content.Client.UserInterface.Controls;
using Content.Shared._Starlight.StationGoals;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._Starlight.StationGoals;

[GenerateTypedNameReferences]
public sealed partial class StationGoalConsoleWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _proto = default!;
    [Dependency] private IGameTiming _timing = default!;
    [Dependency] private IEntityManager _entMan = default!;

    public event Action? OnStartVote;
    public event Action<ProtoId<StationGoalPrototype>>? OnVote;
    public event Action? OnPrint;

    private StationGoalConsoleState? _state;
    private readonly List<(Label Label, TimeSpan Deadline)> _deadlineLabels = new();

    public StationGoalConsoleWindow()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        StartVoteButton.OnPressed += _ => OnStartVote?.Invoke();
        PrintButton.OnPressed += _ => OnPrint?.Invoke();
    }

    public void UpdateState(StationGoalConsoleState state)
    {
        _state = state;
        _deadlineLabels.Clear();

        ActiveCountLabel.Text = Loc.GetString("station-goal-console-active-count", ("count", state.Active.Count), ("max", state.MaxActive));

        ActiveContainer.RemoveAllChildren();
        ActiveContainer.Columns = Math.Max(1, state.MaxActive);
        foreach (var active in state.Active)
        {
            if (_proto.TryIndex(active.Goal, out var goal))
                ActiveContainer.AddChild(BuildActiveCard(goal, active));
        }

        for (var i = state.Active.Count; i < Math.Max(1, state.MaxActive); i++)
        {
            ActiveContainer.AddChild(EmptySlot(Loc.GetString(state.HasStation
                ? "station-goal-console-free-slot"
                : "station-goal-console-no-station")));
        }

        OffersContainer.RemoveAllChildren();
        foreach (var offer in state.Offers)
        {
            if (_proto.TryIndex(offer.Goal, out var goal))
                OffersContainer.AddChild(BuildOfferCard(goal, offer, state.VoteEnd != null));
        }

        NoOffersLabel.Visible = state.HasStation && state.Offers.Count == 0;

        StartVoteButton.Disabled = !state.HasStation
            || state.VoteEnd != null
            || state.Active.Count >= state.MaxActive
            || !state.Offers.Any(o => o.Available);
        PrintButton.Disabled = !state.HasStation;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_state is not { HasStation: true })
        {
            RefreshLabel.Text = string.Empty;
            VoteLabel.Text = string.Empty;
            return;
        }

        var now = _timing.CurTime;
        RefreshLabel.Text = _state.VoteEnd == null
            ? Loc.GetString("station-goal-console-refresh", ("time", FormatTime(_state.NextRefresh - now)))
            : Loc.GetString("station-goal-console-refresh-paused");

        VoteLabel.Text = _state.VoteEnd is { } end
            ? Loc.GetString("station-goal-console-vote-running",
                ("time", FormatTime(end - now)),
                ("cast", _state.VotesCast),
                ("voters", _state.Voters))
            : Loc.GetString("station-goal-console-vote-hint");

        foreach (var (label, deadline) in _deadlineLabels)
            label.Text = FormatTime(deadline - now);
    }

    private static string FormatTime(TimeSpan time)
    {
        if (time < TimeSpan.Zero)
            time = TimeSpan.Zero;

        return time.TotalHours >= 1
            ? $"{(int) time.TotalHours}:{time.Minutes:00}:{time.Seconds:00}"
            : $"{time.Minutes:00}:{time.Seconds:00}";
    }

    private Control BuildActiveCard(StationGoalPrototype goal, StationGoalActiveState active)
    {
        var body = CardBody(goal);

        foreach (var objective in active.Objectives)
        {
            var text = new RichTextLabel { Margin = new Thickness(0, 6, 0, 2) };
            text.SetMessage(FormattedMessage.FromMarkupPermissive(objective.Text));
            body.AddChild(text);

            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 8 };
            row.AddChild(new ProgressBar
            {
                MinValue = 0,
                MaxValue = Math.Max(1f, objective.Target),
                Value = Math.Min(objective.Current, objective.Target),
                MinHeight = 12,
                HorizontalExpand = true,
                VerticalAlignment = VAlignment.Center,
            });
            row.AddChild(new Label
            {
                Text = $"{MathF.Floor(objective.Current)} / {objective.Target}",
                StyleClasses = { StyleClass.LabelWeak },
                MinWidth = 56,
                Align = Label.AlignMode.Right,
            });
            body.AddChild(row);
        }

        body.AddChild(new Control { VerticalExpand = true, MinHeight = 6 });

        if (active.Deadline is { } deadline)
        {
            var value = new Label();
            _deadlineLabels.Add((value, deadline));
            body.AddChild(InfoRow(Loc.GetString("station-goal-console-time-left"), value));
        }

        AddRewards(body, goal);
        return Card(body, goal);
    }

    private Control BuildOfferCard(StationGoalPrototype goal, StationGoalOfferState offer, bool voting)
    {
        var body = CardBody(goal);

        var description = new RichTextLabel { Margin = new Thickness(0, 8, 0, 0) };
        description.SetMessage(FormattedMessage.FromMarkupPermissive(Loc.GetString(goal.Description)));
        body.AddChild(description);

        body.AddChild(new Label
        {
            Text = Loc.GetString("station-goal-console-objectives"),
            StyleClasses = { StyleClass.LabelKeyText },
            Margin = new Thickness(0, 10, 0, 2),
        });

        foreach (var objective in goal.Objectives)
        {
            var line = new RichTextLabel { Margin = new Thickness(6, 0, 0, 0) };
            line.SetMessage(FormattedMessage.FromMarkupPermissive("- " + objective.GetText()));
            body.AddChild(line);
        }

        body.AddChild(new Control { VerticalExpand = true, MinHeight = 10 });

        if (goal.TimeLimit is { } limit)
        {
            body.AddChild(InfoRow(Loc.GetString("station-goal-console-time-limit"),
                new Label { Text = Loc.GetString("station-goal-console-minutes", ("minutes", (int) limit.TotalMinutes)) }));
        }

        AddRewards(body, goal);

        if (!offer.Available)
        {
            var note = new PanelContainer
            {
                StyleClasses = { StyleClass.Negative },
                Margin = new Thickness(0, 8, 0, 0),
            };
            var noteText = new RichTextLabel { Margin = new Thickness(6, 2) };
            noteText.SetMessage(FormattedMessage.FromMarkupPermissive(Loc.GetString("station-goal-console-unavailable")));
            note.AddChild(noteText);
            body.AddChild(note);
        }

        if (voting)
        {
            var vote = new Button
            {
                Text = Loc.GetString("station-goal-console-vote", ("count", offer.Voters.Count)),
                Disabled = !offer.Available,
                Margin = new Thickness(0, 8, 0, 0),
            };
            vote.OnPressed += _ => OnVote?.Invoke(goal.ID);
            body.AddChild(vote);

            if (offer.Voters.Count > 0)
            {
                var voters = new RichTextLabel { Margin = new Thickness(0, 4, 0, 0) };
                voters.SetMessage(FormattedMessage.FromUnformatted(string.Join(", ", offer.Voters)));
                body.AddChild(voters);
            }
        }

        var card = Card(body, goal);
        if (!offer.Available)
            card.Modulate = Color.White.WithAlpha(0.6f);

        return card;
    }

    private BoxContainer CardBody(StationGoalPrototype goal)
    {
        var body = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical };

        var header = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 10 };
        if (goal.Icon != null)
        {
            header.AddChild(new TextureRect
            {
                Texture = _entMan.System<SpriteSystem>().Frame0(goal.Icon),
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
                SetSize = new Vector2(48, 48),
                VerticalAlignment = VAlignment.Center,
            });
        }

        var titleBox = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            VerticalAlignment = VAlignment.Center,
        };
        titleBox.AddChild(new Label
        {
            Text = Loc.GetString(goal.Name),
            StyleClasses = { StyleClass.LabelHeading },
            ClipText = true,
        });

        var departments = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 4,
            Margin = new Thickness(0, 4, 0, 0),
        };
        foreach (var departmentId in goal.Departments)
        {
            if (_proto.TryIndex(departmentId, out var department))
                departments.AddChild(DepartmentTag(Loc.GetString(department.Name), department.Color));
        }

        titleBox.AddChild(departments);
        header.AddChild(titleBox);
        body.AddChild(header);
        return body;
    }

    private static Control DepartmentTag(string name, Color color)
    {
        var tag = new PanelContainer
        {
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = color.WithAlpha(0.15f),
                BorderColor = color.WithAlpha(0.6f),
                BorderThickness = new Thickness(1),
                ContentMarginLeftOverride = 6,
                ContentMarginRightOverride = 6,
                ContentMarginTopOverride = 1,
                ContentMarginBottomOverride = 1,
            },
        };
        tag.AddChild(new Label
        {
            Text = name,
            FontColorOverride = color,
            StyleClasses = { StyleClass.LabelSubText },
        });
        return tag;
    }

    private static Control InfoRow(string key, Control value)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            Margin = new Thickness(0, 2, 0, 0),
        };
        row.AddChild(new Label
        {
            Text = key,
            StyleClasses = { StyleClass.LabelWeak },
            HorizontalExpand = true,
        });
        value.HorizontalAlignment = HAlignment.Right;
        row.AddChild(value);
        return row;
    }

    private static void AddRewards(BoxContainer body, StationGoalPrototype goal)
    {
        body.AddChild(InfoRow(Loc.GetString("station-goal-console-reward-department"),
            new Label { Text = Loc.GetString("station-goal-console-credits", ("amount", goal.DepartmentReward)) }));
        body.AddChild(InfoRow(Loc.GetString("station-goal-console-reward-personal"),
            new Label { Text = Loc.GetString("station-goal-console-credits", ("amount", goal.PersonalReward)) }));
    }

    private Control Card(Control body, StationGoalPrototype goal)
    {
        var accent = goal.Departments.Count > 0 && _proto.TryIndex(goal.Departments[0], out var department)
            ? department.Color
            : Color.Gray;

        var panel = new PanelContainer { StyleClasses = { StarlightStyleClass.InsetPanel } };
        var layout = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
        layout.AddChild(new PanelContainer
        {
            PanelOverride = new StyleBoxFlat { BackgroundColor = accent.WithAlpha(0.8f) },
            MinWidth = 3,
        });

        body.Margin = new Thickness(12, 10);
        body.HorizontalExpand = true;
        layout.AddChild(body);
        panel.AddChild(layout);
        return panel;
    }

    private static Control EmptySlot(string text)
    {
        var panel = new PanelContainer
        {
            StyleClasses = { StarlightStyleClass.InsetPanel },
            Modulate = Color.White.WithAlpha(0.6f),
        };
        panel.AddChild(new Label
        {
            Text = text,
            StyleClasses = { StyleClass.LabelWeak },
            HorizontalAlignment = HAlignment.Center,
            VerticalAlignment = VAlignment.Center,
        });
        return panel;
    }
}
