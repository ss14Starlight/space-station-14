using Content.Client.Stylesheets;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
// ReSharper disable UseCollectionExpression - sandboxing ://///

namespace Content.Client._Starlight.Xenobiology.UI.Widgets;

[GenerateTypedNameReferences]
public sealed partial class GeneSelector : Control
{
    public bool FaceLeft { get; set; } = false;
    public Button ArrowButton = null!;

    public GeneSelector()
    {
        RobustXamlLoader.Load(this);
    }

    protected override void EnteredTree()
    {
        ArrowButton = new Button
        {
            Text = Loc.GetString(FaceLeft
                ? "xenobiology-ui-widgets-gene-selector-arrow-left"
                : "xenobiology-ui-widgets-gene-selector-arrow-right"),
            StyleClasses =
                FaceLeft
                    ? new StyleClassCollection { StyleClass.ButtonOpenRight }
                    : new StyleClassCollection { StyleClass.ButtonOpenLeft }
        };

        ButtonContainer.AddChild(ArrowButton);
        if (!FaceLeft) return;
        GeneButton.StyleClasses = new StyleClassCollection { StyleClass.ButtonOpenLeft };
        ArrowButton.SetPositionFirst();
    }
}

