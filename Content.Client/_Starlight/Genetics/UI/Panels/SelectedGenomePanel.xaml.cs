using Content.Client._Starlight.Genetics.UI.Widgets;
using Content.Shared._Starlight.Genetics.Genes.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Starlight.Genetics.UI.Panels;

[GenerateTypedNameReferences]
public sealed partial class SelectedGenomePanel : Control
{
    [Dependency] private IEntityManager _ent = null!;
    [Dependency] private IPrototypeManager _proto = null!;

    private GeneticsConsoleWindow _window = null!;
    public Entity<IndividualGeneComponent> SelectedGenome;

    public SelectedGenomePanel()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public void Initialize(GeneticsConsoleWindow window) => _window = window;

    public void SelectGenome(Entity<IndividualGeneComponent> genome)
    {
        SelectedGenome = genome;
        RefreshUI();
    }

    public void RefreshUI()
    {
        if (!_ent.EntityExists(SelectedGenome)) return;
        SelectedGeneTraitListContainer.RemoveAllChildren();
        SelectedGeneNameField.Text = SelectedGenome.Comp.Name;
        SelectedGeneIdentifierField.Text = SelectedGenome.Comp.TechnicalName;
        SelectedGeneSequenceField.Text = SelectedGenome.Comp.Sequence;

        foreach (var trait in SelectedGenome.Comp.Traits.Traits)
        {
            if (!_proto.TryIndex(trait.Key, out var proto)) continue;
            var selector = new TraitSelector { Trait = (proto, trait.Value) };
            selector.Initialize(_window);
            SelectedGeneTraitListContainer.AddChild(selector);
        }
    }
}
