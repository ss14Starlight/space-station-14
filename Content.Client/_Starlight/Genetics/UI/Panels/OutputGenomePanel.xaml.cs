using System.Linq;
using Content.Client._Starlight.Genetics.UI.Widgets;
using Content.Shared._Starlight.Genetics;
using Content.Shared._Starlight.Genetics.Genes.Systems;
using Content.Shared._Starlight.Genetics.GeneticTraits.Prototypes;
using Content.Shared.FixedPoint;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Starlight.Genetics.UI.Panels;

[GenerateTypedNameReferences]
public sealed partial class OutputGenomePanel : Control
{
    [Dependency] private IPrototypeManager _proto = null!;

    private GeneticsConsoleWindow _window = null!;

    public OutputGenomePanel()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public void Initialize(GeneticsConsoleWindow window) => _window = window;

    public void RefreshUI()
    {
        TraitSelectors.RemoveAllChildren();
        TraitSelector? restored = null;
        var inputs = _window.GetInputs();
        var combined = TraitDict.Combine(inputs.Select(gene => gene.Comp.Traits));
        foreach (var (protoId, accumulated) in combined.Traits)
        {
            if (!_proto.TryIndex(protoId, out var proto)) continue;
            var selector = new TraitSelector { Trait = (proto, accumulated) };
            selector.Initialize(_window, TraitSource.Output);
            if (_window.IsTraitSelected(proto.ID, TraitSource.Output))
                restored = selector;
            TraitSelectors.AddChild(selector);
        }

        _window.RestoreTraitSelection(TraitSource.Output, restored);
    }
}

