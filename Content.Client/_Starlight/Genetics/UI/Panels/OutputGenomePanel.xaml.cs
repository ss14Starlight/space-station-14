// ReSharper disable UseCollectionExpression

namespace Content.Client._Starlight.Genetics.UI.Panels;

[GenerateTypedNameReferences]
public sealed partial class OutputGenomePanel : Control
{
    [Dependency] private IPrototypeManager _proto = null!;

    private GeneticsConsoleWindow _window = null!;
    private TraitDict _combinedTraits = new();

    public OutputGenomePanel()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        GeneName.IsValid = text => text.Length <= IndividualGeneComponent.MaxNameLength;
        SaveButton.OnPressed += _ =>
        {
            var inputs = _window.GetInputs();
            if (inputs.Count <= 1) return;
            var name = GeneName.Text != string.Empty ? GeneName.Text : null;
            GeneName.SetText(string.Empty);
            // Console status updated in the console's entity system.
            _window.SaveGene(inputs.Select(x => x.Owner).ToHashSet(), _combinedTraits, name);
            _window.ClearInputs();
        };
    }

    public void Initialize(GeneticsConsoleWindow window) => _window = window;

    public void RefreshUI()
    {
        TraitSelectors.RemoveAllChildren();
        TraitSelector? restored = null;
        var inputs = _window.GetInputs();
        _combinedTraits = TraitDict.Combine(inputs.Select(gene => gene.Comp.Traits));
        foreach (var (protoId, accumulated) in _combinedTraits.Traits)
        {
            if (!_proto.TryIndex(protoId, out var proto)) continue;
            var selector = new TraitSelector { Trait = (proto, accumulated) };
            selector.Initialize(_window, TraitSource.Output);
            if (_window.IsTraitSelected(proto.ID, TraitSource.Output))
                restored = selector;
            TraitSelectors.AddChild(selector);
        }

        SaveButton.Disabled = _window.GetInputs().Count <= 1;
        _window.RestoreTraitSelection(TraitSource.Output, restored);
    }
}

