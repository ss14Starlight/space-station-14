using Content.Client._Starlight.Genetics.UI.Panels;
using Content.Client._Starlight.Genetics.UI.Widgets;
using Content.Shared._Starlight.Genetics.Components;
using Content.Shared._Starlight.Genetics.Genes.Components;
using Content.Shared._Starlight.Genetics.GeneticTraits.Prototypes;
using Content.Shared.FixedPoint;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Starlight.Genetics.UI;

[GenerateTypedNameReferences]
public sealed partial class GeneticsConsoleWindow : DefaultWindow
{
    [Dependency] private IEntityManager _ent = null!;
    private ContainerSystem? _container;

    public Entity<GeneticsConsoleComponent> Entity;
    public GeneSelector? SelectedGeneButton;
    public TraitSelector? SelectedTraitButton;
    private string? _selectedTraitId;
    private TraitSource _selectedTraitSource = TraitSource.None;
    public Action<EntityUid>? OnStage;
    public Action<EntityUid>? OnUnstage;
    public Action<int>? OnSetGenePoolSort;
    public Action<int>? OnSetInputGenesSort;
    public Action<EntityUid, string>? OnRenameGene;
    public Action? OnClearInputs;
    public Action<EntityUid>? OnDeleteGene;
    public Action? OnDispenseSampler;

    public GeneticsConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();

        SelectedGenomePanel.Initialize(this);
        CreationPanel.GenePoolPanel.Initialize(this);
        CreationPanel.InputGenesPanel.Initialize(this);
        CreationPanel.OutputGenomePanel.Initialize(this);

        OnClose += SelectedGenomePanel.ForceCloseDialog;
    }

    public void SetEntity(EntityUid entity)
    {
        if (!_ent.TryGetComponent<GeneticsConsoleComponent>(entity, out var comp))
            throw new ArgumentException(
                $"Entity {_ent.ToPrettyString(entity)} does not have {nameof(GeneticsConsoleComponent)}.",
                nameof(entity));

        Entity = (entity, comp);

        CreationPanel.GenePoolPanel.RefreshUI();
        CreationPanel.InputGenesPanel.RefreshUI();
        CreationPanel.OutputGenomePanel.RefreshUI();
    }

    public void SelectGene(GeneSelector selected, BaseButton.ButtonEventArgs args)
    {
        SelectedGeneButton?.Deselect();
        SelectedGeneButton = selected;
        // Trait selection is restored (or cleared) by the genome panel's refresh.
        SelectedGenomePanel.SelectGenome(SelectedGeneButton.Gene);
    }

    public void SelectTrait(TraitSelector selected, BaseButton.ButtonEventArgs args)
    {
        if (selected.Trait is not { } trait) return;
        // Deselects the previous button, even if it lives in the other panel.
        if (SelectedTraitButton != selected)
            SelectedTraitButton?.Deselect();
        SelectedTraitButton = selected;
        _selectedTraitId = trait.proto.ID;
        _selectedTraitSource = selected.Source;
        SelectedTraitPanel.SelectTrait(trait);
    }

    public void DeselectTrait()
    {
        SelectedTraitButton?.Deselect();
        SelectedTraitButton = null;
        _selectedTraitId = null;
        _selectedTraitSource = TraitSource.None;
        SelectedTraitPanel.DeselectTrait();
    }

    /// <summary>
    /// Whether a freshly built selector in the given panel should take over the current trait selection.
    /// </summary>
    public bool IsTraitSelected(string traitId, TraitSource source) =>
        _selectedTraitSource == source && _selectedTraitId == traitId;

    /// <summary>
    /// Called by a panel after rebuilding its trait list. If the selection belongs to that panel, either moves it to
    /// the rebuilt button (refreshing the displayed info) or clears it when the trait is no longer present.
    /// </summary>
    public void RestoreTraitSelection(TraitSource source, TraitSelector? selector)
    {
        if (_selectedTraitSource != source) return;
        if (selector?.Trait is not { } trait)
        {
            DeselectTrait();
            return;
        }

        selector.Select();
        SelectedTraitButton = selector;
        SelectedTraitPanel.SelectTrait(trait);
    }

    public void RenameGene(string newName) => OnRenameGene?.Invoke(SelectedGeneButton!.Gene, newName);

    public void DeleteGene(Entity<IndividualGeneComponent> uid) => OnDeleteGene?.Invoke(uid);

    public void DispenseSampler() => OnDispenseSampler?.Invoke();

    public void ClearInputs() => OnClearInputs?.Invoke();

    public List<Entity<IndividualGeneComponent>> GetInputs() => CreationPanel.InputGenesPanel.GetPool();

    public void RefreshUI()
    {
        SelectedGenomePanel.RefreshUI();
        SelectedTraitPanel.RefreshUI();
        CreationPanel.GenePoolPanel.RefreshUI();
        CreationPanel.InputGenesPanel.RefreshUI();
        CreationPanel.OutputGenomePanel.RefreshUI();
    }

    public void StageGene(GeneSelector target) => OnStage?.Invoke(target.Gene);
    public void UnstageGene(GeneSelector target) => OnUnstage?.Invoke(target.Gene);
    public void SetGenePoolSort(int index) => OnSetGenePoolSort?.Invoke(index);
    public void SetInputGenesSort(int index) => OnSetInputGenesSort?.Invoke(index);
}

