using System.Linq;
using Content.Client.Stylesheets;
using Content.Shared._Starlight.Genetics.Genes.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
// ReSharper disable UseCollectionExpression - sandboxing ://///

namespace Content.Client._Starlight.Genetics.UI.Widgets;

[GenerateTypedNameReferences]
public sealed partial class GeneSelector : Control
{
    private GeneticsConsoleWindow _window = null!;
    public bool FaceLeft { get; init; }
    public Entity<IndividualGeneComponent> Gene { get; init; }
    private Button _arrowButton = null!;
    private bool _isSelected;

    public GeneSelector() => RobustXamlLoader.Load(this);

    public void Initialize(GeneticsConsoleWindow window) => _window = window;

    public void Deselect()
    {
        Button.Pressed = false;
        _isSelected = false;
    }

    public void Select()
    {
        Button.Pressed = true;
        _isSelected = true;
    }

    protected override void EnteredTree()
    {
        _arrowButton = new Button
        {
            Text = Loc.GetString(FaceLeft
                ? "genetics-ui-widgets-gene-selector-arrow-left"
                : "genetics-ui-widgets-gene-selector-arrow-right"),
            StyleClasses =
                FaceLeft
                    ? new StyleClassCollection { StyleClass.ButtonOpenRight }
                    : new StyleClassCollection { StyleClass.ButtonOpenLeft }
        };

        ButtonContainer.AddChild(_arrowButton);
        Button.Text = _window.GetDisplayName(Gene);
        Button.OnToggled += args =>
        {
            // Prevent deselect by pressing same button
            if (!args.Pressed && _isSelected)
            {
                Button.Pressed = true;
                return;
            }

            _isSelected = true;
            _window.SelectGene(this, args);
            _window.UpdateConsoleStatus(Loc.GetString("genetics-ui-status-select-gene",
                ("gene", _window.GetDisplayName(Gene))));
        };
        _arrowButton.OnPressed += _ =>
        {
            if (FaceLeft)
            {
                _window.UnstageGene(this);
                _window.UpdateConsoleStatus(Loc.GetString("genetics-ui-status-unstage-gene",
                    ("gene", _window.GetDisplayName(Gene))));
            }
            else
            {
                _window.StageGene(this);
                _window.UpdateConsoleStatus(Loc.GetString("genetics-ui-status-stage-gene",
                    ("gene", _window.GetDisplayName(Gene))));
            }
        };

        if (!FaceLeft)
        {
            var inputs = _window.GetInputs();
            // Disable children
            if (inputs.Any(ent => ent.Comp.AncestorGenes.Contains(Gene.Comp.TechnicalName)))
                _arrowButton.Disabled = true;
            // Disable ancestors
            if (inputs.Any(ent => Gene.Comp.AncestorGenes.Contains(ent.Comp.TechnicalName)))
                _arrowButton.Disabled = true;
            return;
        }

        Button.StyleClasses = new StyleClassCollection { StyleClass.ButtonOpenLeft };
        _arrowButton.SetPositionFirst();
    }
}

