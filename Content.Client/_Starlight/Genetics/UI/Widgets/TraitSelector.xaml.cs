using Content.Client.Stylesheets;
using Content.Shared._Starlight.Genetics.GeneticTraits.Prototypes;
using Content.Shared.FixedPoint;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
// ReSharper disable UseCollectionExpression

namespace Content.Client._Starlight.Genetics.UI.Widgets;

[GenerateTypedNameReferences]
public sealed partial class TraitSelector : Control
{
    private GeneticsConsoleWindow _window = null!;
    public (GeneticTraitPrototype proto, FixedPoint2 accumulated)? Trait;
    private bool _isSelected;

    public TraitSelector()
    {
        RobustXamlLoader.Load(this);
    }

    public void Deselect()
    {
        Button.Pressed = false;
        _isSelected = false;
    }

    public void Initialize(GeneticsConsoleWindow window) => _window = window;

    protected override void EnteredTree()
    {
        base.EnteredTree();
        if (Trait is not {} trait) return;

        Button.Text = trait.proto.Name;
        ThresholdLabel.Text = trait.accumulated.Float().ToString("F2");
        // Negative color if not enough present to pass threshold.
        if (trait.accumulated < trait.proto.Threshold)
            Button.StyleClasses = new StyleClassCollection { StyleClass.Negative, StyleClass.ButtonOpenRight };

        Button.OnToggled += args =>
        {
            // Prevent deselect by pressing same button
            if (!args.Pressed && _isSelected)
            {
                Button.Pressed = true;
                return;
            }

            _isSelected = true;
            _window.SelectTrait(this, args);
        };
    }
}
