using Content.Client.UserInterface.Controls;
using Content.Shared._Starlight.Genetics;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Starlight.Genetics.Ui;

[GenerateTypedNameReferences]
public sealed partial class GeneticsConsoleWindow : FancyWindow
{
    [Dependency] private EntityManager _entityManager = default!;
    [Dependency] private IPrototypeManager _prototypeManager = default!;
    [Dependency] private ILogManager _logManager = default!;
    private ISawmill _sawmill = default!;

    private List<GeneData> _genes = new();

    private int? _selectedIndex;

    private string? _selectedGeneRename;
    public Action<GeneticsConsoleRenameGeneData>? OnRenameGenePressed;

    public GeneticsConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _sawmill = _logManager.GetSawmill("genetics.ui");

        GenesItemList.OnItemSelected += args =>
        {
            _selectedIndex = args.ItemIndex;
            PopulateSelected();
        };
        GenesItemList.OnItemDeselected += _ =>
        {
            _selectedIndex = null;
            PopulateSelected();
        };

        SetGeneNameButton.OnPressed += _ =>
        {
            if (_selectedIndex != null && _selectedGeneRename != null)
                OnRenameGenePressed?.Invoke
                (
                    new GeneticsConsoleRenameGeneData
                    (
                        _selectedIndex.Value,
                        _selectedGeneRename
                    )
                );
        };
    }

    public void UpdateState(GeneticsConsoleState state)
    {
        _genes = state.Genes;

        PopulateGenes();
        PopulateSelected();
    }

    private void PopulateGenes()
    {
        GenesItemList.Clear();
        GenesItemList.Visible = true;

        foreach (var gene in _genes)
        {
            var name = gene.Name ?? gene.TechnicalName;
            GenesItemList.AddItem(name, metadata: gene);
        }
    }

    private void SetupTable()
    {
        SelectedGeneTraits.Children.Clear();
        var traitNameHeaderBox = new BoxContainer();
        traitNameHeaderBox.HorizontalExpand = true;
        var traitNameHeader = new Label();
        traitNameHeader.Text = "Trait";
        traitNameHeader.Align = Label.AlignMode.Left;
        traitNameHeaderBox.Children.Add(traitNameHeader);

        var traitStrengthHeaderBox = new BoxContainer();
        var traitStrengthLabel = new Label();
        traitStrengthLabel.Text = "Strength";
        traitStrengthLabel.Align = Label.AlignMode.Right;
        traitStrengthHeaderBox.Children.Add(traitStrengthLabel);

        SelectedGeneTraits.Children.Add(traitNameHeaderBox);
        SelectedGeneTraits.Children.Add(traitStrengthHeaderBox);
    }

    private void PopulateSelected()
    {
        if (_selectedIndex != null)
        {
            var selected = _genes[_selectedIndex.Value];
            TechnicalNameLabel.Text = selected.TechnicalName;
            SelectedGeneName.SetText(selected.Name ?? string.Empty);
            SelectedGeneName.Editable = true;
            SetGeneNameButton.Disabled = false;
            SetupTable();
            foreach (var (protoId, strength) in selected.Traits.Traits)
            {
                if (!_prototypeManager.TryIndex(protoId, out var geneticTrait)) continue;
                var leftBox = new BoxContainer();
                leftBox.HorizontalExpand = true;
                var leftBoxLabel = new Label();
                leftBoxLabel.Text = geneticTrait.Name;
                leftBoxLabel.Align = Label.AlignMode.Left;
                leftBox.Children.Add(leftBoxLabel);

                var rightBox = new BoxContainer();
                var rightBoxLabel = new Label();
                rightBoxLabel.Text = $"{strength}";
                rightBoxLabel.Align = Label.AlignMode.Right;
                rightBox.Children.Add(rightBoxLabel);

                SelectedGeneTraits.Children.Add(leftBox);
                SelectedGeneTraits.Children.Add(rightBox);
            }
        }
        else
        {
            TechnicalNameLabel.Text = "NO GENE SELECTED";
            SelectedGeneName.SetText("NO GENE SELECTED");
            SelectedGeneName.Editable = false;
            SetGeneNameButton.Disabled = true;
            SetupTable();
        }
    }
}
