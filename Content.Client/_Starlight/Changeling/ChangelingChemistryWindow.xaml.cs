using System.Globalization;
using System.Linq;
using Content.Client.Chemistry.UI;
using Content.Client.UserInterface.Controls;
using Content.Shared._Starlight.Changeling;
using Content.Shared.Chemistry;
using Content.Shared.Chemistry.Reagent;
using Content.Shared.FixedPoint;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Starlight.Changeling;

[GenerateTypedNameReferences]
public sealed partial class ChangelingChemistryWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _prototypes = default!;

    public event Action<ProtoId<ReagentPrototype>, int>? OnAddReagent;
    public event Action? OnClear;
    public event Action<float>? OnTemperature;
    public event Action<bool>? OnRegeneration;
    public event Action<int>? OnDose;

    private bool _regenerating;
    private Dictionary<ProtoId<ReagentPrototype>, FixedPoint2> _reagents = new();

    public ChangelingChemistryWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        ClearButton.OnPressed += _ => OnClear?.Invoke();
        RegenerationButton.OnPressed += _ => OnRegeneration?.Invoke(!_regenerating);
        DoseGrid.OnButtonPressed += value => OnDose?.Invoke(int.Parse(value, CultureInfo.InvariantCulture));
        SetTemperatureButton.OnPressed += _ =>
        {
            if (float.TryParse(TemperatureInput.Text, NumberStyles.Float, CultureInfo.InvariantCulture, out var temperature))
                OnTemperature?.Invoke(temperature);
        };
    }

    public void UpdateState(ChangelingChemistryUiState state)
    {
        _regenerating = state.Regenerating;
        ChemicalReserve.Text = Loc.GetString("changeling-chemistry-reserve", ("amount", MathF.Round(state.Chemicals, 1)));
        RegenerationButton.Text = Loc.GetString(_regenerating ? "changeling-chemistry-regeneration-on" : "changeling-chemistry-regeneration-off");
        var full = state.Reagents.Count > 0 && state.Reagents.Values.All(amount => amount >= ChangelingChemistry.ReagentCapacity);
        var regenerationStatus = !_regenerating ? "changeling-chemistry-status-off"
            : full ? "changeling-chemistry-status-full"
            : state.CanRegenerate ? "changeling-chemistry-status-active" : "changeling-chemistry-status-paused";
        RegenerationStatus.Text = Loc.GetString(regenerationStatus, ("capacity", ChangelingChemistry.ReagentCapacity));
        MixtureVolume.Text = Loc.GetString("changeling-chemistry-mixture-volume", ("volume", state.Mixture.Volume), ("capacity", state.Mixture.MaxVolume));
        CurrentTemperature.Text = Loc.GetString("changeling-chemistry-temperature", ("temperature", MathF.Round(state.Mixture.Temperature, 1)));
        if (!TemperatureInput.HasKeyboardFocus())
            TemperatureInput.Text = state.TargetTemperature.ToString("F1", CultureInfo.InvariantCulture);
        var selectedDose = state.Dose.ToString(CultureInfo.InvariantCulture);
        if (DoseGrid.Selected != selectedDose)
            DoseGrid.Selected = selectedDose;
        ClearButton.Disabled = state.Mixture.Volume <= 0;

        MixtureContents.Children.Clear();
        foreach (var (reagent, amount) in state.Mixture.Contents)
            MixtureContents.AddReagent(reagent, amount);

        if (_reagents.Count == state.Reagents.Count && _reagents.All(r => state.Reagents.TryGetValue(r.Key, out var amount) && amount == r.Value))
            return;
        _reagents = state.Reagents;
        ReagentList.Children.Clear();
        foreach (var (reagent, amount) in state.Reagents)
        {
            if (!_prototypes.Resolve(reagent, out var prototype))
                continue;
            var card = new ReagentCardControl(new ReagentInventoryItem(
                new ReagentDispenseData(null, reagent), prototype.LocalizedName, amount, prototype.SubstanceColor, false));
            card.OnPressed += _ => OnAddReagent?.Invoke(reagent, int.Parse(AmountGrid.Selected ?? "1", CultureInfo.InvariantCulture));
            ReagentList.AddChild(card);
        }
    }
}
