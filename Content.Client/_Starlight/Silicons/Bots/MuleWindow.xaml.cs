using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._Starlight.Silicons.Bots;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Starlight.Silicons.Bots;

[GenerateTypedNameReferences]
public sealed partial class MuleWindow : FancyWindow
{
    public event Action<MuleCommand>? OnCommand;
    public event Action<NetEntity, bool>? OnBeaconPicked;

    private readonly List<NetEntity> _beacons = new();

    public MuleWindow()
    {
        RobustXamlLoader.Load(this);

        PowerButton.OnPressed += _ => OnCommand?.Invoke(MuleCommand.Power);
        UnloadButton.OnPressed += _ => OnCommand?.Invoke(MuleCommand.Unload);
        GoButton.OnPressed += _ => OnCommand?.Invoke(MuleCommand.Go);
        StopButton.OnPressed += _ => OnCommand?.Invoke(MuleCommand.Stop);
        HomeButton.OnPressed += _ => OnCommand?.Invoke(MuleCommand.Home);
        AutoReturnBox.OnPressed += _ => OnCommand?.Invoke(MuleCommand.AutoReturn);
        AutoPickupBox.OnPressed += _ => OnCommand?.Invoke(MuleCommand.AutoPickup);
        ReportBox.OnPressed += _ => OnCommand?.Invoke(MuleCommand.Report);
        DestinationOption.OnItemSelected += args => OnBeaconPicked?.Invoke(_beacons[args.Id], false);
        HomeOption.OnItemSelected += args => OnBeaconPicked?.Invoke(_beacons[args.Id], true);
    }

    public void UpdateState(MuleBoundUserInterfaceState state)
    {
        var status = !state.On ? "mule-mode-off" : state.Mode switch
        {
            MuleMode.Delivering => "mule-mode-delivering",
            MuleMode.GoingHome => "mule-mode-going-home",
            MuleMode.Blocked => "mule-mode-blocked",
            MuleMode.NoRoute => "mule-mode-no-route",
            _ => "mule-mode-idle",
        };
        StatusLabel.Text = Loc.GetString("mule-window-status", ("status", Loc.GetString(status)));
        LoadLabel.Text = state.Load is { } load
            ? Loc.GetString("mule-window-load", ("load", load))
            : Loc.GetString("mule-window-no-load");
        ChargeLabel.Text = state.Charge is { } charge
            ? Loc.GetString("mule-window-charge", ("charge", (int) MathF.Round(charge * 100)))
            : Loc.GetString("mule-window-no-cell");

        PowerButton.Pressed = state.On;
        AutoReturnBox.Pressed = state.AutoReturn;
        AutoPickupBox.Pressed = state.AutoPickup;
        ReportBox.Pressed = state.Report;

        _beacons.Clear();
        DestinationOption.Clear();
        HomeOption.Clear();
        foreach (var (beacon, name) in state.Beacons.OrderBy(pair => pair.Value))
        {
            DestinationOption.AddItem(name, _beacons.Count);
            HomeOption.AddItem(name, _beacons.Count);
            _beacons.Add(beacon);
        }

        Select(DestinationOption, state.Destination);
        Select(HomeOption, state.Home);
    }

    private void Select(OptionButton option, NetEntity? beacon)
    {
        var index = beacon is { } picked ? _beacons.IndexOf(picked) : -1;
        if (index >= 0)
            option.SelectId(index);
    }
}
