using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._Starlight.Silicons.Bots;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Starlight.Silicons.Bots;

[GenerateTypedNameReferences]
public sealed partial class MuleWindow : FancyWindow
{
    public event Action<MuleCommand>? OnCommand;
    public event Action<NetEntity, bool>? OnBeaconPicked;

    private Dictionary<NetEntity, string> _beacons = new();
    private NetEntity? _selected;

    public MuleWindow()
    {
        RobustXamlLoader.Load(this);

        PowerButton.OnPressed += _ => OnCommand?.Invoke(MuleCommand.Power);
        UnloadButton.OnPressed += _ => OnCommand?.Invoke(MuleCommand.Unload);
        GoButton.OnPressed += _ => OnCommand?.Invoke(MuleCommand.Go);
        StopButton.OnPressed += _ => OnCommand?.Invoke(MuleCommand.Stop);
        HomeButton.OnPressed += _ => OnCommand?.Invoke(MuleCommand.Home);
        AutoReturnBox.OnPressed += _ => OnCommand?.Invoke(MuleCommand.AutoReturn);
        AutoPickupBox.OnPressed += _ => OnCommand?.Invoke(MuleCommand.AutoPickup);
        ReportBox.OnPressed += _ => OnCommand?.Invoke(MuleCommand.Report);

        SearchBar.OnTextChanged += _ => FillBeacons();
        BeaconList.OnItemSelected += args => Select((NetEntity) args.ItemList[args.ItemIndex].Metadata!);
        BeaconList.OnItemDeselected += _ => Select(null);
        SetDestinationButton.OnPressed += _ => Pick(false);
        SetHomeButton.OnPressed += _ => Pick(true);
    }

    public void UpdateState(MuleBoundUserInterfaceState state)
    {
        var status = !state.On ? "mule-mode-off" : state.Mode switch
        {
            MuleMode.Delivering => "mule-mode-delivering",
            MuleMode.GoingHome => "mule-mode-going-home",
            MuleMode.Blocked => "mule-mode-blocked",
            _ => "mule-mode-idle",
        };
        StatusLabel.Text = Loc.GetString("mule-window-status", ("status", Loc.GetString(status)));
        LoadLabel.Text = state.Load is { } load
            ? Loc.GetString("mule-window-load", ("load", load))
            : Loc.GetString("mule-window-no-load");
        ChargeLabel.Text = state.Charge is { } charge
            ? Loc.GetString("mule-window-charge", ("charge", (int) MathF.Round(charge * 100)))
            : Loc.GetString("mule-window-no-cell");
        DestinationLabel.Text = Loc.GetString("mule-window-destination", ("beacon", BeaconName(state.Destination, state.Beacons)));
        HomeLabel.Text = Loc.GetString("mule-window-home", ("beacon", BeaconName(state.Home, state.Beacons)));

        PowerButton.Pressed = state.On;
        AutoReturnBox.Pressed = state.AutoReturn;
        AutoPickupBox.Pressed = state.AutoPickup;
        ReportBox.Pressed = state.Report;

        // Only rebuild the list when the beacons change, so the search and selection survive status updates.
        if (_beacons.Count == state.Beacons.Count && !_beacons.Except(state.Beacons).Any())
            return;

        _beacons = state.Beacons;
        FillBeacons();
    }

    private static string BeaconName(NetEntity? beacon, Dictionary<NetEntity, string> beacons)
    {
        return beacon is { } picked && beacons.TryGetValue(picked, out var name) ? name : Loc.GetString("mule-window-none");
    }

    private void FillBeacons()
    {
        var search = SearchBar.Text.Trim();
        BeaconList.Clear();
        foreach (var (beacon, name) in _beacons.OrderBy(pair => pair.Value))
        {
            if (search.Length > 0 && !name.Contains(search, StringComparison.OrdinalIgnoreCase))
                continue;

            var item = BeaconList.AddItem(name, metadata: beacon);
            item.Selected = beacon == _selected;
        }

        if (_selected is { } selected && !BeaconList.Any(item => (NetEntity) item.Metadata! == selected))
            Select(null);
    }

    private void Select(NetEntity? beacon)
    {
        _selected = beacon;
        SetDestinationButton.Disabled = beacon == null;
        SetHomeButton.Disabled = beacon == null;
    }

    private void Pick(bool home)
    {
        if (_selected is { } beacon)
            OnBeaconPicked?.Invoke(beacon, home);
    }
}
