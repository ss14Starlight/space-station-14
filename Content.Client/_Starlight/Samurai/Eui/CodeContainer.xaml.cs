using Content.Shared._Starlight.Samurai;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Starlight.Samurai.Eui;

[GenerateTypedNameReferences]
public sealed partial class CodeContainer : BoxContainer
{
    public event Action? OnMoveUp;
    public event Action? OnMoveDown;
    public event Action? OnDelete;

    public CodeContainer(SamuraiCode? code = null)
    {
        RobustXamlLoader.Load(this);

        if (code != null)
        {
            SamuraiCodeTitle.Text = code.GetLocName();
            SamuraiCodeContent.TextRope = new Rope.Leaf(code.GetLocDesc());
        }

        MoveUp.OnPressed += _ => OnMoveUp?.Invoke();
        MoveDown.OnPressed += _ => OnMoveDown?.Invoke();
        Delete.OnPressed += _ => OnDelete?.Invoke();
    }

    public string CodeTitle => SamuraiCodeTitle.Text;
    public string CodeText => Rope.Collapse(SamuraiCodeContent.TextRope).Trim();
}
