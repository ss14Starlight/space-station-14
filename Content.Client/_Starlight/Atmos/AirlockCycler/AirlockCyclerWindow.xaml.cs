using System.Globalization;
using System.Linq;
using Content.Client.Stylesheets.Palette;
using Content.Client.UserInterface.Controls;
using Content.Shared._Starlight.Atmos.AirlockCycler;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Starlight.Atmos.AirlockCycler;

[GenerateTypedNameReferences]
public sealed partial class AirlockCyclerWindow : FancyWindow
{
    // Theme-provided label colors
    private const string ClassGood = "status-good";
    private const string ClassBad = "status-bad";
    private const string ClassWarning = "status-warning";
    private const string ClassWeak = "LabelWeak";
    private static readonly string[] _colorClasses = [ClassGood, ClassBad, ClassWarning, ClassWeak];

    public event Action<int>? OnCycle;
    // Long lines wrap in a RichTextLabel, which takes no label style classes: same colors as status-warning and
    // LabelWeak.
    private static readonly Color WarningColor = Palettes.Status.Warning;
    private static readonly Color WeakColor = Color.DarkGray;

    public event Action? OnForce;
    public event Action? OnLockdown;

    /// <summary>
    /// Builds the window and hooks up the force and lockdown buttons.
    /// </summary>
    public AirlockCyclerWindow()
    {
        RobustXamlLoader.Load(this);
        ForceButton.OnPressed += _ => OnForce?.Invoke();
        LockdownButton.OnPressed += _ => OnLockdown?.Invoke();
        SetWrapped(NoSidesLabel, Loc.GetString("airlock-cycler-window-no-sides"), WeakColor);
    }

    private static void SetWrapped(RichTextLabel label, string text, Color color)
    {
        var message = new FormattedMessage();
        message.PushColor(color);
        message.AddText(text);
        message.Pop();
        label.SetMessage(message);
    }

    /// <summary>
    /// Updates current window state.
    /// </summary>
    public void UpdateState(AirlockCyclerBoundUserInterfaceState state)
    {
        var targetName = state.TargetSide is { } t ? SideName(t) : string.Empty;

        // The controller refuses to go on by itself; only a forced open moves it.
        var holding = state.Problem is AirlockCyclerProblem.NoReading
            or AirlockCyclerProblem.IncompatiblePressure
            or AirlockCyclerProblem.NoInlet
            or AirlockCyclerProblem.NoOutlet;
        var lockdown = state.Lockdown && state.State == AirlockCyclerState.Idle;

        StatusLabel.Text = holding
            ? Loc.GetString("airlock-cycler-state-holding", ("side", targetName))
            : lockdown
            ? Loc.GetString("airlock-cycler-state-lockdown")
            : state.State switch
        {
            AirlockCyclerState.Off => Loc.GetString("airlock-cycler-state-off"),
            AirlockCyclerState.Idle when state.Queued.Count > 0
                => Loc.GetString("airlock-cycler-state-next", ("side", SideName(state.Queued[0]))),
            AirlockCyclerState.Idle => Loc.GetString("airlock-cycler-state-idle"),
            AirlockCyclerState.Closing => Loc.GetString("airlock-cycler-state-closing", ("side", targetName)),
            AirlockCyclerState.Pressurizing => Loc.GetString("airlock-cycler-state-pressurizing", ("side", targetName)),
            AirlockCyclerState.Depressurizing => Loc.GetString("airlock-cycler-state-depressurizing", ("side", targetName)),
            _ => string.Empty,
        };
        SetColorClass(StatusLabel, state.State switch
        {
            AirlockCyclerState.Off => ClassWeak,
            AirlockCyclerState.Idle when state.Queued.Count > 0 => ClassWarning,
            AirlockCyclerState.Idle when !lockdown => ClassGood,
            _ => ClassBad,
        });

        var problem = state.Problem switch
        {
            AirlockCyclerProblem.NoVent => Loc.GetString("airlock-cycler-problem-no-vent"),
            AirlockCyclerProblem.Stalled => Loc.GetString("airlock-cycler-problem-stalled"),
            AirlockCyclerProblem.DoorObstructed => Loc.GetString("airlock-cycler-problem-obstructed"),
            AirlockCyclerProblem.IncompatiblePressure => Loc.GetString("airlock-cycler-problem-incompatible"),
            AirlockCyclerProblem.NoReading => Loc.GetString("airlock-cycler-problem-no-reading"),
            AirlockCyclerProblem.DoorUnsecured => Loc.GetString("airlock-cycler-problem-unsecured"),
            AirlockCyclerProblem.NoInlet => Loc.GetString("airlock-cycler-problem-no-inlet"),
            AirlockCyclerProblem.NoOutlet => Loc.GetString("airlock-cycler-problem-no-outlet"),
            _ => string.Empty,
        };

        var onlyNote = state.Problem is AirlockCyclerProblem.None or AirlockCyclerProblem.NoVent;
        if (state.NoVent && state.Problem != AirlockCyclerProblem.NoVent)
        {
            var note = Loc.GetString("airlock-cycler-problem-no-vent");
            problem = problem.Length == 0 ? note : problem + "\n" + note;
        }

        ProblemLabel.Visible = problem.Length > 0;
        SetWrapped(ProblemLabel, problem, state.NoVent && onlyNote ? WeakColor : WarningColor);

        var cycling = state.State is AirlockCyclerState.Closing
            or AirlockCyclerState.Pressurizing
            or AirlockCyclerState.Depressurizing;

        ChamberRow.Visible = !state.NoVent && state.ChamberPressure != null;
        TargetRow.Visible = !state.NoVent && cycling && state.TargetPressure != null;
        TankRow.Visible = !state.NoVent && state.TankPressure != null;
        PressureBox.Visible = ChamberRow.Visible || TargetRow.Visible || TankRow.Visible;
        ChamberLabel.Text = Pressure(state.ChamberPressure);
        TargetLabel.Text = Pressure(state.TargetPressure);
        TankLabel.Text = Pressure(state.TankPressure);

        ForceButton.Visible = !state.NoVent
            && cycling
            && (state.State != AirlockCyclerState.Closing || holding || state.Problem == AirlockCyclerProblem.Stalled);

        LockdownButton.Visible = state.State != AirlockCyclerState.Off && !lockdown && state.Sides.Count > 0;

        // Rows are kept between updates so a button is never swapped out from under the cursor mid-click.
        NoSidesLabel.Visible = state.Sides.Count == 0;
        _seen.Clear();
        foreach (var side in state.Sides)
        {
            _seen.Add(side.Index);
            if (!_rows.TryGetValue(side.Index, out var row))
            {
                row = CreateSideRow(side.Index);
                _rows[side.Index] = row;
                SidesContainer.AddChild(row.Root);
            }

            UpdateSideRow(row, state, side, cycling, state.NoVent);
        }

        foreach (var index in _rows.Keys.ToArray())
        {
            if (_seen.Contains(index))
                continue;

            SidesContainer.RemoveChild(_rows[index].Root);
            _rows.Remove(index);
        }
    }

    private sealed class SideRow
    {
        public BoxContainer Root = default!;
        public Label Name = default!;
        public Label Info = default!;
        public Button Cycle = default!;
    }

    private readonly Dictionary<int, SideRow> _rows = [];
    private readonly HashSet<int> _seen = [];

    /// <summary>
    /// Creates the row of one side: its name, door and pressure info, and the cycle button.
    /// </summary>
    private SideRow CreateSideRow(int index)
    {
        var row = new SideRow
        {
            Root = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 6,
            },
            Name = new Label { MinWidth = 70 },
            Info = new Label { HorizontalExpand = true, ClipText = true, StyleClasses = { ClassWeak } },
            Cycle = new Button { Text = Loc.GetString("airlock-cycler-window-cycle"), MinWidth = 80 },
        };

        row.Cycle.OnPressed += _ => OnCycle?.Invoke(index);
        row.Root.AddChild(row.Name);
        row.Root.AddChild(row.Info);
        row.Root.AddChild(row.Cycle);
        return row;
    }

    private static void UpdateSideRow(SideRow row,
        AirlockCyclerBoundUserInterfaceState state,
        AirlockCyclerSideData side,
        bool cycling,
        bool interlock)
    {
        var isTarget = state.TargetSide == side.Index;

        row.Name.Text = Loc.GetString(side.Name);
        SetColorClass(row.Name, isTarget ? (cycling ? ClassBad : ClassGood) : null);

        var queuedAt = state.Queued.IndexOf(side.Index);
        row.Info.Text = queuedAt >= 0
            ? Loc.GetString("airlock-cycler-window-side-queued", ("position", queuedAt + 1))
            : interlock || side.OutsidePressure is not { } pressure
            ? Loc.GetString("airlock-cycler-window-side-doors", ("open", side.OpenDoors), ("doors", side.Doors))
            : Loc.GetString("airlock-cycler-window-side-info",
                ("pressure", Pressure(pressure)),
                ("open", side.OpenDoors),
                ("doors", side.Doors));
        SetColorClass(row.Info, queuedAt >= 0 ? ClassWarning : ClassWeak);
        row.Cycle.Disabled = state.State == AirlockCyclerState.Off
            || side.Doors == 0
            || (cycling && isTarget)
            || queuedAt >= 0;
    }

    /// <summary>
    /// Swaps the theme color class of a label, removing the other color classes.
    /// </summary>
    private static void SetColorClass(Control control, string? styleClass)
    {
        foreach (var existing in _colorClasses)
        {
            if (existing != styleClass)
                control.RemoveStyleClass(existing);
        }

        if (styleClass != null && !control.HasStyleClass(styleClass))
            control.AddStyleClass(styleClass);
    }

    /// <summary>
    /// Localized name of a side by index (Side A, Side B...).
    /// </summary>
    private static string SideName(int index)
        => Loc.GetString($"airlock-cycler-side-{(char) ('a' + index)}");

    /// <summary>
    /// Formats a pressure to one decimal in kPa, or "No data" when missing.
    /// </summary>
    private static string Pressure(float? kpa)
        => kpa is { } p
            ? Loc.GetString("airlock-cycler-window-pressure", ("pressure", p.ToString("0.0", CultureInfo.InvariantCulture)))
            : Loc.GetString("airlock-cycler-window-no-data");
}
