using System.Linq;
using Content.Client.Stylesheets;
using Content.Client.UserInterface.Controls;
using Content.Shared._Starlight.BluespaceArtillery;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._Starlight.BluespaceArtillery;

[GenerateTypedNameReferences]
public sealed partial class BluespaceArtilleryConsoleWindow : FancyWindow
{
    [Dependency] private IGameTiming _timing = default!;

    private static readonly TimeSpan ConfirmWindow = TimeSpan.FromSeconds(3);
    private static readonly TimeSpan ConfirmDelay = TimeSpan.FromSeconds(0.5);

    public event Action? OnBuild;
    public event Action<NetEntity>? OnSelectTarget;
    public event Action<bool>? OnCharge;
    public event Action? OnFire;

    private BluespaceArtilleryConsoleUiState? _state;
    private readonly Dictionary<NetEntity, Button> _targetButtons = new();
    private string? _targetsKey;
    private TimeSpan? _armedAt;

    public BluespaceArtilleryConsoleWindow()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        BuildHelp.SetMessage(FormattedMessage.FromMarkupPermissive(Loc.GetString("bsa-console-build-help")));
        BuildButton.OnPressed += _ => OnBuild?.Invoke();
        ChargeButton.OnPressed += _ => OnCharge?.Invoke(!(_state?.Charging ?? false));
        FireButton.OnPressed += _ => OnFirePressed();
    }

    public void UpdateState(BluespaceArtilleryConsoleUiState state)
    {
        if (_state?.Target != state.Target)
            _armedAt = null;

        _state = state;

        BuildPanel.Visible = !state.Connected;
        CannonPanel.Visible = state.Connected;

        NoticePanel.Visible = !string.IsNullOrEmpty(state.Notice);
        NoticeLabel.SetMessage(FormattedMessage.FromUnformatted(state.Notice ?? string.Empty));

        if (!state.Connected)
            return;

        UpdateTargets(state);

        var target = state.Targets.FirstOrDefault(t => t.Entity == state.Target);
        TargetLabel.Text = target != null
            ? Loc.GetString("bsa-console-target-value", ("name", target.Name), ("location", target.Location))
            : Loc.GetString("bsa-console-target-none");

        ChargeBar.Value = state.Charge;
        ChargePercentLabel.Text = Loc.GetString("bsa-console-charge-value", ("percent", (int) (state.Charge * 100)));
        PowerLabel.Text = state.Charging
            ? Loc.GetString("bsa-console-power", ("received", FormatPower(state.ReceivedPower)), ("draw", FormatPower(state.DrawRate)))
            : string.Empty;

        ChargeButton.Text = Loc.GetString(state.Charging ? "bsa-console-stop-charge" : "bsa-console-start-charge");
        ChargeButton.Disabled = state.Charge >= 1f;
        UpdateFireButton();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_state is not { Connected: true })
            return;

        var left = _state.CooldownEnd - _timing.CurTime;
        CooldownLabel.Text = left > TimeSpan.Zero
            ? Loc.GetString("bsa-console-cooldown", ("time", $"{(int) left.TotalMinutes:00}:{left.Seconds:00}"))
            : Loc.GetString("bsa-console-cooldown-ready");

        UpdateFireButton();
    }

    private bool CanFire()
        => _state != null
            && _state.Charge >= 1f
            && _state.Target != null
            && _state.CooldownEnd <= _timing.CurTime;

    private void OnFirePressed()
    {
        var now = _timing.CurTime;
        if (_armedAt is not { } armed || now > armed + ConfirmWindow)
        {
            _armedAt = now;
            UpdateFireButton();
            return;
        }

        if (now < armed + ConfirmDelay)
            return;

        _armedAt = null;
        OnFire?.Invoke();
        UpdateFireButton();
    }

    private void UpdateFireButton()
    {
        var canFire = CanFire();
        if (!canFire || (_armedAt is { } armed && _timing.CurTime > armed + ConfirmWindow))
            _armedAt = null;

        FireButton.Disabled = !canFire;
        FireButton.Text = Loc.GetString(_armedAt != null ? "bsa-console-fire-confirm" : "bsa-console-fire");
    }

    private void UpdateTargets(BluespaceArtilleryConsoleUiState state)
    {
        var ordered = state.Targets.OrderByDescending(t => t.TestSite).ToList();
        var key = string.Join('\n', ordered.Select(t => $"{t.Entity}|{t.Name}|{t.Location}|{t.TestSite}"));

        if (key != _targetsKey)
        {
            _targetsKey = key;
            RebuildTargets(ordered);
        }

        foreach (var (entity, button) in _targetButtons)
            button.Pressed = entity == state.Target;
    }

    private void RebuildTargets(List<BluespaceArtilleryTargetState> targets)
    {
        TargetList.RemoveAllChildren();
        _targetButtons.Clear();

        if (targets.Count == 0)
        {
            TargetList.AddChild(new Label
            {
                Text = Loc.GetString("bsa-console-no-targets"),
                StyleClasses = { StyleClass.LabelWeak },
            });
            return;
        }

        string? location = null;
        foreach (var target in targets)
        {
            var group = target.TestSite ? Loc.GetString("bsa-console-test-sites") : target.Location;
            if (group != location)
            {
                location = group;
                TargetList.AddChild(new Label
                {
                    Text = group,
                    StyleClasses = { StyleClass.LabelKeyText },
                    Margin = new Thickness(0, TargetList.ChildCount == 0 ? 0 : 8, 0, 2),
                });
            }

            var button = new Button
            {
                Text = target.Name,
                ToggleMode = true,
                ClipText = true,
                StyleClasses = { StyleClass.ButtonSquare },
            };
            var entity = target.Entity;
            button.OnPressed += _ => OnSelectTarget?.Invoke(entity);
            _targetButtons[entity] = button;
            TargetList.AddChild(button);
        }
    }

    private static string FormatPower(float watts)
        => watts >= 1_000_000f
            ? $"{watts / 1_000_000f:0.##} MW"
            : $"{watts / 1000f:0.#} kW";
}
