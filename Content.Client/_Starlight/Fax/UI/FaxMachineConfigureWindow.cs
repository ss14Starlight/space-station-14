using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._Starlight.Fax;
using Content.Shared.EntityTable.EntitySelectors;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Starlight.Fax.UI;

[GenerateTypedNameReferences]
public sealed partial class FaxMachineConfigureWindow : FancyWindow
{
    public Action<string>? OnNameChanged;
    public Action<string>? OnGroupSelected;
    public Action<int>? OnOrderChanged;

    public FaxMachineConfigureWindow()
    {
        RobustXamlLoader.Load(this);

        NameEdit.OnTextChanged += args => OnNameChanged?.Invoke(args.Text);
        GroupSelector.OnItemSelected += args =>
        {
            GroupSelector.SelectId(args.Id);
            OnGroupSelected?.Invoke((string) GroupSelector.SelectedMetadata!);
        };
        OrderSpinBox.ValueChanged += args => OnOrderChanged?.Invoke(args.Value);
    }

    public void SetName(string name)
    {
        NameEdit.Text = name;
    }

    public void SetGroupings(IEnumerable<FaxGroupPrototype> groupings)
    {
        GroupSelector.Clear();
        foreach (var group in groupings.OrderBy(g => g.Order))
        {
            GroupSelector.AddItem(Loc.GetString(group.Name), group.ID.GetHashCode());
            GroupSelector.SetItemMetadata(GroupSelector.ItemCount - 1, group.ID);
        }
    }

    public void SetSelectedGrouping(string selectedGrouping)
    {
        // TODO
    }

    public void SetOrder(int order)
    {
        OrderSpinBox.Value = order;
    }
}
