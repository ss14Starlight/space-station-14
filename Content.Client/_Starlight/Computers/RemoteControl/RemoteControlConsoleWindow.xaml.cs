            var localMousePosition = (_remoteMouseScreenPosition - (Vector2)_remoteSpeechBubbleRoot.GlobalPixelPosition)
                / _remoteSpeechBubbleRoot.UIScale;
            LayoutContainer.SetPosition(cursor, localMousePosition - (cursor.Size / 2));
        }
    }

