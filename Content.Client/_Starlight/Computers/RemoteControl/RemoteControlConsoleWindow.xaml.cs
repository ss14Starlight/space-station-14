    private void OnFirstChanceKeyEvent(KeyEventArgs args, KeyEventType type)
    {
        var activeContext = _inputManager.Contexts.ActiveContext;
        var functionAvailable =
            activeContext.FunctionExistsHierarchy(ContentKeyFunctions.ReleasePulledObject);
        var focusedControl = IoCManager.Resolve<IUserInterfaceManager>().KeyboardFocused;
        var controlledEntity = _remoteControl.ControlledEntity;
        var dropBindings = _inputManager.GetKeyBindings(ContentKeyFunctions.Drop);
        var throwBindings = _inputManager.GetKeyBindings(ContentKeyFunctions.ThrowItemInHand);
        var releasePulledObjectBindings = _inputManager.GetKeyBindings(ContentKeyFunctions.ReleasePulledObject);
        var dropFunctionAvailable = activeContext.FunctionExistsHierarchy(ContentKeyFunctions.Drop);
        var throwFunctionAvailable =
            activeContext.FunctionExistsHierarchy(ContentKeyFunctions.ThrowItemInHand);

        foreach (var binding in releasePulledObjectBindings)
        {
            if (binding.BaseKey != args.Key)
                continue;

            var modifiersMatch =
                IsModifierPressed(binding.Mod1, args.Key) &&
                IsModifierPressed(binding.Mod2, args.Key) &&
                IsModifierPressed(binding.Mod3, args.Key);
            var canHandle = functionAvailable &&
                modifiersMatch &&
                controlledEntity is not null &&
                focusedControl is null &&
                !args.Handled;

            var moreSpecificHandActionMatches = dropBindings
                .Where(action => dropFunctionAvailable
                    && MatchesHandActionBinding(action, args.Key)
                    && IsStrictSubCombo(binding, action))
                .Concat(throwBindings.Where(action => throwFunctionAvailable
                    && MatchesHandActionBinding(action, args.Key)
                    && IsStrictSubCombo(binding, action)))
                .OrderByDescending(CountModifiers)
                .FirstOrDefault();
            var moreSpecificHandActionAllowsSubCombinations =
                moreSpecificHandActionMatches?.AllowSubCombs == true;
            var sameComboHandAction =
                (dropFunctionAvailable && dropBindings.Any(action =>
                    MatchesHandActionBinding(action, args.Key) && IsSameKeyCombo(binding, action))) ||
                (throwFunctionAvailable && throwBindings.Any(action =>
                    MatchesHandActionBinding(action, args.Key) && IsSameKeyCombo(binding, action)));

            if (!canHandle || type == KeyEventType.Up)
                continue;

            if (moreSpecificHandActionMatches is not null && !moreSpecificHandActionAllowsSubCombinations)
                continue;

            if (sameComboHandAction || moreSpecificHandActionAllowsSubCombinations)
            {
                if (type == KeyEventType.Down)
                    RemoteReleasePulledObjectPressed?.Invoke();

                return;
            }

            args.Handle();

            if (type == KeyEventType.Down)
                RemoteReleasePulledObjectPressed?.Invoke();

            return;
        }
    }

    private bool IsModifierPressed(Keyboard.Key modifier, Keyboard.Key eventKey)
        => modifier == Keyboard.Key.Unknown || modifier == eventKey || _inputManager.IsKeyDown(modifier);

    private bool MatchesHandActionBinding(IKeyBinding binding, Keyboard.Key eventKey)
        => binding.BaseKey == eventKey &&
            IsModifierPressed(binding.Mod1, eventKey) &&
            IsModifierPressed(binding.Mod2, eventKey) &&
            IsModifierPressed(binding.Mod3, eventKey);

    private static int CountModifiers(IKeyBinding binding)
    {
        var count = 0;
        if (binding.Mod1 != Keyboard.Key.Unknown)
            count++;
        if (binding.Mod2 != Keyboard.Key.Unknown && binding.Mod2 != binding.Mod1)
            count++;
        if (binding.Mod3 != Keyboard.Key.Unknown && binding.Mod3 != binding.Mod1 && binding.Mod3 != binding.Mod2)
            count++;

        return count;
    }

    private static bool IsSameKeyCombo(IKeyBinding first, IKeyBinding second)
        => first.BaseKey == second.BaseKey &&
            ContainsModifiers(first, second) &&
            ContainsModifiers(second, first);

    private static bool IsStrictSubCombo(IKeyBinding subCombo, IKeyBinding superCombo)
        => subCombo.BaseKey == superCombo.BaseKey &&
            ContainsModifiers(superCombo, subCombo) &&
            HasAdditionalModifiers(superCombo, subCombo);

    private static bool ContainsModifiers(IKeyBinding superset, IKeyBinding subset)
        => IsModifierContained(subset.Mod1, superset) &&
            IsModifierContained(subset.Mod2, superset) &&
            IsModifierContained(subset.Mod3, superset);

    private static bool IsModifierContained(Keyboard.Key modifier, IKeyBinding binding)
        => modifier == Keyboard.Key.Unknown ||
            binding.Mod1 == modifier ||
            binding.Mod2 == modifier ||
            binding.Mod3 == modifier;

    private static bool HasAdditionalModifiers(IKeyBinding superset, IKeyBinding subset)
        => HasAdditionalModifier(superset.Mod1, subset) ||
            HasAdditionalModifier(superset.Mod2, subset) ||
            HasAdditionalModifier(superset.Mod3, subset);

    private static bool HasAdditionalModifier(Keyboard.Key modifier, IKeyBinding subset)
        => modifier != Keyboard.Key.Unknown && !IsModifierContained(modifier, subset);

    private bool HandleRemoteHandCycle(RemoteControlHandAction action)
    {
        if (_remoteControl.ControlledEntity is null || !RemoteView.Visible)
            return false;

        if (_gameTiming.IsFirstTimePredicted)
            RemoteHandPressed?.Invoke(string.Empty, action);

        return true;
    }

    private sealed class RemoteToggleKnockdownInputHandler(RemoteControlConsoleWindow window) : InputCmdHandler
    {
        public override bool FireOutsidePrediction => true;

        public override bool HandleCmdMessage(IEntityManager entManager, ICommonSession? session,
            IFullInputCmdMessage message)
        {
            if (window._remoteControl.ControlledEntity is null)
                return false;

            if (message.State == BoundKeyState.Down
                && (!window._gameTiming.InPrediction || window._gameTiming.IsFirstTimePredicted))
                window.RemoteToggleKnockdownPressed?.Invoke();

            return true;
        }
    }

    private sealed class RemoteHandCycleInputHandler(
        RemoteControlConsoleWindow window,
        RemoteControlHandAction action) : InputCmdHandler
    {
        public override bool HandleCmdMessage(IEntityManager entManager, ICommonSession? session,
            IFullInputCmdMessage message)
        {
            if (message.State != BoundKeyState.Down)
                return window._remoteControl.ControlledEntity is not null && window.RemoteView.Visible;

            return window.HandleRemoteHandCycle(action);
        }
    }

