using System.Globalization;
using Content.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Client.AutoGenerated;

namespace Content.Client._Starlight.GasMining.Ui;

/// <summary>
/// Client-side UI used to control a gas extractor
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class GasExtractorWindow : FancyWindow
{
    public event Action<bool>? ToggleStatusButtonPressed;
    public event Action<string>? ExtractorExtractionRateChanged;

    private float MaxMolesExtractedPerSecond = 200f;

    public GasExtractorWindow()
    {
        RobustXamlLoader.Load(this);

        ToggleStatusButton.OnToggled += _ => ToggleStatusButtonPressed?.Invoke(ToggleStatusButton.Pressed);

        ExtractorExtractionRateInput.OnTextChanged += _ => SetExtractionRateButton.Disabled = false;
        SetExtractionRateButton.OnPressed += _ =>
        {
            ExtractorExtractionRateChanged?.Invoke(ExtractorExtractionRateInput.Text ??= "");
            SetExtractionRateButton.Disabled = true;
        };

        SetMaxRateButton.OnPressed += _ =>
        {
            ExtractorExtractionRateInput.Text = MaxMolesExtractedPerSecond.ToString(CultureInfo.CurrentCulture);
            SetExtractionRateButton.Disabled = false;
        };
    }

    public void SetExtractionRate(float rate) => ExtractorExtractionRateInput.Text = rate.ToString(CultureInfo.CurrentCulture);

    public void SetExtractorStatus(bool enabled) => ToggleStatusButton.Pressed = enabled;

    public void SetMaxExtractionRate(float maxExtractionRate) => MaxMolesExtractedPerSecond = maxExtractionRate;
}
