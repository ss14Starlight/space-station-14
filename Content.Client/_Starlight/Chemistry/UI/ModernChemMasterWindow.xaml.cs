    public void DirtyData(ChemMasterUIDirtyFlags flags) => _dirtyFlags |= flags;

    protected override void FrameUpdate(FrameEventArgs args)
    {
        // we don't get an event when the contents of the contained container update
        // so we'll just poll it for when it changes and set storage dirty
        var owner = _owner;
        if (owner.Valid)
        {
            int? count = null;
            var outputContainer = _itemSlotsSystem.GetItemOrNull(_owner, SharedChemMaster.OutputSlotName);
            if (_entityManager.TryGetComponent(outputContainer, out StorageComponent? storage))
                count = storage.Container.Count;

            if (count != _lastOutputItemCount)
            {
                _lastOutputItemCount = count;
                _dirtyFlags |= ChemMasterUIDirtyFlags.Inventory;
            }
        }

        if (_dirtyFlags != 0)
        {
            UpdateData(_dirtyFlags);
            _dirtyFlags = 0;
        }
    }

    private void UpdateData(ChemMasterUIDirtyFlags flags)
    {
        var owner = _owner;
        if (!owner.IsValid() || !_entityManager.TryGetComponent<ChemMasterComponent>(owner, out var chemMaster))
            return;

        if (!_solutionContainerSystem.TryGetSolution(owner, SharedChemMaster.BufferSolutionName, out _, out var bufferSolution))
            return;

        bool outputSourceChanged = false;
        bool bufferReagentsDirty = false;
        bool sortingChanged = false;

        if ((flags & ChemMasterUIDirtyFlags.Settings) != 0)
        {
            // PillType
            PillTypeButtons[chemMaster.PillType].Pressed = true;
            PillTypeButtonsClassic[chemMaster.PillType].Pressed = true;

            // Mode
            if (chemMaster.Mode != _mode)
            {
                _mode = chemMaster.Mode;
                BufferTransferButton.Pressed = chemMaster.Mode == ChemMasterMode.Transfer;
                BufferDiscardButton.Pressed = chemMaster.Mode == ChemMasterMode.Discard;
                BufferTransferButtonClassic.Pressed = chemMaster.Mode == ChemMasterMode.Transfer;
                BufferDiscardButtonClassic.Pressed = chemMaster.Mode == ChemMasterMode.Discard;
            }

            // SortingType
            if (chemMaster.SortingType != _sortingType)
            {
                _sortingType = chemMaster.SortingType;
                var sortLabel = chemMaster.SortingType switch
                {
                    ChemMasterSortingType.Alphabetical => Loc.GetString("chem-master-window-sort-type-alphabetical"),
                    ChemMasterSortingType.Quantity => Loc.GetString("chem-master-window-sort-type-quantity"),
                    ChemMasterSortingType.Latest => Loc.GetString("chem-master-window-sort-type-latest"),
                    _ => Loc.GetString("chem-master-window-sort-type-none"),
                };

                BufferSortButton.Text = sortLabel;
                BufferSortButtonClassic.Text = sortLabel;

                bufferReagentsDirty = true;
                sortingChanged = true;
            }

            // DrawSource
            if (chemMaster.DrawSource != _drawSource)
            {
                _drawSource = chemMaster.DrawSource;

                OutputBufferDraw.Pressed = chemMaster.DrawSource == ChemMasterDrawSource.Internal;
                OutputBeakerDraw.Pressed = chemMaster.DrawSource == ChemMasterDrawSource.External;
                OutputBufferDrawClassic.Pressed = chemMaster.DrawSource == ChemMasterDrawSource.Internal;
                OutputBeakerDrawClassic.Pressed = chemMaster.DrawSource == ChemMasterDrawSource.External;

                outputSourceChanged = true;
            }

            // TransferAmount
            SetSelectedAmount(chemMaster.TransferAmount);
        }

        // inputContainer is the inserted beaker
        if ((flags & (ChemMasterUIDirtyFlags.Solutions | ChemMasterUIDirtyFlags.Inventory)) != 0)
        {
            var inputContainer = _itemSlotsSystem.GetItemOrNull(owner, SharedChemMaster.InputSlotName);
            var inputContainerInfo = BuildInputContainerInfo(inputContainer);

            if (!ContainerInfo.DeepEquals(inputContainerInfo, _prevInputContainerInfo))
            {
                _prevInputContainerInfo = inputContainerInfo?.DeepClone();

                // beaker view in modern and classic UIs
                BuildContainerUI(InputContainerInfo, inputContainerInfo, true, modernMode: true);
                BuildContainerUI(InputContainerInfoClassic, inputContainerInfo, true, modernMode: false);

                // output tab view should update when source is set to external
                if (chemMaster.DrawSource == ChemMasterDrawSource.External)
                {
                    outputSourceChanged = true;
                }

                InputEjectButton.Disabled = inputContainerInfo is null;
                InputEjectButtonClassic.Disabled = inputContainerInfo is null;
            }
        }

        // buffer UI
        if (bufferReagentsDirty || (flags & ChemMasterUIDirtyFlags.Solutions) != 0)
        {
            var bufferReagents = bufferSolution.Contents;
            var bufferCurrentVolume = bufferSolution.Volume;

            static bool ReagentsEqual(List<ReagentQuantity>? a, List<ReagentQuantity>? b)
            {
                if (a == null || b == null)
                    return a == b;

                if (a.Count != b.Count) return false;

                for (int i = 0; i < a.Count; i++)
                {
                    if (a[i] != b[i]) return false;
                }

                return true;
            }

            if (sortingChanged || !ReagentsEqual(bufferReagents, _prevBufferContents))
            {
                _prevBufferContents ??= [];
                _prevBufferContents.Clear();
                _prevBufferContents.AddRange(bufferReagents);

                BuildBufferUi(chemMaster, bufferSolution);

                if (chemMaster.DrawSource == ChemMasterDrawSource.Internal)
                {
                    outputSourceChanged = true;
                }
            }
        }

        // the output source is either the buffer or beaker, depending on the mode
        if (outputSourceChanged)
        {
            // the original code passed modern: false to both, including the modern...
            // gonna just leave it as it is for now
            BuildOutputLeftContainer(OutputInputContainerInfo, chemMaster, bufferSolution, _prevInputContainerInfo, modernMode: false);
            BuildOutputLeftContainer(OutputInputContainerInfoClassic, chemMaster, bufferSolution, _prevInputContainerInfo, modernMode: false);
        }

        // the output container is the inserted pill bottle, patch pack or bottle
        bool outputContainerChanged = false;
        if ((flags & ChemMasterUIDirtyFlags.Inventory) != 0)
        {
            var outputContainer = _itemSlotsSystem.GetItemOrNull(owner, SharedChemMaster.OutputSlotName);
            var outputContainerInfo = BuildOutputContainerInfo(outputContainer);

            if (!ContainerInfo.DeepEquals(outputContainerInfo, _prevOutputContainerInfo))
            {
                outputContainerChanged = true;

                _prevOutputContainerInfo = outputContainerInfo?.DeepClone();

                // when a different pill bottle / patch box is inserted,
                // allow its container label to be populated again.
                var currentContainer = outputContainerInfo?.Uid;
                if (currentContainer != _lastOutputContainer)
                {
                    _lastOutputContainer = currentContainer;
                    _containerLabelManuallySet = false;
                    ContainerLabelLine = "";
                }

                // Until the user explicitly changes the container label, keep it
                // synchronized with either the existing container label or the
                // automatically generated item label.
                if (outputContainerInfo is not null &&
                    !_containerLabelManuallySet)
                {
                    var existingLabel = outputContainerInfo.ContainerLabel;

                    ContainerLabelLine = !string.IsNullOrEmpty(existingLabel)
                        ? existingLabel
                        : LabelLine;
                }

                BuildContainerUI(OutputContainerInfo, outputContainerInfo, false, modernMode: true, "chem-master-window-no-output-container-loaded-text", truncateName: false);
                BuildContainerUI(OutputContainerInfoClassic, outputContainerInfo, false, modernMode: false, "chem-master-window-no-output-container-loaded-text", truncateName: false);

                OutputEjectButton.Disabled = OutputEjectButtonClassic.Disabled = outputContainerInfo is null;

                var containerFull = outputContainerInfo != null && outputContainerInfo.CurrentVolume >= outputContainerInfo.MaxVolume;
                var bottleFull = outputContainerInfo?.Reagents != null && containerFull;
                var pillFull = outputContainerInfo?.PillEntities != null && containerFull;
                var patchFull = outputContainerInfo?.PatchEntities != null && containerFull;

                CreateBottleButton.Disabled = CreateBottleButtonClassic.Disabled = outputContainerInfo?.Reagents == null || bottleFull;
                CreateBottleButton.ToolTip = CreateBottleButtonClassic.ToolTip = !CreateBottleButton.Disabled ? null : bottleFull ?
                    Loc.GetString("chem-master-window-create-bottle-full-tooltip") : Loc.GetString("chem-master-window-create-bottle-tooltip");

                CreatePillButton.Disabled = CreatePillButtonClassic.Disabled = outputContainerInfo?.PillEntities == null || pillFull;
                CreatePillButton.ToolTip = CreatePillButtonClassic.ToolTip = !CreatePillButton.Disabled ? null : pillFull ?
                    Loc.GetString("chem-master-window-create-pill-full-tooltip") : Loc.GetString("chem-master-window-create-pill-tooltip");

                CreatePatchButton.Disabled = CreatePatchButtonClassic.Disabled = outputContainerInfo?.PatchEntities == null || patchFull;
                CreatePatchButton.ToolTip = CreatePatchButtonClassic.ToolTip = !CreatePatchButton.Disabled ? null : patchFull ?
                    Loc.GetString("chem-master-window-create-patch-full-tooltip") : Loc.GetString("chem-master-window-create-patch-tooltip");
            }
        }

        // dosage calculations
        if (outputContainerChanged || outputSourceChanged)
        {
            var output = _prevOutputContainerInfo;
            var remainingCapacity = output is null ? 0 : (output.MaxVolume - output.CurrentVolume).Int();
            var holdsReagents = output?.Reagents != null;
            var itemNumberMax = holdsReagents ? 0 : remainingCapacity;
            var bottleAmountMax = holdsReagents ? remainingCapacity : 0;
            var outputVolume = chemMaster.DrawSource switch
            {
                ChemMasterDrawSource.Internal => bufferSolution.Volume.Int(),
                ChemMasterDrawSource.External => _prevInputContainerInfo?.CurrentVolume.Int() ?? 0,
                _ => 0,
            };

            // Modern layout.
            PillDosage.Value = (int)Math.Min(outputVolume, chemMaster.PillDosageLimit);
            PatchDosage.Value = (int)Math.Min(outputVolume, chemMaster.PatchDosageLimit);

            PillNumber.IsValid = x => x >= 0 && x <= itemNumberMax;
            PillDosage.IsValid = x => x > 0 && x <= chemMaster.PillDosageLimit;
            PatchNumber.IsValid = x => x >= 0 && x <= itemNumberMax;
            PatchDosage.IsValid = x => x > 0 && x <= chemMaster.PatchDosageLimit;
            BottleDosage.IsValid = x => x >= 0 && x <= bottleAmountMax;

            PillNumber.Value = PillDosage.Value > 0
                ? Math.Min(outputVolume / PillDosage.Value, itemNumberMax)
                : 0;
            PatchNumber.Value = PatchDosage.Value > 0
                ? Math.Min(outputVolume / PatchDosage.Value, itemNumberMax)
                : 0;
            BottleDosage.Value = Math.Min(bottleAmountMax, outputVolume);

            // Classic layout.
            PillDosageClassic.Value = (int)Math.Min(outputVolume, chemMaster.PillDosageLimit);
            PatchDosageClassic.Value = (int)Math.Min(outputVolume, chemMaster.PatchDosageLimit);

            PillNumberClassic.IsValid = x => x >= 0 && x <= itemNumberMax;
            PillDosageClassic.IsValid = x => x > 0 && x <= chemMaster.PillDosageLimit;
            PatchNumberClassic.IsValid = x => x >= 0 && x <= itemNumberMax;
            PatchDosageClassic.IsValid = x => x > 0 && x <= chemMaster.PatchDosageLimit;
            BottleDosageClassic.IsValid = x => x >= 0 && x <= bottleAmountMax;

            PillNumberClassic.Value = PillDosageClassic.Value > 0
                ? Math.Min(outputVolume / PillDosageClassic.Value, itemNumberMax)
                : 0;
            PatchNumberClassic.Value = PatchDosageClassic.Value > 0
                ? Math.Min(outputVolume / PatchDosageClassic.Value, itemNumberMax)
                : 0;
            BottleDosageClassic.Value = Math.Min(bottleAmountMax, outputVolume);
        }

        // output valve toggle
        if ((flags & ChemMasterUIDirtyFlags.PlumbingOutput) != 0)
        {
            var valveOpen = _entityManager.TryGetComponent<PlumbingOutletComponent>(owner, out var plumbingOutlet) && plumbingOutlet.Enabled;
            var valveText = Loc.GetString(valveOpen
                ? "chem-master-window-valve-open"
                : "chem-master-window-valve-closed");

            ValveButton.Text = valveText;
            ValveButtonClassic.Text = valveText;
        }

        // output source is either the buffer or the beaker (input slot) depending on mode
        if (outputSourceChanged)
        {
            var reagents = chemMaster.DrawSource switch
            {
                ChemMasterDrawSource.Internal => bufferSolution.Contents,
                ChemMasterDrawSource.External => _prevInputContainerInfo?.Reagents ?? [],
                _ => throw new($"Chemmaster {owner} draw source is not set"),
            };

            if (reagents.Count == 0)
                LabelLine = string.Empty;
            else
            {
                var reagent = reagents.MinBy(r => r.Quantity).Reagent;
                _prototypeManager.TryIndex(reagent.Prototype, out var proto);
                LabelLine = proto?.LocalizedName ?? string.Empty;
            }
        }
    }

    private void BuildBufferUi(ChemMasterComponent chemMaster, Solution bufferSolution)
    {
        BufferInfo.Children.Clear();
        BufferInfoClassic.Children.Clear();

        if (bufferSolution.Contents.Count == 0)
        {
            var emptyLabel = new Label { Text = Loc.GetString("chem-master-window-buffer-empty-text") };
            var emptyLabelClassic = new Label { Text = Loc.GetString("chem-master-window-buffer-empty-text") };
            BufferInfo.Children.Add(emptyLabel);
            BufferInfoClassic.Children.Add(emptyLabelClassic);
            return;
        }

        // Buffer volume header row
        void AddBufferHeader(BoxContainer target)
        {
            var hbox = new BoxContainer { Orientation = LayoutOrientation.Horizontal };
            hbox.AddChild(new Label { Text = $"{Loc.GetString("chem-master-window-buffer-label")} " });
            hbox.AddChild(new Label
            {
                Text = $"{bufferSolution.Volume}u",
                StyleClasses = { StyleClass.LabelWeak }
            });
            target.AddChild(hbox);
        }
        AddBufferHeader(BufferInfo);
        AddBufferHeader(BufferInfoClassic);

        var reagentList = new List<(ReagentId reagentId, string name, Color color, FixedPoint2 quantity)>();
        foreach (var (reagent, quantity) in bufferSolution.Contents)
        {
            _prototypeManager.TryIndex(reagent.Prototype, out ReagentPrototype? proto);
            var name = proto?.LocalizedName ?? Loc.GetString("chem-master-window-unknown-reagent-text");
            var reagentColor = proto?.SubstanceColor ?? default(Color);
            reagentList.Add((reagent, name, reagentColor, quantity));
        }

        reagentList = chemMaster.SortingType switch
        {
            ChemMasterSortingType.Alphabetical => reagentList.OrderBy(x => x.name).ToList(),
            ChemMasterSortingType.Quantity => reagentList.OrderByDescending(x => x.quantity).ToList(),
            ChemMasterSortingType.Latest => Enumerable.Reverse(reagentList).ToList(),
            _ => reagentList
        };

        var rowCount = 0;
        foreach (var (reagentId, name, color, quantity) in reagentList)
        {
            BufferInfo.Children.Add(BuildReagentRow(color, rowCount, name, reagentId, quantity, true, true, modernMode: true));
            BufferInfoClassic.Children.Add(BuildReagentRow(color, rowCount, name, reagentId, quantity, true, true, modernMode: false));
            rowCount++;
        }

        if (!string.IsNullOrEmpty(SearchBar.Text))
            UpdateReagentPrototypes(SearchBar.Text);
    }

    /// <summary>
    /// Builds the pill type selector for one layout.
    /// </summary>
    private static Button[] BuildPillTypeButtons(GridContainer grid, SpriteSystem sprite)
    {
        const int PillTypeCount = 20;
        var resourcePath = new ResPath(PillsRsiPath);
        var pillTypeGroup = new ButtonGroup();
        var buttons = new Button[PillTypeCount];

        for (uint i = 0; i < buttons.Length; i++)
        {
            var styleBase = StyleClass.ButtonOpenBoth;
            if (i == 9)
                styleBase = StyleClass.ButtonOpenLeft;
            else if (i == 10)
                styleBase = StyleClass.ButtonOpenRight;

            buttons[i] = new Button
            {
                Access = AccessLevel.Public,
                StyleClasses = { styleBase },
                MaxSize = new Vector2(42, 28),
                Group = pillTypeGroup,
            };

            var specifier = new SpriteSpecifier.Rsi(resourcePath, "pill" + (i + 1));
            var pillTypeTexture = new TextureRect
            {
                Texture = sprite.Frame0(specifier),
                TextureScale = new Vector2(1.75f, 1.75f),
                Stretch = TextureRect.StretchMode.KeepCentered,
            };

            buttons[i].AddChild(pillTypeTexture);
            grid.AddChild(buttons[i]);
        }

        return buttons;
    }

    // Window size referenced from MinSize attribute
    // We specify the Classic MinSize here since the original value is in an upstream file and it needs to be a bit longer for spacing reasons
    // Amount of characters before truncating name in modern layout
    // Amount of characters before truncating name in classic layout
    private static bool IsInCustomAmountRange(string s) => int.TryParse(s, out var v) && v > 0 && v <= 1000;

    /// <summary>
    /// Truncates a reagent name with an ellipsis if it exceeds the max length.
    /// Returns the display name and a tooltip with the full name. No tooltip is shown when untruncated.
    /// </summary>
    private static (string display, string? toolTip) TruncateReagentName(string name, int maxLength)
    {
        if (name.Length <= maxLength)
            return (name, null);

        return (name[..maxLength].TrimEnd() + "...", name);
    }

    private void ApplyLayout()
    {
        ModernTabs.Visible = !_classicMode;
        ClassicTabs.Visible = _classicMode;

        var targetSize = _classicMode ? _classicMinSize : _modernMinSize;
        MinSize = targetSize;
        // Force window to specified dimensions, MinSize alone doesn't shrink an already larger window
        SetSize = targetSize;
        if (!_classicMode)
        {
            CustomAmountButton.Disabled = !IsCustomAmountValid(CustomAmountLineEdit.Text);
        }
        else
        {
            UpdateClassicCustomButtons();
        }
    }

    /// <summary>
    /// Builds a 2x5 amount selection grid into the given GridContainer.
    /// Both modern tabs get their own grid instance but share the _selectedAmount state.
    /// </summary>
    private void BuildAmountGrid(GridContainer grid)
    {
        var amountGroup = new ButtonGroup();

        for (var idx = 0; idx < _amountConfigs.Length; idx++)
        {
            var (label, amount) = _amountConfigs[idx];
            var btn = new Button
            {
                Access = AccessLevel.Public,
                Text = label,
                ToggleMode = true,
                Group = amountGroup,
                MinSize = new Vector2(46, 0),
                Pressed = !_customSelected && amount == _selectedAmount,
                StyleClasses = { idx == 8 ? StyleClass.ButtonOpenRight : StyleClass.ButtonOpenBoth },
            };

            var capturedAmount = amount;
            btn.OnPressed += _ =>
            {
                _customSelected = false;
                CustomAmountButton.Pressed = false;
                SaveCustomPerChemMaster();
                OnAmountSelected?.Invoke(capturedAmount);
            };

            grid.AddChild(btn);
        }
    }

    private void BuildContainerUI(Control control, ContainerInfo? info, bool addReagentButtons, bool modernMode, string emptyLoc = "chem-master-window-no-container-loaded-text", bool truncateName = true)
    {
        control.Children.Clear();

        if (info is null)
        {
            control.Children.Add(new Label { Text = Loc.GetString(emptyLoc) });
            return;
        }

        control.Children.Add(new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            Children =
            {
                new Label { Text = $"{info.DisplayName}: " },
                new Label
                {
                    Text = $"{info.CurrentVolume}/{info.MaxVolume}",
                    StyleClasses = { StyleClass.LabelWeak }
                }
            }
        });

        var rowCount = 0;

        if (info.PillEntities != null)
        {
            foreach (var (id, quantity) in info.PillEntities)
            {
                control.Children.Add(BuildReagentRow(
                    default,
                    rowCount++,
                    id,
                    default,
                    quantity,
                    false,
                    addReagentButtons,
                    modernMode,
                    truncateName: truncateName));
            }
        }

        if (info.PatchEntities != null)
        {
            foreach (var (id, quantity) in info.PatchEntities)
            {
                control.Children.Add(BuildReagentRow(
                    default,
                    rowCount++,
                    id,
                    default,
                    quantity,
                    false,
                    addReagentButtons,
                    modernMode,
                    truncateName: truncateName));
            }
        }

        if (info.Reagents != null)
        {
            foreach (var reagent in info.Reagents)
            {
                _prototypeManager.TryIndex(reagent.Reagent.Prototype, out ReagentPrototype? proto);
                var name = proto?.LocalizedName ?? Loc.GetString("chem-master-window-unknown-reagent-text");
                var reagentColor = proto?.SubstanceColor ?? default(Color);
                control.Children.Add(BuildReagentRow(reagentColor, rowCount++, name, reagent.Reagent, reagent.Quantity, false, addReagentButtons, modernMode, truncateName: truncateName));
            }
        }
    }

    private void BuildOutputLeftContainer(Control control, ChemMasterComponent chemMaster, Solution bufferSolution, ContainerInfo? inputContainerInfo, bool modernMode)
    {
        if (chemMaster.DrawSource == ChemMasterDrawSource.Internal)
        {
            // Show buffer contents when packaging from buffer
            control.Children.Clear();
            if (bufferSolution.Contents.Count == 0)
            {
                control.Children.Add(new Label { Text = Loc.GetString("chem-master-window-buffer-empty-text") });
                return;
            }

            control.Children.Add(new BoxContainer
            {
                Orientation = LayoutOrientation.Horizontal,
                Children =
                {
                    new Label { Text = $"{Loc.GetString("chem-master-window-buffer-label")} " },
                    new Label { Text = $"{bufferSolution.Volume}u", StyleClasses = { StyleClass.LabelWeak } }
                }
            });

            var rowCount = 0;
            foreach (var (reagent, quantity) in bufferSolution.Contents)
            {
                _prototypeManager.TryIndex(reagent.Prototype, out ReagentPrototype? proto);
                var name = proto?.LocalizedName ?? Loc.GetString("chem-master-window-unknown-reagent-text");
                control.Children.Add(BuildReagentRow(default, rowCount++, name, reagent, quantity, true, false, modernMode, truncateName: false));
            }
        }
        else
        {
            BuildContainerUI(control, inputContainerInfo, false, modernMode, "chem-master-window-no-input-container-loaded-text", truncateName: false);
        }
    }

    private Control BuildReagentRow(Color reagentColor, int rowCount, string name, ReagentId reagent, FixedPoint2 quantity, bool isBuffer, bool addReagentButtons, bool modernMode, bool truncateName = true)
    {
        var rowColor1 = Color.FromHex("#1B1B1E");
        var rowColor2 = Color.FromHex("#202025");
        var currentRowColor = (rowCount % 2 == 1) ? rowColor1 : rowColor2;
        var hasColor = reagentColor != default(Color) && addReagentButtons;

        if (modernMode && addReagentButtons)
        {
            // Truncate very long names to prevent UI issues.
            string? toolTip = null;
            if (truncateName)
                (name, toolTip) = TruncateReagentName(name, MaxReagentNameLength);

            // Modern: the entire row is a ReagentButton. Amount is read from the selected amount at click time. If custom amount is selected, send via custom message; otherwise use _selectedAmount.
            var rowBtn = new ReagentButton(string.Empty, _selectedAmount, reagent, isBuffer, StyleClass.ButtonSquare)
            {
                HorizontalExpand = true,
                ToolTip = toolTip, // Labels ignore the mouse, so the tooltip lives on the row button.
            };
            rowBtn.OnPressed += a => { if (_customSelected && _customAmount is { } c) OnCustomReagentButtonPressed?.Invoke(a, reagent, c, isBuffer); else { rowBtn.Amount = _selectedAmount; OnReagentButtonPressed?.Invoke(a, rowBtn); } };

            // Color row at the start of the button
            var row = new PanelContainer
            {
                MinSize = new Vector2(4, 30),
                Margin = new Thickness(-4, 0, 6, 0),
                VerticalAlignment = VAlignment.Center,
                PanelOverride = new StyleBoxFlat
                {
                    BackgroundColor = hasColor ? reagentColor : Color.Transparent,
                }
            };

            var inner = new BoxContainer
            {
                Orientation = LayoutOrientation.Horizontal,
                Children =
                {
                    row,
                    new Label { Text = $"{name}: " },
                    new Label
                    {
                        Text = $"{quantity}u",
                        StyleClasses = { StyleClass.LabelWeak }
                    },
                    new Control { HorizontalExpand = true },
                }
            };
            rowBtn.AddChild(inner);
            return rowBtn;
        }

        // Classic: striped PanelContainer with full per-row amount buttons
        if (reagentColor == default || !addReagentButtons)
            reagentColor = currentRowColor;

        // Truncate very long names to prevent UI issues.
        var classicName = name;
        string? classicToolTip = null;
        if (truncateName)
            (classicName, classicToolTip) = TruncateReagentName(name, MaxClassicReagentNameLength);

        var reagentButtonConstructors = CreateReagentTransferButtons(reagent, isBuffer, addReagentButtons);

        var rowContainer = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            Children =
            {
                new PanelContainer
                {
                    Name = "colorPanel",
                    VerticalExpand = true,
                    MinWidth = 4,
                    PanelOverride = new StyleBoxFlat { BackgroundColor = reagentColor },
                    Margin = new Thickness(0, 1, 4, 1)
                },
                new Label { Text = $"{classicName}: ", ToolTip = classicToolTip, MouseFilter = classicToolTip == null ? MouseFilterMode.Ignore : MouseFilterMode.Stop },
                new Label
                {
                    Text = $"{quantity}u",
                    StyleClasses = { StyleClass.LabelWeak }
                },
                new Control { HorizontalExpand = true },
            }
        };

        foreach (var btn in reagentButtonConstructors)
        {
            rowContainer.AddChild(btn);
        }

        return new PanelContainer
        {
            PanelOverride = new StyleBoxFlat(currentRowColor),
            Children = { rowContainer }
        };
    }

    /// <summary>
    /// Classic mode only: generates the full set of per-row amount buttons.
    /// Modern mode rows are buttons themselves - this is not called for them.
    /// </summary>
    private List<ReagentButton> CreateReagentTransferButtons(ReagentId reagent, bool isBuffer, bool addReagentButtons)
    {
        if (!addReagentButtons)
            return new List<ReagentButton>();

        // Classic: full button strip with # preceding 1 for custom amount
        var buttons = new List<ReagentButton>();

        var hashButton = new ReagentButton("#", ChemMasterReagentAmount.U1, reagent, isBuffer, StyleClass.ButtonOpenRight)
        {
            Disabled = !IsCustomAmountValid(CustomAmountLineEditClassic.Text)
        };
        hashButton.OnPressed += a => { if (IsCustomAmountValid(CustomAmountLineEditClassic.Text) && int.TryParse(CustomAmountLineEditClassic.Text, out var v)) OnCustomReagentButtonPressed?.Invoke(a, reagent, FixedPoint2.New(v), isBuffer); };
        buttons.Add(hashButton);

        var buttonConfigs = new (string text, ChemMasterReagentAmount amount, string styleClass)[]
        {
            ("1",   ChemMasterReagentAmount.U1,   StyleClass.ButtonOpenBoth),
            ("5",   ChemMasterReagentAmount.U5,   StyleClass.ButtonOpenBoth),
            ("10",  ChemMasterReagentAmount.U10,  StyleClass.ButtonOpenBoth),
            ("15",  ChemMasterReagentAmount.U15,  StyleClass.ButtonOpenBoth),
            ("20",  ChemMasterReagentAmount.U20,  StyleClass.ButtonOpenBoth),
            ("30",  ChemMasterReagentAmount.U30,  StyleClass.ButtonOpenBoth),
            ("40",  ChemMasterReagentAmount.U40,  StyleClass.ButtonOpenBoth),
            ("60",  ChemMasterReagentAmount.U60,  StyleClass.ButtonOpenBoth),
            ("120", ChemMasterReagentAmount.U120, StyleClass.ButtonOpenBoth),
            (Loc.GetString("chem-master-window-buffer-all-amount"), ChemMasterReagentAmount.All, StyleClass.ButtonOpenLeft),
        };

        foreach (var (text, amount, styleClass) in buttonConfigs)
        {
            buttons.Add(MakeReagentButton(text, amount, reagent, isBuffer, styleClass));
        }

        return buttons;
    }

    private void DeselectGrid()
    { foreach (var c in AmountGrid.Children) if (c is Button b) b.Pressed = false; }

    private void HandleCustomAmountTextChanged(LineEdit source, LineEdit target, bool isModern)
    {
        if (target.Text != source.Text)
            target.Text = source.Text;
        if (isModern)
            CustomAmountButton.Disabled = !IsCustomAmountValid(source.Text);
        if (_customSelected)
        {
            if (IsCustomAmountValid(source.Text) && int.TryParse(source.Text, out var v))
                _customAmount = FixedPoint2.New(v);
            else
            {
                _customAmount = null;
                _customSelected = false;
                if (isModern)
                    CustomAmountButton.Pressed = false;
            }
        }
        SaveCustomPerChemMaster();
        UpdateClassicCustomButtons();
    }

    private bool IsCustomAmountValid(string s) => !string.IsNullOrWhiteSpace(s) && IsInCustomAmountRange(s);

    private ReagentButton MakeReagentButton(string text, ChemMasterReagentAmount amount, ReagentId id, bool isBuffer, string styleClass)
    {
        var reagentTransferButton = new ReagentButton(text, amount, id, isBuffer, styleClass);
        reagentTransferButton.OnPressed += args
            => OnReagentButtonPressed?.Invoke(args, reagentTransferButton);
        return reagentTransferButton;
    }

    private void SaveCustomPerChemMaster()
    { if (_chemMasterNetEntity is { } id) _customPerChemMaster[id] = (CustomAmountLineEdit.Text, _customAmount, _customSelected); }

    private void SyncGrid(GridContainer grid)
    {
        if (_customSelected)
        {
            DeselectGrid();
            return;
        }

        var i = 0;
        foreach (var child in grid.Children)
        {
            if (child is Button btn && i < _amountConfigs.Length)
            {
                btn.Pressed = _amountConfigs[i].Amount == _selectedAmount;
                i++;
            }
        }
    }

    private void UpdateClassicCustomButtons()
    {
        var valid = IsCustomAmountValid(CustomAmountLineEditClassic.Text);
        void UpdateIn(Control root)
        {
            foreach (var child in root.Children)
            {
                if (child is ReagentButton rb && rb.Text == "#")
                    rb.Disabled = !valid;
                else if (child is Control c)
                    UpdateIn(c);
            }
        }
        UpdateIn(BufferInfoClassic);
        UpdateIn(InputContainerInfoClassic);
        UpdateIn(OutputContainerInfoClassic);
    }

    private void UpdateReagentPrototypes(string? filter = null)
    {
        var owner = _owner;
        if (!_owner.IsValid() ||
            !_solutionContainerSystem.TryGetSolution(owner, SharedChemMaster.BufferSolutionName, out _, out var bufferSolution) ||
            !_entityManager.TryGetComponent<ChemMasterComponent>(owner, out var chemMaster))
            return;

        BufferInfo.Children.Clear();
        BufferInfoClassic.Children.Clear();

        if (bufferSolution.Contents.Count == 0)
        {
            BufferInfo.Children.Add(new Label { Text = Loc.GetString("chem-master-window-buffer-empty-text") });
            BufferInfoClassic.Children.Add(new Label { Text = Loc.GetString("chem-master-window-buffer-empty-text") });
            return;
        }

        // Re-add header (mirrors UpdatePanelInfo) so search doesn't hide buffer volume
        void AddHeader(BoxContainer target)
        {
            var h = new BoxContainer { Orientation = LayoutOrientation.Horizontal };
            h.AddChild(new Label { Text = $"{Loc.GetString("chem-master-window-buffer-label")} " });
            h.AddChild(new Label { Text = $"{bufferSolution.Volume}u", StyleClasses = { StyleClass.LabelWeak } });
            target.AddChild(h);
        }
        AddHeader(BufferInfo);
        AddHeader(BufferInfoClassic);

        var reagentList = new List<(ReagentId reagentId, string name, Color color, FixedPoint2 quantity)>();
        foreach (var (reagent, quantity) in bufferSolution.Contents)
        {
            _prototypeManager.TryIndex(reagent.Prototype, out ReagentPrototype? proto);
            var name = proto?.LocalizedName ?? Loc.GetString("chem-master-window-unknown-reagent-text");
            var reagentColor = proto?.SubstanceColor ?? default(Color);
            reagentList.Add((reagent, name, reagentColor, quantity));
        }

        if (!string.IsNullOrEmpty(filter))
        {
            var trimmedFilter = filter.Trim();

            reagentList = reagentList
                .Where(r =>
                    r.name.Contains(
                        trimmedFilter,
                        StringComparison.InvariantCultureIgnoreCase)
                    || r.reagentId.Prototype.ToString().Contains(
                        trimmedFilter,
                        StringComparison.InvariantCultureIgnoreCase))
                .ToList();
        }

        reagentList = chemMaster.SortingType switch
        {
            ChemMasterSortingType.Alphabetical => reagentList.OrderBy(x => x.name).ToList(),
            ChemMasterSortingType.Quantity => reagentList.OrderByDescending(x => x.quantity).ToList(),
            ChemMasterSortingType.Latest => Enumerable.Reverse(reagentList).ToList(),
            _ => reagentList
        };

        var rowCount = 0;
        foreach (var (reagentId, name, color, quantity) in reagentList)
        {
            BufferInfo.Children.Add(BuildReagentRow(color, rowCount, name, reagentId, quantity, true, true, modernMode: true));
            BufferInfoClassic.Children.Add(BuildReagentRow(color, rowCount, name, reagentId, quantity, true, true, modernMode: false));
            rowCount++;
        }
    }

    private ContainerInfo? BuildInputContainerInfo(EntityUid? container)
    {
        if (container is not { Valid: true })
            return null;

        if (!_entityManager.TryGetComponent(container, out FitsInDispenserComponent? fits)
            || !_solutionContainerSystem.TryGetSolution(container.Value, fits.Solution, out _, out var solution))
        {
            return null;
        }

        return BuildContainerInfo(GetName(container.Value), solution);
    }

    private ContainerInfo? BuildOutputContainerInfo(EntityUid? container)
    {
        if (container is not { Valid: true })
            return null;

        var name = GetName(container.Value);
        {
            if (_solutionContainerSystem.TryGetSolution(
                    container.Value, SharedChemMaster.BottleSolutionName, out _, out var solution))
            {
                return BuildContainerInfo(name, solution);
            }
        }

        if (!_entityManager.TryGetComponent(container, out StorageComponent? storage))
            return null;

        _entityManager.TryGetComponent<LabelComponent>(container.Value, out var labelComp);
        var existingLabel = labelComp?.CurrentLabel;

        var items = storage.Container.ContainedEntities.Select((Func<EntityUid, (string, FixedPoint2 quantity)>)(pill =>
        {
            if (_solutionContainerSystem.TryGetSolution(pill, SharedChemMaster.PillSolutionName, out _, out var solution))
            {
                var quantity = solution?.Volume ?? FixedPoint2.Zero;
                return (GetName(pill), quantity);
            }
            else if (_solutionContainerSystem.TryGetSolution(pill, SharedChemMaster.PatchSolutionName, out _, out var patchSolution))
            {
                var patchQuantity = patchSolution?.Volume ?? FixedPoint2.Zero;
                return (GetName(pill), patchQuantity);
            }
            else
            {
                return ("none", FixedPoint2.Zero);
            }
        })).ToList();

        if (_tagSystem.HasTag(container.Value, PatchPackTag))
        {
            return new ContainerInfo(name, _storageSystem.GetCumulativeItemAreas((container.Value, storage)), storage.Grid.GetArea())
            {
                PatchEntities = items,
                ContainerLabel = existingLabel,
                Uid = _entityManager.GetNetEntity(container.Value)
            };
        }

        return new ContainerInfo(name, _storageSystem.GetCumulativeItemAreas((container.Value, storage)), storage.Grid.GetArea())
        {
            PillEntities = items,
            ContainerLabel = existingLabel,
            Uid = _entityManager.GetNetEntity(container.Value)
        };
    }

    private static ContainerInfo BuildContainerInfo(string name, Solution solution) => new(name, solution.Volume, solution.MaxVolume)
    {
        Reagents = solution.Contents,
    };

    private string GetName(EntityUid uid) => _entityManager.GetComponent<MetaDataComponent>(uid).EntityName;
