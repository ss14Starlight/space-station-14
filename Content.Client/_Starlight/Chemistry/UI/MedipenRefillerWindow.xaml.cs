using System.Linq;
using Content.Client.Chemistry.UI;
using Content.Client.UserInterface.Controls;
using Content.Shared._Starlight.Chemistry.EntitySystems;
using Content.Shared.Chemistry;
using Content.Shared.Chemistry.Reagent;
using Content.Shared.Labels.Components;
using Content.Shared.Storage;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Client._Starlight.Chemistry.UI;

/// <summary>
/// Lists the jugs stored in a medipen refiller, each with a button to take it out, using the dispenser's jug cards.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class MedipenRefillerWindow : FancyWindow
{
    [Dependency] private IEntityManager _entityManager = default!;
    [Dependency] private IPrototypeManager _prototypeManager = default!;

    private readonly MedipenRefillerSystem _refiller;
    private EntityUid _owner;
    private List<ReagentInventoryItem> _shown = [];

    public event Action<ItemStorageLocation>? OnEjectJugButtonPressed;

    public MedipenRefillerWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _refiller = _entityManager.System<MedipenRefillerSystem>();
    }

    public void SetOwner(EntityUid owner) => _owner = owner;

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        // At most four jugs, so rebuilding the list when it changes is cheap.
        var jugs = GetJugs();
        if (jugs.SequenceEqual(_shown))
            return;

        _shown = jugs;
        JugList.Children.Clear();
        foreach (var jug in jugs)
        {
            var card = new ReagentCardControl(jug);
            card.OnEjectButtonPressed += location => OnEjectJugButtonPressed?.Invoke(location);
            JugList.Children.Add(card);
        }

        NoJugsLabel.Visible = jugs.Count == 0;
    }

    private List<ReagentInventoryItem> GetJugs()
    {
        var items = new List<ReagentInventoryItem>();
        if (!_owner.IsValid())
            return items;

        foreach (var (jug, location, solution) in _refiller.GetJugs(_owner))
        {
            var contents = solution.Comp.Solution;
            var labelText = _entityManager.TryGetComponent<LabelComponent>(jug, out var label) ? label.CurrentLabel : null;
            var name = !string.IsNullOrEmpty(labelText)
                ? labelText
                : _entityManager.GetComponent<MetaDataComponent>(jug).EntityName;

            // An unlabelled jug shows what it holds after its name.
            if (string.IsNullOrEmpty(labelText)
                && contents.GetPrimaryReagentId() is { } primary
                && _prototypeManager.TryIndex<ReagentPrototype>(primary.Prototype, out var reagent))
            {
                name = $"{name} ({reagent.LocalizedName})";
            }

            items.Add(new ReagentInventoryItem(new ReagentDispenseData(location, null), name, contents.Volume,
                contents.GetColor(_prototypeManager), false));
        }

        items.Sort((a, b) => string.Compare(a.ReagentLabel, b.ReagentLabel, StringComparison.CurrentCulture));
        return items;
    }
}
