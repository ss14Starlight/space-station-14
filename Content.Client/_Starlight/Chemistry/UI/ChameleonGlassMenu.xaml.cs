using System.Numerics;
using Content.Client.Stylesheets;
using Content.Shared.Chemistry.Reagent;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Starlight.Chemistry.UI;

[GenerateTypedNameReferences]
public sealed partial class ChameleonGlassMenu : DefaultWindow
{
    [Dependency] private IPrototypeManager _prototypes = default!;
    [Dependency] private IEntityManager _entities = default!;

    private readonly SpriteSystem _sprites;
    private string _search = string.Empty;
    private string? _selected;

    public event Action<string>? OnSelected;

    public ChameleonGlassMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _sprites = _entities.System<SpriteSystem>();
        Search.OnTextChanged += args =>
        {
            _search = args.Text;
            Refresh();
        };
    }

    public void UpdateState(string? selected)
    {
        _selected = selected;
        Refresh();
    }

    private void Refresh()
    {
        Grid.RemoveAllChildren();
        var group = new ButtonGroup();

        foreach (var reagent in _prototypes.EnumeratePrototypes<ReagentPrototype>())
        {
            if (reagent.MetamorphicSprite == null ||
                !reagent.LocalizedName.Contains(_search, StringComparison.OrdinalIgnoreCase))
                continue;

            var id = reagent.ID;
            var button = new Button
            {
                MinSize = new Vector2(64, 64),
                HorizontalExpand = true,
                Group = group,
                StyleClasses = { StyleClass.ButtonSquare },
                ToggleMode = true,
                Pressed = id == _selected,
                ToolTip = reagent.LocalizedName
            };
            button.OnPressed += _ => OnSelected?.Invoke(id);
            button.AddChild(new TextureRect
            {
                Texture = _sprites.Frame0(reagent.MetamorphicSprite),
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
                HorizontalExpand = true,
                VerticalExpand = true
            });
            Grid.AddChild(button);
        }
    }
}
