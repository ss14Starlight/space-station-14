namespace Content.Client._Starlight.Chemistry.UI;

/// <summary>
/// Client-side UI used to control a <see cref="ReagentDispenserComponent"/>.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class ReagentDispenserWindow : FancyWindow
{
    [Dependency] private IEntityManager _entityManager = default!;
    [Dependency] private IPrototypeManager _prototypeManager = default!;

    private readonly SharedBatterySystem _battery;
    private readonly ItemSlotsSystem _itemSlotsSystem;
    private readonly PowerCellSystem _powercell;
    private readonly SharedSolutionContainerSystem _solutionContainerSystem;

    private EntityUid _owner;
    private List<ReagentInventoryItem> _currentInventory = [];
    private bool _dirty = true;

    /// <summary>
    /// Create and initialize the dispenser UI client-side. Creates the basic layout,
    /// actual data isn't filled in until the server sends data about the dispenser.
    /// </summary>
    public ReagentDispenserWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _battery = _entityManager.System<SharedBatterySystem>();
        _powercell = _entityManager.System<PowerCellSystem>();
        _itemSlotsSystem = _entityManager.System<ItemSlotsSystem>();
        _solutionContainerSystem = _entityManager.System<SolutionContainerSystem>();

        ValveButton.OnPressed += _ => OnToggleValveButtonPressed?.Invoke();
    }

    public event Action<ReagentDispenseData>? OnDispenseReagentButtonPressed;

    public event Action<ItemStorageLocation>? OnEjectJugButtonPressed;

    public event Action? OnToggleValveButtonPressed;

    public void SetOwner(EntityUid owner) => _owner = owner;

    public void UpdateData() => _dirty = true;

    /// <summary>
    /// Update the button grid of reagents which can be dispensed.
    /// </summary>
    /// <param name="inventory">Reagents which can be dispensed by this dispenser</param>
    public void UpdateReagentsList(List<ReagentInventoryItem> inventory)
    {
        if (ReagentList == null)
            return;

        //Sort inventory by reagentLabel
        inventory.Sort((x, y) => x.ReagentLabel.CompareTo(y.ReagentLabel));

        // only clear if changed
        if (_currentInventory.SequenceEqual(inventory))
            return;

        _currentInventory = inventory;
        ReagentList.Children.Clear();

        foreach (var item in inventory)
        {
            var card = new ReagentCardControl(item);
            card.OnPressed += OnDispenseReagentButtonPressed;
            card.OnEjectButtonPressed += OnEjectJugButtonPressed;
            ReagentList.Children.Add(card);
        }
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateEnergyDisplay();

        if (_dirty)
        {
            _dirty = false;
            UpdateUIImpl();
        }
    }

    private ContainerInfo? BuildOutputContainerInfo(EntityUid? container)
    {
        if (container is not { Valid: true })
            return null;

        if (_solutionContainerSystem.TryGetFitsInDispenser(container.Value, out _, out var solution))
            return new ContainerInfo(GetName(container.Value), solution.Volume, solution.MaxVolume)
            {
                Reagents = solution.Contents
            };

        return null;
    }

    private List<ReagentInventoryItem> GetInventory(Entity<ReagentDispenserComponent> reagentDispenser)
    {
        if (!_entityManager.TryGetComponent<StorageComponent>(reagentDispenser.Owner, out var storage))
        {
            return [];
        }

        var inventory = new List<ReagentInventoryItem>();

        foreach (var (storedContainer, storageLocation) in storage.StoredItems)
        {
            if (storedContainer == EntityUid.Invalid)
                continue;

            string reagentLabel;
            if (_entityManager.TryGetComponent<LabelComponent>(storedContainer, out var label) && !string.IsNullOrEmpty(label.CurrentLabel))
                reagentLabel = label.CurrentLabel;
            else
                reagentLabel = GetName(storedContainer);

            // Get volume remaining and color of solution
            FixedPoint2 quantity = 0f;
            var reagentColor = Color.White;
            if (_solutionContainerSystem.TryGetDrainableSolution(storedContainer, out _, out var sol))
            {
                quantity = sol.Volume;
                reagentColor = sol.GetColor(_prototypeManager);
            }

            var data = new ReagentDispenseData(storageLocation, null);
            inventory.Add(new ReagentInventoryItem(data, reagentLabel, quantity, reagentColor, false));
        }

        foreach (var (reagent, _) in reagentDispenser.Comp.GeneratableReagents)
        {
            if (_prototypeManager.TryIndex(reagent, out var reagentPrototype))
            {
                FixedPoint2 quantity = 100f;
                var data = new ReagentDispenseData(null, reagent);
                inventory.Add(new ReagentInventoryItem(data, reagentPrototype.LocalizedName, quantity, reagentPrototype.SubstanceColor, true));
            }
        }

        return inventory;
    }

    private string GetName(EntityUid uid) => _entityManager.GetComponent<MetaDataComponent>(uid).EntityName;

    /// <summary>
    /// Update the fill state and list of reagents held by the current reagent container, if applicable.
    /// </summary>
    private void UpdateContainerInfo(ContainerInfo? outputContainer)
    {
        ContainerInfo.Children.Clear();

        if (outputContainer is null)
        {
            ContainerInfoName.Text = "";
            ContainerInfoFill.Text = "";
            ContainerInfo.Children.Add(new Label { Text = Loc.GetString("reagent-dispenser-window-no-container-loaded-text") });
            return;
        }

        // Set Name of the container and its fill status (Ex: 44/100u)
        ContainerInfoName.Text = outputContainer.DisplayName;
        ContainerInfoFill.Text = outputContainer.CurrentVolume + "/" + outputContainer.MaxVolume;

        foreach (var (reagent, quantity) in outputContainer.Reagents!)
        {
            // Try get to the prototype for the given reagent. This gives us its name.
            var localizedName = _prototypeManager.TryIndex(reagent.Prototype, out var p)
                ? p.LocalizedName
                : Loc.GetString("reagent-dispenser-window-reagent-name-not-found-text");

            var nameLabel = new Label { Text = $"{localizedName}: " };
            var quantityLabel = new Label
            {
                Text = Loc.GetString("reagent-dispenser-window-quantity-label-text", ("quantity", quantity)),
                StyleClasses = { StyleClass.LabelWeak },
            };

            ContainerInfo.Children.Add(new BoxContainer
            {
                Orientation = LayoutOrientation.Horizontal,
                Children =
                {
                    nameLabel,
                    quantityLabel,
                }
            });
        }
    }

    private void UpdateEnergyDisplay()
    {
        var energyAmount = 0f;
        if (_owner.IsValid() && _powercell.TryGetBatteryFromSlot(_owner, out var battery))
            energyAmount = _battery.GetChargeLevel(battery.Value.AsNullable());

        EnergyDisplayBar.Value = energyAmount;
        EnergyDisplay.Text = Loc.GetString("mech-energy-display", ("amount", (int)MathF.Round(energyAmount * 100)));
    }

    private void UpdateUIImpl()
    {
        if (!_owner.IsValid() || !_entityManager.TryGetComponent(_owner, out ReagentDispenserComponent? comp))
            return;

        Entity<ReagentDispenserComponent> reagentDispenser = (_owner, comp);

        var outputContainer = _itemSlotsSystem.GetItemOrNull(reagentDispenser, SharedReagentDispenser.OutputSlotName);
        var outputContainerInfo = BuildOutputContainerInfo(outputContainer);

        UpdateContainerInfo(outputContainerInfo);
        UpdateReagentsList(GetInventory(reagentDispenser));
        View.SetEntity(outputContainer);

        // Disable the Clear & Eject button if no beaker
        ClearButton.Disabled = EjectButton.Disabled = outputContainerInfo is null;

        // Update valve button
        var valveOpen = _entityManager.TryGetComponent<PlumbingOutletComponent>(reagentDispenser.Owner, out var plumbingOutlet) && plumbingOutlet.Enabled;
        ValveButton.Text = Loc.GetString(valveOpen
            ? "reagent-dispenser-window-valve-open"
            : "reagent-dispenser-window-valve-closed");

        var selectedAmount = ((int)reagentDispenser.Comp.DispenseAmount).ToString();
        if (AmountGrid.Selected != selectedAmount) AmountGrid.Selected = selectedAmount;
    }
}
