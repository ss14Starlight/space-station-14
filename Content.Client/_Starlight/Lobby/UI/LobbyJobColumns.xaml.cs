namespace Content.Client._Starlight.Lobby.UI;

/// <summary>
/// A control that displays the job columns in the lobby, allowing players to view and prioritize jobs, as well as see which profiles are available for each job. It handles the layout and balancing of job icons across different priority levels (Never, Low, Medium) and provides tooltips with profile previews for each job.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class LobbyJobColumns : Control
{
    [Dependency] private IEntityManager _entManager = default!;
    [Dependency] private IClientPreferencesManager _preferences = default!;
    [Dependency] private IPrototypeManager _prototypeManager = default!;
    [Dependency] private JobRequirementsManager _requirements = default!;
    [Dependency] private ISharedPlayerManager _playerManager = default!;

    // The total number of columns available for job icons across all priority levels.
    private const int TotalColumns = 9;
    private const int MinColumns = 2;

    public LobbyJobColumns()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _prototypeManager.PrototypesReloaded += OnPrototypesReloaded;
        DraggableJobTarget.UpdatedOrderedJobs(_prototypeManager);

        // Set up fallback targets for job priorities to ensure that if a job cannot be placed in its designated priority column, it will fall back to the next available priority column.
        GetTarget(JobPriority.High).SetFallbackTarget(GetTarget(JobPriority.Medium));
        CollapseButton.OnPressed += _ => SetCollapsed(JobGrid.Visible);
        SetCollapsed(false);
    }

    [Obsolete]
    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);
        if (disposing)
            _prototypeManager.PrototypesReloaded -= OnPrototypesReloaded;
    }

    private void SetCollapsed(bool collapsed)
    {
        JobGrid.Visible = !collapsed;
        PriorityLock.Visible = !collapsed;
        CollapseButton.Text = collapsed ? "►" : "▼";
    }

    private DraggableJobTarget GetTarget(JobPriority priority)
        => FindControl<DraggableJobTarget>($"{priority}Box");

    private void OnPrototypesReloaded(PrototypesReloadedEventArgs args)
    {
        if (!args.WasModified<JobPrototype>() && !args.WasModified<DepartmentPrototype>())
            return;

        DraggableJobTarget.UpdatedOrderedJobs(_prototypeManager);
        Refresh();
    }

    public void Refresh()
    {
        foreach (var priority in Enum.GetValues<JobPriority>())
        {
            GetTarget(priority).ClearIcons();
        }

        if (_preferences.Preferences is not { } prefs)
            return;

        var sprite = _entManager.System<SpriteSystem>();
        foreach (var job in DraggableJobTarget.OrderedJobs)
        {
            if (!job.SetPreference || !_requirements.IsAllowed(job, null, out _))
                continue;

            var icon = new DraggableJobIcon(job, () => PriorityLock.Pressed, _ => CreateJobTooltip(job));
            if (prefs.GetAllEnabledProfilesForJob(job).Count == 0)
                icon.Modulate = Color.Salmon;
            icon.Texture = sprite.Frame0(_prototypeManager.Index(job.Icon).Icon);

            foreach (var priority in Enum.GetValues<JobPriority>())
            {
                GetTarget(priority).RegisterJobIcon(icon);
            }

            icon.OnPriorityChanged += SendUpdatedPriorities;
            icon.OnPriorityChanged += BalanceColumns;

            GetTarget(prefs.JobPriorities.GetValueOrDefault(job, JobPriority.Never)).AddJobIcon(icon, preOrdered: true);
        }

        BalanceColumns();
    }

    /// <summary>
    /// Balances the number of columns allocated to each job priority level (Never, Low, Medium) based on the number of jobs contained in each priority. It calculates the optimal distribution of columns to minimize the number of rows required to display all jobs while also minimizing the spread of columns across priorities. The method updates the column settings for each priority target accordingly.
    /// </summary>
    private void BalanceColumns()
    {
        var targets = new[] { GetTarget(JobPriority.Never), GetTarget(JobPriority.Low), GetTarget(JobPriority.Medium) };
        var counts = targets.Select(t => Math.Max(1, t.ContainedJobCount())).ToArray();

        var best = (Rows: int.MaxValue, Spread: int.MaxValue, Columns: (MinColumns, MinColumns, MinColumns));
        for (var a = MinColumns; a <= TotalColumns - (2 * MinColumns); a++)
        {
            for (var b = MinColumns; b <= TotalColumns - a - MinColumns; b++)
            {
                var c = TotalColumns - a - b;
                var rows = Math.Max((counts[0] - 1) / a, Math.Max((counts[1] - 1) / b, (counts[2] - 1) / c)) + 1;
                var spread = (a * a) + (b * b) + (c * c);
                if (rows < best.Rows || (rows == best.Rows && spread < best.Spread))
                    best = (rows, spread, (a, b, c));
            }
        }

        targets[0].SetColumns(best.Columns.Item1);
        targets[1].SetColumns(best.Columns.Item2);
        targets[2].SetColumns(best.Columns.Item3);
    }

    private void SendUpdatedPriorities()
    {
        var priorities = new Dictionary<ProtoId<JobPrototype>, JobPriority>();
        foreach (var priority in Enum.GetValues<JobPriority>())
        {
            if (priority == JobPriority.Never)
                continue;

            foreach (var job in GetTarget(priority).GetContainedJobs())
            {
                priorities[job] = priority;
            }
        }

        UserInterfaceManager.GetUIController<LobbyUIController>().SetJobPriorities(priorities, this);
    }

    private Tooltip? CreateJobTooltip(JobPrototype job)
    {
        if (_preferences.Preferences is not { } prefs)
            return null;

        var tooltip = new Tooltip();
        var content = tooltip.GetChild(0);
        content.RemoveAllChildren();
        content.AddChild(new Label
        {
            Text = job.LocalizedName,
            StyleClasses = { "LabelHeading" },
            HorizontalAlignment = HAlignment.Center,
        });

        var grid = new GridContainer { Margin = new Thickness(6) };
        content.AddChild(grid);

        var profiles = prefs.GetAllProfilesForJob(job);
        if (profiles.Count == 0)
        {
            grid.AddChild(new Label
            {
                Text = Loc.GetString("lobby-character-preview-panel-tooltip-no-profiles-for-job", ("job", job.LocalizedName)),
                Align = Label.AlignMode.Center,
            });
            return tooltip;
        }

        foreach (var profile in profiles.Values)
        {
            var preview = new ProfilePreviewSpriteView
            {
                SetSize = new Vector2(64),
                Scale = new Vector2(2),
                HorizontalAlignment = HAlignment.Right,
            };
            preview.Initialize(_preferences, _prototypeManager, _playerManager);
            preview.LoadPreview(profile, job);

            var description = preview.ProfileName;
            if (preview.LoadoutName != null)
                description = $"{description}\n\"{preview.LoadoutName}\"";
            if (!profile.Enabled)
                description += $"\n{Loc.GetString("character-setup-gui-character-picker-button-disabled-button")}";

            grid.AddChild(new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                Children =
                {
                    new Label
                    {
                        Text = description,
                        Align = Label.AlignMode.Right,
                        HorizontalExpand = true,
                        Margin = new Thickness(0, 0, 10, 0),
                        StyleClasses = { profile.Enabled ? "LabelKeyText" : "LabelWeak" },
                    },
                    preview,
                },
            });
        }

        return tooltip;
    }
}
