using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Starlight.Lobby.UI;

/// <summary>
/// Lets the player give a reason for rejecting pending preference edits, which is sent to the admin.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class PendingPreferencesRejectWindow : DefaultWindow
{
    public event Action<string?>? OnSubmit;

    public PendingPreferencesRejectWindow()
    {
        RobustXamlLoader.Load(this);

        ReasonEdit.OnTextChanged += _ => Placeholder.Visible = ReasonEdit.TextLength == 0;
        CancelButton.OnPressed += _ => Close();
        SubmitButton.OnPressed += _ =>
        {
            var reason = Rope.Collapse(ReasonEdit.TextRope).Trim();
            OnSubmit?.Invoke(reason.Length == 0 ? null : reason);
            Close();
        };
    }
}
