using Content.Shared._Starlight.Body.Editor;
using Content.Shared.Humanoid.Markings;
using Content.Shared.Preferences;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Starlight.Lobby.UI;

[GenerateTypedNameReferences]
public sealed partial class BodyTab : Control
{
    private readonly BodyEditorStore _store = new();
    private readonly SpriteSystem _sprite;
    private readonly MarkingManager _markingManager;
    private IPrototypeManager? _prototype;

    private string? _draggedMarkingId;
    private string? _dropTargetMarkingId;
    private readonly Dictionary<string, SelectedMarkingCard> _selectedCards = new();
    private readonly List<MarkingPrototype> _availableMarkings = new();

    public event Action<BodyProfile>? BodyProfileChanged;
    public event Action<HumanoidCharacterProfile>? ProfileChanged;

    public BodyTab()
    {
        RobustXamlLoader.Load(this);
        _markingManager = IoCManager.Resolve<MarkingManager>();
        _sprite = IoCManager.Resolve<IEntitySystemManager>().GetEntitySystem<SpriteSystem>();
        BodyPreview.SetStore(_store);
        _store.StateChanged += OnStateChanged;
    }

    public void Initialize(IPrototypeManager prototype, SpriteSystem sprite)
    {
        _prototype = prototype;
        BodyPreview.Initialize(prototype, sprite);
    }

    public void SetProfile(HumanoidCharacterProfile? profile)
    {
        _store.Dispatch(new BodyEditorSetProfileAction(profile));

        if (profile != null)
            _store.Dispatch(new BodyEditorSetBodyProfileAction(BodyProfileLegacy.GetOrConvert(profile, _markingManager)));

        if (_store.State.SelectedPartPath == null && _store.State.Character.BodyRoot != null)
            _store.Dispatch(new BodyEditorSelectPartAction(_store.State.Character.BodyRoot.Path));
    }

    public void SetBodyProfile(BodyProfile profile) =>
        _store.Dispatch(new BodyEditorSetBodyProfileAction(profile));

    private void OnStateChanged(BodyEditorState state, BodyEditorChange change)
    {
        if ((change & BodyEditorChange.Direction) != 0)
            RefreshMarkingPreviews();

        const BodyEditorChange StructuralMask =
            BodyEditorChange.Profile
            | BodyEditorChange.BodyProfile
            | BodyEditorChange.BodyRoot
            | BodyEditorChange.SelectedPart;

        if ((change & StructuralMask) != 0)
        {
            PopulateSidePanels();
            return;
        }

        if ((change & BodyEditorChange.BodyProfileMarkings) != 0)
            PopulateMarkings();

        if ((change & BodyEditorChange.BodyProfileColors) != 0)
            RefreshMarkingPreviews();
    }

    private void PopulateSidePanels()
    {
        PopulateBodyParts();
        PopulateColors();
        PopulateMarkings();
    }

    private void RefreshMarkingPreviews()
    {
        AvailableMarkingsGrid.RefreshAll();
        foreach (var card in _selectedCards.Values)
            card.RebuildPreview();
    }

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);

        if (disposing)
            _store.StateChanged -= OnStateChanged;
    }
}
