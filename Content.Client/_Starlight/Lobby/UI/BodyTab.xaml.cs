/// <summary>
/// Edits the body part by part: pick a part on the preview or in the part tree, then its markings and colors.
/// All data goes through an <see cref="IBodyEditorBackend"/>.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class BodyTab : Control, IMarkingCardDragHost
{
    private readonly IEntityManager _entity;
    private readonly SpriteSystem _sprite;
    private readonly MarkingManager _markings;

    private IBodyEditorBackend? _backend;
    private EntityUid _previewEntity;
    private bool _dirty;

    private BodyEditorPart? _part;
    private IReadOnlyList<BodyEditorGroup> _groups = [];
    private string? _groupId;
    private readonly List<(string Name, Control Content, bool Leading)> _sections = new();
    private int _section = -1;
    private int _spriteSignature;
    private string? _colorId;
    private readonly List<MarkingPrototype> _available = new();

    private MarkingCard? _dragged;
    private MarkingCard? _dropTarget;
    private readonly List<MarkingCard> _pickedCards = new();

    public BodyTab()
    {
        RobustXamlLoader.Load(this);
        _entity = IoCManager.Resolve<IEntityManager>();
        _sprite = _entity.System<SpriteSystem>();
        _markings = IoCManager.Resolve<MarkingManager>();

        BodyPreview.PartPressed += SelectPart;
        BodyPreview.PartHovered += BodyPreview.Highlight;
        BodyPreview.Rotated += () => _dirty = true;
        SearchEdit.OnTextChanged += _ => PopulateAvailable();
    }

    public void SetBackend(IBodyEditorBackend backend)
    {
        _backend?.Changed -= MarkDirty;
        _backend = backend;
        _backend.Changed += MarkDirty;
        _part ??= backend.Root;
        _dirty = true;
    }

    /// <summary>
    /// The character entity of the editor's preview, drawn here without clothes.
    /// </summary>
    public void SetPreviewEntity(EntityUid entity)
    {
        _previewEntity = entity;
        _dirty = true;
    }

    private void MarkDirty() => _dirty = true;

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (!VisibleInTree)
            return;

        // Once per frame at most, as a color picker drag edits every frame.
        if (_dirty)
        {
            _dirty = false;
            Populate();
            return;
        }

        // The preview entity picks an edit up a bit later, so its sprite is watched for that.
        if (_backend != null && SpriteSignature() != _spriteSignature)
            UpdatePreview();
    }

    private void UpdatePreview()
    {
        _spriteSignature = SpriteSignature();
        BodyPreview.Update(_previewEntity, _backend!);
    }

    private int SpriteSignature()
    {
        if (!_entity.TryGetComponent(_previewEntity, out SpriteComponent? sprite))
            return 0;

        var hash = new HashCode();
        hash.Add(_previewEntity);
        hash.Add(BodyPreview.Direction);
        foreach (var layer in sprite.AllLayers)
        {
            if (layer is not SpriteComponent.Layer spriteLayer)
                continue;
            hash.Add(spriteLayer.Visible);
            hash.Add(spriteLayer.State);
            hash.Add(spriteLayer.ActualRsi);
            hash.Add(spriteLayer.Color);
        }

        return hash.ToHashCode();
    }

    /// <summary>
    /// Drops the picked group and color, after the whole profile was replaced.
    /// </summary>
    public void ResetSelection()
    {
        _groupId = null;
        _colorId = null;
        ColorEditor.RemoveAllChildren();
        _dirty = true;
    }

    private void Populate()
    {
        if (_backend == null)
            return;

        if (_part == null || _backend.Root?.Contains(_part) != true)
            _part = _backend.Root;

        UpdatePreview();
        PopulateParts();
        PopulateGroups();
        PopulatePicked();
        PopulateAvailable();
        PopulateColors();
    }

    private void SelectPart(BodyEditorPart part)
    {
        _part = part;
        _groupId = null;
        _colorId = null;
        _section = -1;
        SectionArea.RemoveAllChildren();
        SectionArea.Visible = false;
        MarkingsArea.Visible = true;
        Populate();
    }

    #region Parts

    private void PopulateParts()
    {
        Breadcrumb.RemoveAllChildren();
        ChildParts.RemoveAllChildren();
        if (_backend?.Root is not { } root || _part == null)
            return;

        var path = new List<BodyEditorPart>();
        FindPath(root, _part, path);
        for (var i = 0; i < path.Count; i++)
        {
            if (i > 0)
                Breadcrumb.AddChild(new Label { Text = "›", StyleClasses = { "LabelSubText" }, VAlign = Label.VAlignMode.Center });
            Breadcrumb.AddChild(PartButton(path[i], i == path.Count - 1, null));
        }

        foreach (var child in _part.Children)
            ChildParts.AddChild(PartButton(child, false, "▸ "));
    }

    private Button PartButton(BodyEditorPart part, bool current, string? prefix)
    {
        var button = new Button
        {
            Text = prefix + Loc.GetString(part.Name),
            ToggleMode = true,
            Pressed = current,
            HorizontalExpand = prefix != null,
        };
        button.Label.Align = prefix != null ? Label.AlignMode.Left : Label.AlignMode.Center;
        button.OnPressed += _ => SelectPart(part);
        button.OnMouseEntered += _ => BodyPreview.Highlight(part);
        button.OnMouseExited += _ => BodyPreview.Highlight(null);
        return button;
    }

    private static bool FindPath(BodyEditorPart node, BodyEditorPart target, List<BodyEditorPart> path)
    {
        path.Add(node);
        if (node.Id == target.Id)
            return true;

        foreach (var child in node.Children)
        {
            if (FindPath(child, target, path))
                return true;
        }

        path.RemoveAt(path.Count - 1);
        return false;
    }

    #endregion

    #region Markings

    /// <summary>
    /// Adds a whole-body section next to the marking groups, such as cybernetics.
    /// </summary>
    /// <param name="leading">Put its button before the marking groups instead of after.</param>
    public void AddSection(string name, Control content, bool leading = false)
    {
        content.Orphan();
        _sections.Add((name, content, leading));
        _dirty = true;
    }

    /// <summary>
    /// Opens a section added with <see cref="AddSection"/>.
    /// </summary>
    public void ShowSection(Control content)
    {
        var index = _sections.FindIndex(s => s.Content == content);
        if (index >= 0)
            SelectSection(index);
    }

    private void SelectSection(int section)
    {
        _section = section;
        SectionArea.RemoveAllChildren();
        if (section >= 0)
            SectionArea.AddChild(_sections[section].Content);
        SectionArea.Visible = section >= 0;
        MarkingsArea.Visible = section < 0;
        PopulateGroups();
    }

    private BodyEditorGroup? CurrentGroup()
        => _groups.FirstOrDefault(g => g.Id == _groupId) ?? _groups.FirstOrDefault();

    private void PopulateGroups()
    {
        GroupList.RemoveAllChildren();
        _groups = _backend != null && _part != null ? _backend.GetGroups(_part) : [];
        if (_backend == null)
            return;

        var current = CurrentGroup();
        _groupId = current?.Id;
        AddSectionButtons(leading: true);

        foreach (var group in _groups)
        {
            var count = _backend.GetMarkings(group).Count;
            var button = new Button
            {
                Text = count > 0 ? $"{group.Name} ({count})" : group.Name,
                ToggleMode = true,
                Pressed = _section < 0 && group.Id == current?.Id,
            };
            button.OnPressed += _ =>
            {
                _groupId = group.Id;
                SelectSection(-1);
                PopulatePicked();
                PopulateAvailable();
            };
            GroupList.AddChild(button);
        }

        if (_groups.Count == 0 && _sections.Count == 0)
            GroupList.AddChild(new Label { Text = Loc.GetString("body-editor-no-markings"), StyleClasses = { "LabelSubText" } });

        AddSectionButtons(leading: false);

        // With no markings on this part, a section is all there is to show.
        if (_section < 0 && _groups.Count == 0 && _sections.Count > 0)
            SelectSection(0);
    }

    private void AddSectionButtons(bool leading)
    {
        for (var i = 0; i < _sections.Count; i++)
        {
            if (_sections[i].Leading != leading)
                continue;

            var index = i;
            var button = new Button { Text = _sections[i].Name, ToggleMode = true, Pressed = _section == i };
            button.OnPressed += _ => SelectSection(index);
            GroupList.AddChild(button);
        }
    }

    private void PopulatePicked()
    {
        PickedList.RemoveAllChildren();
        _pickedCards.Clear();
        if (_backend == null || CurrentGroup() is not { } group)
        {
            PickedHeader.Text = string.Empty;
            return;
        }

        var picked = _backend.GetMarkings(group);
        PickedHeader.Text = group.Max >= 0
            ? Loc.GetString("body-editor-picked-limited", ("count", picked.Count), ("max", group.Max), ("min", group.Min))
            : Loc.GetString("body-editor-picked", ("count", picked.Count));

        var size = new Vector2(64, 64);
        foreach (var marking in picked)
        {
            if (!_markings.TryGetMarking(marking, out var prototype))
                continue;

            var card = new MarkingCard(marking.MarkingId, BuildPreview(prototype, marking.MarkingColors, size), true, this)
            {
                SetSize = size,
                ToolTip = Loc.GetString($"marking-{prototype.ID}"),
            };
            card.OnRemove += () => _backend.RemoveMarking(group, marking.MarkingId);
            _pickedCards.Add(card);
            PickedList.AddChild(card);
        }
    }

    private readonly HashSet<string> _pickedIds = new();

    private void PopulateAvailable()
    {
        _available.Clear();
        _pickedIds.Clear();
        if (_backend != null && CurrentGroup() is { } group)
        {
            foreach (var marking in _backend.GetMarkings(group))
                _pickedIds.Add(marking.MarkingId);

            var search = SearchEdit.Text.Trim();
            _available.AddRange(_backend.GetAvailable(group).Where(m =>
                search.Length == 0 || Loc.GetString($"marking-{m.ID}").Contains(search, StringComparison.CurrentCultureIgnoreCase)));
        }

        // Same list as before, as after a color change: refresh in place, keeping the scroll.
        var key = $"{CurrentGroup()?.Id}|{SearchEdit.Text}|{_available.Count}";
        if (key == _availableKey)
        {
            AvailableGrid.RefreshAll();
            return;
        }

        _availableKey = key;
        AvailableGrid.SetItems(_available.Count, BuildAvailableCard);
    }

    private string? _availableKey;

    private Control BuildAvailableCard(int index)
    {
        var prototype = _available[index];
        var card = new MarkingCard(prototype.ID,
            BuildPreview(prototype, _backend!.GetDefaultColors(prototype), AvailableGrid.ItemSize), _pickedIds.Contains(prototype.ID))
        {
            ToolTip = Loc.GetString($"marking-{prototype.ID}"),
        };
        card.OnPressed += _ =>
        {
            if (CurrentGroup() is { } current)
                _backend.ToggleMarking(current, prototype);
        };
        return card;
    }

    /// <summary>
    /// The marking over the body part it is drawn on, both facing the way the preview does.
    /// </summary>
    private Control BuildPreview(MarkingPrototype marking, IReadOnlyList<Color> colors, Vector2 cellSize)
    {
        var scale = MarkingCard.ScaleFor(cellSize);
        var stack = new LayoutContainer { SetSize = new Vector2(32, 32) * scale };

        if (_entity.TryGetComponent(_previewEntity, out SpriteComponent? sprite)
            && _sprite.LayerMapTryGet((_previewEntity, sprite), marking.BodyPart, out var index, false)
            && sprite[index] is SpriteComponent.Layer { ActualRsi: { } rsi } layer
            && rsi.TryGetState(layer.State, out var state))
        {
            AddTexture(stack, Frame(state), layer.Color, scale);
        }

        var slotColors = marking.GetColorSlotColors(colors);
        for (var i = 0; i < marking.Sprites.Count; i++)
        {
            var color = marking.GetColorIndex(i) is var slot && slot < slotColors.Count ? slotColors[slot] : Color.White;
            AddTexture(stack, Frame(_sprite.RsiStateLike(marking.Sprites[i])), color, scale);
        }

        return stack;
    }

    private Texture Frame(IRsiStateLike state)
        => state.GetFrame(state.RsiDirections == RsiDirectionType.Dir1 ? RsiDirection.South : BodyPreview.Direction, 0);

    private static void AddTexture(LayoutContainer stack, Texture texture, Color color, float scale)
        => stack.AddChild(new TextureRect
        {
            Texture = texture,
            TextureScale = new Vector2(scale),
            ModulateSelfOverride = color,
            MouseFilter = MouseFilterMode.Ignore,
        });

    public void BeginDrag(MarkingCard card)
    {
        _dragged = card;
        _dropTarget = card;
        RefreshDrag();
    }

    public void DragOver(MarkingCard card)
    {
        if (_dragged == null)
            return;

        _dropTarget = card;
        RefreshDrag();
    }

    public void EndDrag()
    {
        var dragged = _dragged;
        var target = _dropTarget;
        _dragged = null;
        _dropTarget = null;
        RefreshDrag();

        if (dragged == null || target == null || CurrentGroup() is not { } group)
            return;

        // A click without a drag picks the marking's colors.
        if (dragged == target)
        {
            SelectColor(_backend?.GetColors(_part!).FirstOrDefault(c => c.Id.Contains($"#{dragged.MarkingId}#"))?.Id);
            return;
        }

        _backend?.MoveMarking(group, dragged.MarkingId, target.MarkingId);
    }

    private void RefreshDrag()
    {
        foreach (var card in _pickedCards)
            card.SetDragState(card == _dragged, _dragged != null && card == _dropTarget && card != _dragged);
    }

    #endregion

    #region Colors

    private void PopulateColors()
    {
        ColorList.RemoveAllChildren();
        if (_backend == null || _part == null)
        {
            ColorEditor.RemoveAllChildren();
            return;
        }

        var colors = _backend.GetColors(_part);
        var selected = colors.FirstOrDefault(c => c.Id == _colorId) ?? colors.FirstOrDefault();
        foreach (var color in colors)
        {
            var row = new Button
            {
                ToggleMode = true,
                Pressed = color.Id == selected?.Id,
            };
            row.AddChild(new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 6,
                Children =
                {
                    new PanelContainer
                    {
                        PanelOverride = new StyleBoxFlat(color.Value),
                        SetSize = new Vector2(14, 14),
                        VerticalAlignment = VAlignment.Center,
                    },
                    new Label { Text = color.Label, ClipText = true, HorizontalExpand = true },
                },
            });
            row.OnPressed += _ => SelectColor(color.Id);
            ColorList.AddChild(row);
        }

        // The editor stays while its color changes, or a drag on the picker would be cut off every frame.
        if (selected?.Id != _colorId || ColorEditor.ChildCount == 0)
        {
            _colorId = selected?.Id;
            BuildColorEditor(selected);
        }
    }

    private void SelectColor(string? id)
    {
        if (id == null)
            return;

        _colorId = id;
        ColorEditor.RemoveAllChildren();
        PopulateColors();
    }

    private void BuildColorEditor(BodyEditorColor? color)
    {
        ColorEditor.RemoveAllChildren();
        if (color == null || _backend is not { } backend)
            return;

        ColorEditor.AddChild(new Label { Text = color.Label, StyleClasses = { "LabelSubText" }, ClipText = true });

        if (color.Tone is { } tone)
        {
            var slider = new Slider { MinValue = 0, MaxValue = 100, Value = tone.ToTone(color.Value), HorizontalExpand = true };
            slider.OnValueChanged += _ => backend.SetColor(color.Id, tone.FromTone(slider.Value));
            ColorEditor.AddChild(slider);
        }
        else
        {
            var picker = new StarlightColorPicker { Color = color.Value, Constrain = color.Constrain };
            picker.OnColorChanged += value => backend.SetColor(color.Id, value);
            ColorEditor.AddChild(picker);
        }

        if (color.Glowing is { } glowing)
        {
            var check = new CheckBox { Text = Loc.GetString("body-editor-glowing"), Pressed = glowing };
            check.OnToggled += args => backend.SetGlowing(color.Id, args.Pressed);
            ColorEditor.AddChild(check);
        }
    }

    #endregion
}
