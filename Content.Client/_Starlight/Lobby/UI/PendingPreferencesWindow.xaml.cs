using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Starlight.Lobby.UI;

/// <summary>
/// Prompts the player to review, accept, or reject preference edits made by an admin.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class PendingPreferencesWindow : DefaultWindow
{
    public PendingPreferencesWindow() => RobustXamlLoader.Load(this);

    public void SetAdmin(string admin) =>
        InfoLabel.SetMessage(FormattedMessage.FromMarkupOrThrow(
            Loc.GetString("pending-preferences-window-info", ("admin", FormattedMessage.EscapeText(admin)))));
}
