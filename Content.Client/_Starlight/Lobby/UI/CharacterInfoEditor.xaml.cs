using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Starlight.Lobby.UI;

[GenerateTypedNameReferences]
public sealed partial class CharacterInfoEditor : BoxContainer
{
    public TextEdit PhysicalDescInput => Physical.Input;
    public TextEdit PersonalityDescInput => Personality.Input;
    public TextEdit ExploitableInput => Exploitable.Input;
    public TextEdit SecretsInput => Secrets.Input;

    public CharacterInfoEditor()
    {
        RobustXamlLoader.Load(this);
    }

    /// <summary>
    /// Refreshes the length counters after the text was set from code.
    /// </summary>
    public void UpdateCounts()
    {
        Physical.UpdateCount();
        Personality.UpdateCount();
        Exploitable.UpdateCount();
        Secrets.UpdateCount();
    }
}
