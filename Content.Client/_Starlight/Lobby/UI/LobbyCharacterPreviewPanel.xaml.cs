using System.Linq;
using Content.Client.Lobby;
using Content.Shared.Preferences;
using Content.Shared.Roles;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Starlight.Lobby.UI;

/// <summary>
/// A panel that shows a preview of the selected character in the lobby, including their name, job, and sprite.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class LobbyCharacterPreviewPanel : Control
{
    [Dependency] private IClientPreferencesManager _preferences = default!;
    [Dependency] private IPrototypeManager _prototypeManager = default!;

    /// <summary>
    /// <see cref="LobbyState"/> needs to register events on this button, so provide a property to access it publicly.
    /// </summary>
    public Button CharacterSetupButton => CharacterSetup;

    public LobbyCharacterPreviewPanel()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        JobPriorities.OnPressed += _ => UserInterfaceManager.GetUIController<LobbyUIController>().OpenJobPrioritiesWindow(); // Starlight-edit
    }

    public void SetLoaded(bool value)
    {
        Loaded.Visible = value;
        Unloaded.Visible = !value;
    }


    /// <summary>
    /// Refresh the selected character summary
    /// </summary>
    public void Refresh()
    {
        if (_preferences.Preferences is not { } prefs)
            return;

        var high = prefs.JobPriorities.FirstOrDefault(p => p.Value == JobPriority.High).Key;
        if (high != default && _prototypeManager.TryIndex<JobPrototype>(high, out var highJob))
        {
            HighJob.Text = Loc.GetString("lobby-character-preview-panel-high-job", ("job", highJob.LocalizedName));
            CharacterCount.Text = Loc.GetString("lobby-character-preview-panel-job-characters",
                ("count", prefs.GetAllEnabledProfilesForJob(high).Count));
            return;
        }

        HighJob.Text = Loc.GetString("lobby-character-preview-panel-no-high-job");
        CharacterCount.Text = Loc.GetString("lobby-character-preview-panel-enabled-characters",
            ("count", prefs.Characters.Values.OfType<HumanoidCharacterProfile>().Count(p => p.Enabled)));
    }
}
