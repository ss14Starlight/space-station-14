namespace Content.Client._Starlight.Lobby.UI;

/// <summary>
/// A window that allows the player to set their job priorities for the round.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class JobPrioritiesWindow : DefaultWindow
{
    [Dependency] private IClientPreferencesManager _preferences = default!;
    [Dependency] private IPrototypeManager _prototype = default!;
    [Dependency] private JobRequirementsManager _requirements = default!;

    /// <summary>
    /// Invoked when the player changes their job priorities. The dictionary contains the new priorities for each job.
    /// </summary>
    public event Action<Dictionary<ProtoId<JobPrototype>, JobPriority>>? OnPrioritiesChanged;

    private readonly ButtonGroup _filterGroup = new();
    private Dictionary<ProtoId<JobPrototype>, JobPriority> _priorities = [];
    private Filter _filter = Filter.All;
    private ProtoId<DepartmentPrototype>? _departmentFilter;

    private enum Filter : byte
    {
        All,
        Selected,
        Department,
    }

    public JobPrioritiesWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        SearchLineEdit.OnTextChanged += _ => Rebuild();
        Refresh();
    }

    /// <summary>
    /// Refreshes the job priorities window, rebuilding the filters and job cards based on the current preferences and prototypes.
    /// </summary>
    public void Refresh()
    {
        _priorities = _preferences.Preferences?.JobPriorities.ToDictionary() ?? [ ];
        RebuildFilters();
        Rebuild();
    }

    private List<(DepartmentPrototype Department, List<JobPrototype> Jobs)> GetDepartments()
    {
        var departments = _prototype.EnumeratePrototypes<DepartmentPrototype>()
            .Where(d => !d.EditorHidden)
            .ToList();
        departments.Sort(DepartmentUIComparer.Instance);

        var seen = new HashSet<ProtoId<JobPrototype>>();
        var result = new List<(DepartmentPrototype, List<JobPrototype>)>();
        foreach (var department in departments)
        {
            var jobs = new List<JobPrototype>();
            foreach (var id in department.Roles)
            {
                if (!seen.Add(id) || !_prototype.TryIndex(id, out var job) || !job.SetPreference)
                    continue;
                jobs.Add(job);
            }

            if (jobs.Count > 0)
                result.Add((department, jobs));
        }

        return result;
    }

    private void RebuildFilters()
    {
        FilterGrid.RemoveAllChildren();
        AddFilter(Loc.GetString("job-priorities-window-filter-all"), null, Filter.All, null);
        AddFilter(Loc.GetString("job-priorities-window-filter-selected"), null, Filter.Selected, null);
        foreach (var (department, _) in GetDepartments())
            AddFilter(Loc.GetString(department.Name), department.Color, Filter.Department, department.ID);
    }

    private void AddFilter(string text, Color? color, Filter filter, string? department)
    {
        var button = new Button { ToggleMode = true, Group = _filterGroup, Text = text };
        if (color is { } c)
            button.Label.FontColorOverride = c;

        button.Pressed = _filter == filter && (filter != Filter.Department || _departmentFilter == department);
        button.OnPressed += _ =>
        {
            _filter = filter;
            _departmentFilter = department;
            Rebuild();
        };
        FilterGrid.AddChild(button);
    }

    private void Rebuild()
    {
        DepartmentGrid.RemoveAllChildren();
        var search = SearchLineEdit.Text.Trim();

        foreach (var (department, jobs) in GetDepartments())
        {
            if (_filter == Filter.Department && _departmentFilter != department.ID)
                continue;

            var shown = jobs.Where(job =>
                    (_filter != Filter.Selected || GetPriority(job) != JobPriority.Never)
                    && (search.Length == 0 || job.LocalizedName.Contains(search, StringComparison.CurrentCultureIgnoreCase)))
                .ToList();
            if (shown.Count == 0)
                continue;

            DepartmentGrid.AddChild(BuildDepartment(department, jobs, shown));
        }

        UpdateSummary();
    }

    private Control BuildDepartment(DepartmentPrototype department, List<JobPrototype> jobs, List<JobPrototype> shown)
    {
        var selected = jobs.Count(job => GetPriority(job) != JobPriority.Never);
        var header = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 6,
            Children =
            {
                new PanelContainer
                {
                    PanelOverride = new Robust.Client.Graphics.StyleBoxFlat(department.Color),
                    MinSize = new(8, 8),
                    VerticalAlignment = VAlignment.Center,
                },
                new Label
                {
                    Text = Loc.GetString(department.Name).ToUpperInvariant(),
                    StyleClasses = { "LabelKeyText" },
                    HorizontalExpand = true,
                },
                new Label
                {
                    Text = selected > 0 ? Loc.GetString("job-priorities-window-selected", ("count", selected)) : string.Empty,
                    StyleClasses = { "LabelSubText" },
                },
            },
        };

        var cards = new GridContainer { Columns = 2, HSeparationOverride = 6, VSeparationOverride = 6 };
        foreach (var job in shown)
        {
            cards.AddChild(BuildCard(job));
        }

        return new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            SeparationOverride = 6,
            Children = { header, cards },
        };
    }

    private Control BuildCard(JobPrototype job)
    {
        var priority = GetPriority(job);
        var allowed = _requirements.IsAllowed(job, null, out var reason);
        var hasCharacter = _preferences.Preferences?.GetAllEnabledProfilesForJob(job.ID).Count > 0;

        var card = new ContainerButton
        {
            HorizontalExpand = true,
            MinWidth = 180,
            Disabled = !allowed,
            EnableAllKeybinds = true,
            StyleClasses = { StarlightStyleClass.JobCard },
        };
        if (priority == JobPriority.High)
            card.AddStyleClass(StarlightStyleClass.JobCardHigh);
        if (!allowed)
            card.ToolTip = reason.ToString();

        var bars = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 2 };
        for (var i = 1; i <= 3; i++)
        {
            var bar = new PanelContainer { MinSize = new(10, 3), VerticalAlignment = VAlignment.Center };
            bar.AddStyleClass(i <= (int) priority ? StarlightStyleClass.PriorityBarFilled : StarlightStyleClass.PriorityBar);
            bars.AddChild(bar);
        }

        var status = new Label
        {
            Text = !allowed
                ? Loc.GetString("job-priorities-window-locked")
                : !hasCharacter && priority != JobPriority.Never
                    ? Loc.GetString("job-priorities-window-no-character")
                    : Loc.GetString($"humanoid-profile-editor-job-priority-{priority.ToString().ToLowerInvariant()}-button"),
            StyleClasses = { "LabelSubText" },
            Margin = new Thickness(6, 0, 0, 0),
        };
        if (allowed && !hasCharacter && priority != JobPriority.Never)
            status.AddStyleClass("negative");

        card.AddChild(new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            Margin = new Thickness(8, 4),
            Children =
            {
                new Label { Text = job.LocalizedName, ClipText = true },
                new BoxContainer
                {
                    Orientation = BoxContainer.LayoutOrientation.Horizontal,
                    Children = { bars, status },
                },
            },
        });

        card.OnPressed += args =>
        {
            if (args.Event.Function == EngineKeyFunctions.UIClick)
                Change(job, +1);
            else if (args.Event.Function == EngineKeyFunctions.UIRightClick)
                Change(job, -1);
        };

        return card;
    }

    private void Change(JobPrototype job, int step)
    {
        var next = (JobPriority) Math.Clamp((int) GetPriority(job) + step, (int) JobPriority.Never, (int) JobPriority.High);

        // Only one high priority job: the previous one steps down, as in the old drag and drop columns.
        if (next == JobPriority.High)
        {
            foreach (var (other, priority) in _priorities.ToList())
            {
                if (priority == JobPriority.High && other != job.ID)
                    _priorities[other] = JobPriority.Medium;
            }
        }

        if (next == JobPriority.Never)
            _priorities.Remove(job.ID);
        else
            _priorities[job.ID] = next;

        OnPrioritiesChanged?.Invoke(new Dictionary<ProtoId<JobPrototype>, JobPriority>(_priorities));
        Rebuild();
    }

    private JobPriority GetPriority(JobPrototype job)
        => _priorities.GetValueOrDefault(job.ID, JobPriority.Never);

    private void UpdateSummary()
    {
        var high = _priorities.FirstOrDefault(p => p.Value == JobPriority.High).Key;
        var highName = high != default && _prototype.TryIndex(high, out var job)
            ? job.LocalizedName
            : Loc.GetString("job-priorities-window-none");

        SummaryLabel.Text = Loc.GetString("job-priorities-window-summary",
            ("high", highName),
            ("medium", _priorities.Count(p => p.Value == JobPriority.Medium)),
            ("low", _priorities.Count(p => p.Value == JobPriority.Low)));
    }
}
