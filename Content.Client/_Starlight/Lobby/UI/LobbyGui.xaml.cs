using Content.Client.Changelog;
using Content.Client.Info;
using Content.Client.Lobby;
using Content.Client.Message;
using Content.Client.Stylesheets;
using Content.Client.UserInterface.Systems.EscapeMenu;
using Content.Client.UserInterface.Systems.Guidebook;
using Content.Shared._Starlight.CCVar;
using Robust.Client.AutoGenerated;
using Robust.Client.Console;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;

namespace Content.Client._Starlight.Lobby.UI;

[GenerateTypedNameReferences]
public sealed partial class LobbyGui : UIScreen
{
    [Dependency] private IClientConsoleHost _consoleHost = default!;
    [Dependency] private IConfigurationManager _configurationManager = default!;
    [Dependency] private ChangelogManager _changelog = default!;

    public LobbyGui()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        SetAnchorPreset(MainContainer, LayoutPreset.Wide);
        SetAnchorPreset(Background, LayoutPreset.Wide);

        LobbySong.SetMarkup(Loc.GetString("lobby-state-song-no-song-text"));

        LeaveButton.OnPressed += _ => _consoleHost.ExecuteCommand("disconnect");
        OptionsButton.OnPressed += _ => UserInterfaceManager.GetUIController<OptionsUIController>().ToggleWindow();

        if (LinkBanner.ChildCount > 0 && LinkBanner.GetChild(0) is BoxContainer links)
            links.Orientation = BoxContainer.LayoutOrientation.Vertical;
        LinksButton.SetContent(LinkBanner);

        RulesButton.OnPressed += _ => new RulesAndInfoWindow().Open();
        GuidebookButton.OnPressed += _ => UserInterfaceManager.GetUIController<GuidebookUIController>().ToggleGuidebook();

        _configurationManager.OnValueChanged(StarlightCCVars.LobbyChatWidth, _ => UpdateChatWidth(), true);
        ChatResizeHandle.OnDragStarted += () => _dragStartWidth = ChatColumn.SetWidth;
        ChatResizeHandle.OnDragged += offset => ChatColumn.SetWidth = ClampChatWidth(_dragStartWidth - offset);
        ChatResizeHandle.OnDragFinished += () =>
        {
            _configurationManager.SetCVar(StarlightCCVars.LobbyChatWidth, (int) ChatColumn.SetWidth);
            _configurationManager.SaveToFile();
        };

        CardToggle.OnPressed += _ => SetCardCollapsed(CardBody.Visible);
        SetCardCollapsed(false);

        _configurationManager.OnValueChanged(StarlightCCVars.LobbyJobColumns, show => JobColumnsBox.Visible = show, true);

        _configurationManager.OnValueChanged(StarlightCCVars.AntagsEnabled, enabled => AntagsCheckBox.Pressed = enabled, true);
        AntagsCheckBox.OnToggled += args =>
        {
            _configurationManager.SetCVar(StarlightCCVars.AntagsEnabled, args.Pressed);
            _configurationManager.SaveToFile();
        };

        _configurationManager.OnValueChanged(StarlightCCVars.ServerName, name => ServerName.Text = name, true);
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        _changelog.NewChangelogEntriesChanged += UpdateLinksHighlight;
        UpdateLinksHighlight();
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();
        _changelog.NewChangelogEntriesChanged -= UpdateLinksHighlight;
    }

    private void UpdateLinksHighlight()
    {
        if (_changelog.NewChangelogEntries)
            LinksButton.AddStyleClass(StyleClass.Negative);
        else
            LinksButton.RemoveStyleClass(StyleClass.Negative);
    }

    private const float MinChatWidth = 300;

    /// <summary>
    /// Room left for the middle column, where votes and the playtime comment go.
    /// </summary>
    private const float MinMiddleWidth = 200;

    private float _dragStartWidth;

    protected override void Resized()
    {
        base.Resized();
        UpdateChatWidth();
    }

    private void UpdateChatWidth()
        => ChatColumn.SetWidth = ClampChatWidth(_configurationManager.GetCVar(StarlightCCVars.LobbyChatWidth));

    private float ClampChatWidth(float width)
    {
        // Before the first layout there is no size to clamp against.
        if (Width <= 0)
            return Math.Max(width, MinChatWidth);

        // The screen's own size: in Resized the columns aren't arranged yet.
        var max = Width - ColumnsBox.Margin.SumHorizontal - LeftSide.SetWidth - LeftSide.Margin.SumHorizontal - ChatResizeHandle.MinWidth - MinMiddleWidth;
        return Math.Clamp(width, MinChatWidth, Math.Max(MinChatWidth, max));
    }

    private void SetCardCollapsed(bool collapsed)
    {
        CardBody.Visible = !collapsed;
        CardToggle.Text = collapsed ? "►" : "▼";
    }

    public void SwitchState(LobbyGuiState state)
    {
        if (state == LobbyGuiState.CharacterSetup)
            UserInterfaceManager.GetUIController<LobbyUIController>().OpenCharacterSetupWindow();
    }

    public enum LobbyGuiState : byte
    {
        /// <summary>
        ///  The default state, i.e., what's seen on launch.
        /// </summary>
        Default,
        /// <summary>
        ///  The character setup state.
        /// </summary>
        CharacterSetup
    }
}
