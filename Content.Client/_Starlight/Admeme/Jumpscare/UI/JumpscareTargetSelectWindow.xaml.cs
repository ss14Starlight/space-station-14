using System.Linq;
using Content.Shared._Starlight.Admeme.Jumpscare;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Starlight.Admeme.Jumpscare.UI;

/// <summary>
/// Popup for picking which players the multi-target jumpscare panel hits.
/// Edits the selection set it was given in place.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class JumpscareTargetSelectWindow : DefaultWindow
{
    private readonly HashSet<NetEntity> _selected;
    private List<JumpscarePlayerInfo> _players = [];

    public event Action? OnSelectionChanged;

    public JumpscareTargetSelectWindow(HashSet<NetEntity> selected)
    {
        RobustXamlLoader.Load(this);
        _selected = selected;

        SelectAllButton.OnPressed += _ => Select(_ => true);
        DeselectAllButton.OnPressed += _ => Select(_ => false);
        SelectGhostsButton.OnPressed += _ => Select(p => p.IsGhost);
        SelectLivingButton.OnPressed += _ => Select(p => p.IsAlive);
    }

    public void SetPlayers(List<JumpscarePlayerInfo> players)
    {
        _players = players.OrderBy(p => p.Username, StringComparer.OrdinalIgnoreCase).ToList();
        Refresh();
    }

    private void Select(Func<JumpscarePlayerInfo, bool> predicate)
    {
        _selected.Clear();
        foreach (var player in _players.Where(predicate))
            _selected.Add(player.Entity);

        Refresh();
        OnSelectionChanged?.Invoke();
    }

    private void Refresh()
    {
        PlayerContainer.RemoveAllChildren();
        EmptyLabel.Visible = _players.Count == 0;

        foreach (var (entity, username, entityName, isGhost, isAlive) in _players)
        {
            var status = isGhost ? "jumpscare-ui-player-ghost"
                : isAlive ? "jumpscare-ui-player-alive"
                : "jumpscare-ui-player-dead";

            var checkBox = new Button
            {
                Text = Loc.GetString("jumpscare-ui-player-entry",
                    ("username", username),
                    ("name", entityName),
                    ("status", Loc.GetString(status))),
                Pressed = _selected.Contains(entity),
                ToggleMode = true
            };

            checkBox.OnToggled += args =>
            {
                if (args.Pressed)
                    _selected.Add(entity);
                else
                    _selected.Remove(entity);
                OnSelectionChanged?.Invoke();
            };

            PlayerContainer.AddChild(checkBox);
        }
    }
}
