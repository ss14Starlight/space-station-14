using System.Diagnostics.CodeAnalysis;
using System.Linq;
using Content.Shared._Starlight.Admeme.Jumpscare;
using Content.Shared.Damage;
using Content.Shared.Damage.Prototypes;
using Content.Shared.FixedPoint;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Audio;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._Starlight.Admeme.Jumpscare.UI;

[GenerateTypedNameReferences]
public sealed partial class JumpscareEntityPanel : DefaultWindow
{
    [Dependency] private IEntityManager _ent = null!;
    [Dependency] private IPrototypeManager _proto = null!;

    /// <summary>
    /// Entities to jumpscare. Locked to a single entity when <see cref="AllowMultiTarget"/> is false.
    /// </summary>
    public readonly HashSet<NetEntity> Targets = [];

    /// <summary>
    /// Whether <see cref="Targets"/> can be edited, i.e. the panel wasn't opened on a specific entity.
    /// </summary>
    public bool AllowMultiTarget { get; private set; }

    private JumpscareTargetSelectWindow? _targetWindow;
    private List<JumpscarePlayerInfo> _players = [];
    private DamageSpecifier _damage = new();

    private readonly Dictionary<LineEdit, string> _lastText = [];
    private readonly List<LineEdit> _damageLineEdits = [];

    public Action<JumpscareData, IReadOnlyCollection<NetEntity>>? OnDoJumpscare;

    /// <summary>
    /// Raised when the target select popup opens, so the player list can be refreshed.
    /// </summary>
    public Action? OnRequestPlayers;

    public JumpscareEntityPanel()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        AddMarginRecursive(this);

        // Times are entered in seconds.
        FadeInTime.Text = "0";
        HoldTime.Text = "1";
        FadeTime.Text = "1";
        KnockdownTime.Text = "5";

        _lastText.Add(AudioParamsVolume, AudioParamsVolume.Text);
        _lastText.Add(AudioParamsPitch, AudioParamsPitch.Text);
        _lastText.Add(AudioParamsMaxDistance, AudioParamsMaxDistance.Text);
        _lastText.Add(AudioParamsRolloffFactor, AudioParamsRolloffFactor.Text);
        _lastText.Add(AudioParamsReferenceDistance, AudioParamsReferenceDistance.Text);
        _lastText.Add(AudioParamsOffsetSeconds, AudioParamsOffsetSeconds.Text);
        _lastText.Add(AudioParamsVariation, AudioParamsVariation.Text);
        _lastText.Add(FadeInTime, FadeInTime.Text);
        _lastText.Add(HoldTime, HoldTime.Text);
        _lastText.Add(FadeTime, FadeTime.Text);
        _lastText.Add(KnockdownTime, KnockdownTime.Text);

        AudioParamsVolume.OnFocusExit += args => TryParseFloat(AudioParamsVolume, args.Text, out _);
        AudioParamsPitch.OnFocusExit += args => TryParseFloat(AudioParamsPitch, args.Text, out _);
        AudioParamsMaxDistance.OnFocusExit += args => TryParseFloat(AudioParamsMaxDistance, args.Text, out _);
        AudioParamsRolloffFactor.OnFocusExit += args => TryParseFloat(AudioParamsRolloffFactor, args.Text, out _);
        AudioParamsReferenceDistance.OnFocusExit +=
            args => TryParseFloat(AudioParamsReferenceDistance, args.Text, out _);
        AudioParamsOffsetSeconds.OnFocusExit += args => TryParseFloat(AudioParamsOffsetSeconds, args.Text, out _);
        AudioParamsVariation.OnFocusExit += args => TryParseFloat(AudioParamsVariation, args.Text, out _);
        FadeInTime.OnFocusExit += args => TryParseTimeSpan(FadeInTime, args.Text, out _);
        HoldTime.OnFocusExit += args => TryParseTimeSpan(HoldTime, args.Text, out _);
        FadeTime.OnFocusExit += args => TryParseTimeSpan(FadeTime, args.Text, out _);
        KnockdownTime.OnFocusExit += args => TryParseTimeSpan(KnockdownTime, args.Text, out _);

        SpriteType.AddItem(Loc.GetString("jumpscare-ui-none"), 0);
        SpriteType.AddItem(Loc.GetString("jumpscare-ui-sprite-specifier-rsi-button"), 1);
        SpriteType.AddItem(Loc.GetString("jumpscare-ui-sprite-specifier-texture-button"), 2);
        SpriteType.SelectId(0);

        SpriteType.OnItemSelected += args =>
        {
            SpriteType.SelectId(args.Id);
            SpritePath.Visible = args.Id > 0;
            RsiStateContainer.Visible = args.Id == 1;
        };

        SoundType.AddItem(Loc.GetString("jumpscare-ui-none"), 0);
        SoundType.AddItem(Loc.GetString("jumpscare-ui-sound-specifier-path-button"), 1);
        SoundType.AddItem(Loc.GetString("jumpscare-ui-sound-specifier-collection-button"), 2);
        SoundType.SelectId(0);

        SoundType.OnItemSelected += args =>
        {
            SoundType.SelectId(args.Id);
            Params.Visible = args.Id > 0;
            SoundPath.Visible = args.Id > 0;
        };

        DamageTypeOptionButton.OnItemSelected += args =>
        {
            DamageTypeOptionButton.SelectId(args.Id);
            AddDamageTypeButton.Disabled = DamageTypeOptionButton.GetItemMetadata(args.Id) is null;
        };
        DamageGroupOptionButton.OnItemSelected += args =>
        {
            DamageGroupOptionButton.SelectId(args.Id);
            AddDamageGroupButton.Disabled = DamageGroupOptionButton.GetItemMetadata(args.Id) is null;
        };
        AddDamageTypeButton.OnPressed += _ =>
        {
            var type = (DamageTypePrototype)DamageTypeOptionButton.GetItemMetadata(DamageTypeOptionButton.SelectedId)!;
            _damage.DamageDict.Add(type, 0);
            RefreshDamageTypes();
        };
        AddDamageGroupButton.OnPressed += _ =>
        {
            var type =
                (DamageGroupPrototype)DamageGroupOptionButton.GetItemMetadata(DamageGroupOptionButton.SelectedId)!;
            _damage.DamageGroupDict.Add(type, 0);
            RefreshDamageGroups();
        };

        KnockdownTarget.OnToggled += args => KnockdownTimeContainer.Visible = args.Pressed;

        SelectTargetsButton.OnPressed += _ => OpenTargetWindow();
        OnClose += () => _targetWindow?.Close();
        UpdateTargetsButton();

        SubmitButton.OnPressed += _ =>
        {
            SpriteSpecifier? sprite = null;
            SoundSpecifier? sound = null;
            TryParseFloat(AudioParamsVolume, AudioParamsVolume.Text, out var volume);
            TryParseFloat(AudioParamsPitch, AudioParamsPitch.Text, out var pitch);
            TryParseFloat(AudioParamsMaxDistance, AudioParamsMaxDistance.Text, out var maxDist);
            TryParseFloat(AudioParamsRolloffFactor, AudioParamsRolloffFactor.Text, out var rolloff);
            TryParseFloat(AudioParamsReferenceDistance, AudioParamsReferenceDistance.Text, out var refDist);
            TryParseFloat(AudioParamsOffsetSeconds, AudioParamsOffsetSeconds.Text, out var offset);
            TryParseFloat(AudioParamsVariation, AudioParamsVariation.Text, out var variation);
            AudioParams? @params = new AudioParams
            {
                Volume = volume ?? AudioParams.Default.Volume,
                Pitch = pitch ?? AudioParams.Default.Pitch,
                MaxDistance = maxDist ?? AudioParams.Default.MaxDistance,
                RolloffFactor = rolloff ?? AudioParams.Default.RolloffFactor,
                ReferenceDistance = refDist ?? AudioParams.Default.ReferenceDistance,
                PlayOffsetSeconds = offset ?? AudioParams.Default.PlayOffsetSeconds,
                Variation = variation ?? AudioParams.Default.Variation
            };
            sprite = SpriteType.SelectedId switch
            {
                1 => new SpriteSpecifier.Rsi(new ResPath(SpritePath.Text), RsiState.Text),
                2 => new SpriteSpecifier.Texture(new ResPath(SpritePath.Text)),
                _ => sprite
            };

            sound = SoundType.SelectedId switch
            {
                1 => new SoundPathSpecifier(new ResPath(SoundPath.Text), @params),
                2 => new SoundCollectionSpecifier(SoundPath.Text, @params),
                _ => sound
            };

            TryParseTimeSpan(FadeInTime, FadeInTime.Text, out var fadeInTime);
            TryParseTimeSpan(HoldTime, HoldTime.Text, out var holdTime);
            TryParseTimeSpan(FadeTime, FadeTime.Text, out var fadeTime);
            TryParseTimeSpan(KnockdownTime, KnockdownTime.Text, out var knockdownTime);

            var jumpscare = new JumpscareData
            {
                Sprite = sprite,
                Sound = sound,
                AshTarget = AshTarget.Pressed,
                FreezeTarget = FreezeTarget.Pressed,
                KnockdownTarget = KnockdownTarget.Pressed,
                SoundAudibleToOthers = SoundAudibleToOthers.Pressed,
                RenderAboveUI = RenderAboveUI.Pressed,
                FadeInTime = fadeInTime ?? TimeSpan.Zero,
                HoldTime = holdTime ?? TimeSpan.FromSeconds(1),
                FadeTime = fadeTime ?? TimeSpan.FromSeconds(1),
                KnockdownTime = knockdownTime ?? TimeSpan.FromSeconds(5),
                Damage = _damage
            };

            OnDoJumpscare?.Invoke(jumpscare, Targets);
        };

        RefreshDamageTypes();
        RefreshDamageGroups();
    }

    /// <summary>
    /// Applies state from the server. Locks the panel to a single target, or unlocks it for multiple targets
    /// picked from <paramref name="players"/> if <paramref name="lockedTarget"/> is null.
    /// </summary>
    public void SetState(NetEntity? lockedTarget, List<JumpscarePlayerInfo> players)
    {
        AllowMultiTarget = lockedTarget == null;
        SelectTargetsButton.Visible = AllowMultiTarget;

        if (lockedTarget is { } locked)
        {
            _targetWindow?.Close();
            Targets.Clear();
            Targets.Add(locked);
            Title = Loc.GetString("jumpscare-ui-window-title",
                ("name", _ent.ToPrettyString(_ent.GetEntity(locked))));
            UpdateTargetsButton();
            return;
        }

        Title = Loc.GetString("jumpscare-ui-window-title-multi");

        // Keep the existing selection, minus anyone who left or changed bodies.
        _players = players;
        var available = players.Select(p => p.Entity).ToHashSet();
        Targets.IntersectWith(available);

        _targetWindow?.SetPlayers(_players);
        UpdateTargetsButton();
    }

    private void OpenTargetWindow()
    {
        if (_targetWindow == null)
        {
            _targetWindow = new JumpscareTargetSelectWindow(Targets);
            _targetWindow.OnSelectionChanged += UpdateTargetsButton;
            _targetWindow.OnClose += () => _targetWindow = null;
            _targetWindow.SetPlayers(_players);
            _targetWindow.OpenCentered();
        }
        else
            _targetWindow.MoveToFront();

        OnRequestPlayers?.Invoke();
    }

    private void UpdateTargetsButton()
    {
        SelectTargetsButton.Text = Loc.GetString("jumpscare-ui-select-targets-button", ("count", Targets.Count));
        SubmitButton.Disabled = Targets.Count == 0;
    }

    private static void AddMarginRecursive(Control control)
    {
        foreach (var child in control.Children)
            if (child is Label label)
                label.Margin = new Thickness(0, 0, 5, 0);
            else if (child.ChildCount > 0) AddMarginRecursive(child);
    }

    private void RefreshDamageTypes()
    {
        DamageTypeOptionButton.Clear();
        foreach (var lineEdit in _damageLineEdits) _lastText.Remove(lineEdit);
        AddDamageTypeButton.Disabled = true;
        DamageTypeOptionButton.AddItem(Loc.GetString("jumpscare-ui-damage-none"), 0);
        var types = _proto.EnumeratePrototypes<DamageTypePrototype>();
        var idx = 1;
        foreach (var type in types)
        {
            if (_damage.DamageDict.ContainsKey(type)) continue;
            DamageTypeOptionButton.AddItem(type.LocalizedName, idx);
            DamageTypeOptionButton.SetItemMetadata(idx, type);
            idx++;
        }
        DamageTypeOptionButton.SelectId(0);

        DamageTypeContainer.RemoveAllChildren();
        foreach (var type in _damage.DamageDict)
        {
            var hbox = new HBox();
            var label = new Label { Text = _proto.Index(type.Key).LocalizedName };
            var lineEdit = new LineEdit { Text = type.Value.ToString(), HorizontalExpand = true };
            lineEdit.OnFocusExit += args =>
            {
                if (!TryParseFloat(lineEdit, args.Text, out var value)) return;
                _lastText[lineEdit] = args.Text;
                _damage += new DamageSpecifier { DamageDict = { { type.Key, FixedPoint2.New(value.Value) } } };
            };
            var rmButton = new Button
            {
                Text = Loc.GetString("jumpscare-ui-rm-damage-button"),
                StyleClasses = new StyleClassCollection("negative")
            };
            rmButton.OnPressed += _ =>
            {
                _damage.DamageDict.Remove(type.Key);
                RefreshDamageTypes();
            };
            DamageTypeContainer.AddChild(hbox);
            hbox.AddChild(label);
            hbox.AddChild(lineEdit);
            hbox.AddChild(rmButton);
            _lastText.Add(lineEdit, lineEdit.Text);
            _damageLineEdits.Add(lineEdit);
        }
    }

    private void RefreshDamageGroups()
    {
        DamageGroupOptionButton.Clear();
        foreach (var lineEdit in _damageLineEdits) _lastText.Remove(lineEdit);
        AddDamageGroupButton.Disabled = true;
        DamageGroupOptionButton.AddItem(Loc.GetString("jumpscare-ui-damage-none"), 0);
        var types = _proto.EnumeratePrototypes<DamageGroupPrototype>();
        var idx = 1;
        foreach (var type in types)
        {
            if (_damage.DamageGroupDict.ContainsKey(type)) continue;
            DamageGroupOptionButton.AddItem(type.LocalizedName, idx);
            DamageGroupOptionButton.SetItemMetadata(idx, type);
            idx++;
        }
        DamageGroupOptionButton.SelectId(0);

        DamageGroupContainer.RemoveAllChildren();
        foreach (var type in _damage.DamageGroupDict)
        {
            var hbox = new HBox();
            var label = new Label { Text = _proto.Index(type.Key).LocalizedName };
            var lineEdit = new LineEdit { Text = type.Value.ToString(), HorizontalExpand = true };
            lineEdit.OnFocusExit += args =>
            {
                if (!TryParseFloat(lineEdit, args.Text, out var value)) return;
                _lastText[lineEdit] = args.Text;
                _damage += new DamageSpecifier { DamageGroupDict = { { type.Key, FixedPoint2.New(value.Value) } } };
            };
            var rmButton = new Button { Text = Loc.GetString("jumpscare-ui-rm-damage-button") };
            rmButton.OnPressed += _ =>
            {
                _damage.DamageGroupDict.Remove(type.Key);
                RefreshDamageTypes();
            };
            DamageGroupContainer.AddChild(hbox);
            hbox.AddChild(label);
            hbox.AddChild(lineEdit);
            hbox.AddChild(rmButton);
            _lastText.Add(lineEdit, lineEdit.Text);
            _damageLineEdits.Add(lineEdit);
        }
    }

    private bool TryParseFloat(LineEdit lineEdit, string line, [NotNullWhen(true)] out float? value)
    {
        value = null;
        if (!float.TryParse(line, out var result))
        {
            lineEdit.Text = _lastText[lineEdit];
            return false;
        }
        _lastText[lineEdit] = line;
        value = result;
        return true;
    }

    private void TryParseTimeSpan(LineEdit lineEdit, string line, out TimeSpan? value)
    {
        value = null;
        if (!float.TryParse(line, out var seconds) || seconds < 0)
        {
            lineEdit.Text = _lastText[lineEdit];
            return;
        }

        _lastText[lineEdit] = line;
        value = TimeSpan.FromSeconds(seconds);
    }
}

