using Content.Client.Stylesheets;
using Content.Client.UserInterface.Controls;
using Content.Shared._Starlight.MeteorShield;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Starlight.MeteorShield;

[GenerateTypedNameReferences]
public sealed partial class MeteorShieldConsoleWindow : FancyWindow
{
    public event Action<NetEntity>? OnToggle;

    public MeteorShieldConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        HelpLabel.SetMessage(FormattedMessage.FromMarkupPermissive(Loc.GetString("meteor-shield-console-help")));
    }

    public void UpdateState(MeteorShieldConsoleUiState state)
    {
        CoverageBar.Value = state.Coverage;
        CoverageLabel.Text = Loc.GetString("meteor-shield-console-percent", ("percent", (int) (state.Coverage * 100)));
        DestroyedLabel.Text = Loc.GetString("meteor-shield-console-destroyed", ("count", state.Destroyed));
        GoalLabel.Text = state.GoalCoverage is { } goal
            ? Loc.GetString("meteor-shield-console-goal", ("percent", (int) (goal * 100)))
            : string.Empty;

        SatelliteList.RemoveAllChildren();
        if (state.Satellites.Count == 0)
        {
            SatelliteList.AddChild(new Label
            {
                Text = Loc.GetString("meteor-shield-console-no-satellites"),
                StyleClasses = { StyleClass.LabelWeak },
            });
            return;
        }

        foreach (var satellite in state.Satellites)
            SatelliteList.AddChild(SatelliteRow(satellite));
    }

    private Control SatelliteRow(MeteorShieldSatelliteState satellite)
    {
        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 8 };

        row.AddChild(new Label
        {
            Text = satellite.Designation,
            StyleClasses = { StyleClass.LabelKeyText },
            MinWidth = 90,
            VerticalAlignment = VAlignment.Center,
        });

        var status = satellite.Active
            ? "meteor-shield-console-status-active"
            : satellite.InSpace
                ? "meteor-shield-console-status-standby"
                : "meteor-shield-console-status-not-in-space";

        var statusLabel = new Label
        {
            Text = Loc.GetString(status),
            HorizontalExpand = true,
            VerticalAlignment = VAlignment.Center,
        };
        if (satellite.Active)
            statusLabel.AddStyleClass(StyleClass.StatusGood);
        else if (!satellite.InSpace)
            statusLabel.AddStyleClass(StyleClass.StatusWarning);
        row.AddChild(statusLabel);

        row.AddChild(new Label
        {
            Text = Loc.GetString("meteor-shield-console-distance", ("distance", (int) satellite.Distance)),
            StyleClasses = { StyleClass.LabelWeak },
            MinWidth = 70,
            VerticalAlignment = VAlignment.Center,
        });

        var toggle = new Button
        {
            Text = Loc.GetString(satellite.Active ? "meteor-shield-console-deactivate" : "meteor-shield-console-activate"),
            Disabled = !satellite.Active && !satellite.InSpace,
            MinWidth = 100,
        };
        var entity = satellite.Entity;
        toggle.OnPressed += _ => OnToggle?.Invoke(entity);
        row.AddChild(toggle);

        return row;
    }
}
