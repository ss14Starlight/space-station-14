using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Starlight.UserInterface.Controls;

/// <summary>
/// A control that displays a conversation with messages and allows the player to send messages.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class ConversationView : BoxContainer
{
    private readonly List<FormattedMessage> _messages = new();
    private string _filter = string.Empty;

    /// <summary>
    /// Raised when the player submits a message. The message text is passed as an argument.
    /// </summary>
    public event Action<string>? OnMessageSubmitted;

    public event Action<string>? OnInputChanged;

    public bool InputVisible
    {
        get => InputRow.Visible;
        set => InputRow.Visible = value;
    }

    public ConversationView()
    {
        RobustXamlLoader.Load(this);

        SearchLineEdit.OnTextChanged += args => SetFilter(args.Text);
        InputLineEdit.OnTextEntered += args => Submit(args.Text);
        InputLineEdit.OnTextChanged += args => OnInputChanged?.Invoke(args.Text);
        SendButton.OnPressed += _ => Submit(InputLineEdit.Text);
    }

    /// <summary>
    /// Adds a message to the conversation view. If the message matches the current filter, it will also be displayed in the output.
    /// </summary>
    public void AddMessage(FormattedMessage message)
    {
        _messages.Add(message);
        if (Matches(message))
            Output.AddMessage(message);
    }

    /// <summary>
    /// Sets the text for the typing indicator.
    /// </summary>
    public void SetTyping(string text)
    {
        TypingLabel.SetMessage(FormattedMessage.FromUnformatted(text));
        TypingLabel.Visible = text.Length > 0;
    }

    private void Submit(string text)
    {
        if (string.IsNullOrWhiteSpace(text))
            return;

        OnMessageSubmitted?.Invoke(text);
        InputLineEdit.Clear();
    }

    private void SetFilter(string filter)
    {
        _filter = filter.Trim();
        Output.Clear();
        foreach (var message in _messages)
        {
            if (Matches(message))
                Output.AddMessage(message);
        }
    }

    private bool Matches(FormattedMessage message)
        => _filter.Length == 0 || message.ToString().Contains(_filter, StringComparison.CurrentCultureIgnoreCase);
}
