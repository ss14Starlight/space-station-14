using System.Numerics;
using Content.Shared.CartridgeLoader.Cartridges;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Map;

namespace Content.Client.CartridgeLoader.Cartridges;

[GenerateTypedNameReferences]
public sealed partial class MapUiFragment : Control
{
    [Dependency] private IEntityManager _entMan = default!;
    public MapUiFragment()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

    }

    public void UpdateState(MapUiState state)
    {
        if (_entMan.TryGetEntity(state.mapUid, out var mapUid) &&
            _entMan.TryGetEntity(state.trackedEntityUid, out var trackedEntityUid))
        {
            _entMan.TryGetComponent<TransformComponent>(trackedEntityUid, out var transform);
            NavMapScreen.MapUid = transform!.GridUid;
            if (trackedEntityUid is { } trackent)
                NavMapScreen.TrackedCoordinates.Add(new EntityCoordinates(trackent, Vector2.Zero),
                    (true, Color.Cyan));
            NavMapScreen.ForceNavMapUpdate();
            NavMapScreen.ForceRecenter();
        }
    }
}

