using Content.Shared._Starlight.Medical.Virology;
using Content.Client.Pinpointer.UI;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Starlight.Medical.Virology;

[GenerateTypedNameReferences]
public sealed partial class PathogenDetectorWindow : DefaultWindow
{
    public NavMapControl MapControl => ContaminationMap;

    public PathogenDetectorWindow()
    {
        RobustXamlLoader.Load(this);
    }

    public void UpdateState(PathogenDetectorUiState state)
    {
        StationNameLabel.Text = state.StationName;
        ContaminationBar.Value = state.Contamination;
        ContaminationValueLabel.Text = Loc.GetString(
            "pathogen-monitor-contamination-value",
            ("level", state.Contamination.ToString("0.0")));
        SignatureLabel.Text = Loc.GetString(
            "pathogen-monitor-signatures",
            ("virus", state.Virus.ToString("0.0")),
            ("bacteria", state.Bacteria.ToString("0.0")),
            ("fungus", state.Fungus.ToString("0.0")));

        RoomList.Clear();
        if (state.Groups.Count == 0)
        {
            RoomList.Add(new ItemList.Item(RoomList)
            {
                Text = Loc.GetString("pathogen-monitor-no-contaminated-rooms"),
                Disabled = true,
            });
        }
        else
        {
            foreach (var group in state.Groups)
            {
                RoomList.Add(new ItemList.Item(RoomList)
                {
                    Text = Loc.GetString(
                        "pathogen-monitor-room-entry",
                        ("room", group.BeaconName),
                        ("level", group.Total.ToString("0.0"))),
                    Disabled = true,
                });
            }
        }

        SickCrewList.Clear();
        if (state.SickCrew.Count == 0)
        {
            SickCrewList.Add(new ItemList.Item(SickCrewList)
            {
                Text = Loc.GetString("pathogen-monitor-no-sick-crew"),
                Disabled = true,
            });
            return;
        }

        foreach (var name in state.SickCrew)
        {
            SickCrewList.Add(new ItemList.Item(SickCrewList)
            {
                Text = name,
                Disabled = true,
            });
        }
    }
}
