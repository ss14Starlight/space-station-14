using Content.Shared._Starlight.Medical.Virology;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Starlight.Medical.Virology;

[GenerateTypedNameReferences]
public sealed partial class PathogenDetectorWindow : DefaultWindow
{
    public PathogenDetectorWindow()
    {
        RobustXamlLoader.Load(this);
    }

    public void UpdateState(PathogenDetectorUiState state)
    {
        InfectionList.Clear();
        if (state.Infections.Count == 0)
        {
            InfectionList.Add(new ItemList.Item(InfectionList)
            {
                Text = Loc.GetString("pathogen-detector-no-infections"),
                Disabled = true,
            });
        }
        else
        {
            foreach (var entry in state.Infections)
            {
                InfectionList.Add(new ItemList.Item(InfectionList)
                {
                    Text = Loc.GetString(
                        "pathogen-detector-entry",
                        ("name", entry.Name),
                        ("detection", entry.Detection)),
                    Disabled = true,
                });
            }
        }

        ContaminationLabel.Text = state.Contamination;
    }
}
