using System.Linq;
using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared._Starlight.Knapping;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Starlight.Knapping.UI;

[GenerateTypedNameReferences]
public sealed partial class KnappingWindow : FancyWindow
{
    public event Action<int, int, bool>? OnTileSet;
    public event Action<string>? OnRecipeSelected;
    public event Action? OnFinishPressed;

    private readonly List<Button> _boardButtons = [];
    private readonly List<Button> _previewButtons = [];
    private readonly Dictionary<int, string> _recipeByOptionId = [];

    private int _width;
    private int _height;
    private bool _carveMode = true;
    private bool _allowRestore = true;

    private static readonly Color _filledTint = new(0.88f, 0.69f, 0.48f);
    private static readonly Color _removedTint = new(0.28f, 0.22f, 0.18f);
    private static readonly Color _previewFilledTint = new(0.78f, 0.61f, 0.44f);
    private static readonly Color _previewRemovedTint = new(0.20f, 0.17f, 0.15f);

    public KnappingWindow()
    {
        RobustXamlLoader.Load(this);

        RecipeOption.OnItemSelected += args =>
        {
            RecipeOption.SelectId(args.Id);

            if (_recipeByOptionId.TryGetValue(args.Id, out var recipe))
                OnRecipeSelected?.Invoke(recipe);
        };

        CarveModeButton.OnPressed += _ =>
        {
            _carveMode = true;
            UpdateModeButtons(null);
        };

        RestoreModeButton.OnPressed += _ =>
        {
            if (!_allowRestore)
                return;

            _carveMode = false;
            UpdateModeButtons(null);
        };

        FinishButton.OnPressed += _ => OnFinishPressed?.Invoke();
    }

    public void SetState(KnappingBoundUserInterfaceState state)
    {
        Title = Loc.GetString(state.Text.WindowTitle);
        SubtitleLabel.Text = Loc.GetString(state.Text.WindowSubtitle);
        BoardHeaderLabel.Text = Loc.GetString(state.Text.BoardLabel);
        RecipeHeaderLabel.Text = Loc.GetString(state.Text.RecipeLabel);
        PreviewHeaderLabel.Text = Loc.GetString(state.Text.PreviewLabel);
        HelpLabel.Text = Loc.GetString(state.Text.WorkpieceHelp);
        FinishButton.Text = Loc.GetString(state.Text.FinishButtonText);
        MaterialLabel.Text = Loc.GetString(state.Text.MaterialLabel, ("material", Loc.GetString(state.MaterialName)));

        _allowRestore = state.AllowRestore;
        if (!_allowRestore)
            _carveMode = true;

        if (_width != state.Width || _height != state.Height)
            RebuildGrids(state.Width, state.Height);

        UpdateBoard(state);
        UpdateRecipes(state);
        UpdatePreview(state);
        UpdateModeButtons(state);

        var selected = state.Recipes.FirstOrDefault(x => x.Id == state.SelectedRecipe);
        RecipeCategoryLabel.Text = selected == null
            ? string.Empty
            : Loc.GetString(selected.Category);
        RecipeDescriptionLabel.Text = selected == null
            ? string.Empty
            : Loc.GetString(selected.Description);

        StatusLabel.Text = Loc.GetString(state.Status);
        FinishButton.Disabled = !state.CanFinish;
    }

    private void RebuildGrids(int width, int height)
    {
        _width = width;
        _height = height;

        BoardGrid.Columns = width;
        PreviewGrid.Columns = width;

        BoardGrid.RemoveAllChildren();
        PreviewGrid.RemoveAllChildren();
        _boardButtons.Clear();
        _previewButtons.Clear();

        for (var y = 0; y < height; y++)
        {
            for (var x = 0; x < width; x++)
            {
                var capturedX = x;
                var capturedY = y;

                var boardButton = new Button
                {
                    MinSize = new Vector2(38, 38),
                    Text = "X",
                    ToolTip = Loc.GetString("knapping-tile-tooltip"),
                };

                boardButton.OnPressed += _ =>
                {
                    if (_carveMode)
                    {
                        OnTileSet?.Invoke(capturedX, capturedY, false);
                        return;
                    }

                    if (_allowRestore)
                        OnTileSet?.Invoke(capturedX, capturedY, true);
                };

                BoardGrid.AddChild(boardButton);
                _boardButtons.Add(boardButton);

                var preview = new Button
                {
                    MinSize = new Vector2(22, 22),
                    Text = "X",
                    Disabled = true,
                };

                PreviewGrid.AddChild(preview);
                _previewButtons.Add(preview);
            }
        }
    }

    private void UpdateBoard(KnappingBoundUserInterfaceState state)
    {
        var count = Math.Min(_boardButtons.Count, state.Filled.Length);

        for (var i = 0; i < count; i++)
        {
            var filled = state.Filled[i];
            ApplyTileVisual(_boardButtons[i], filled, false);

            _boardButtons[i].ToolTip = filled
                ? Loc.GetString("knapping-tile-filled-tooltip")
                : Loc.GetString("knapping-tile-empty-tooltip");
        }
    }

    private void UpdateRecipes(KnappingBoundUserInterfaceState state)
    {
        RecipeOption.Clear();
        _recipeByOptionId.Clear();

        var selectedOption = -1;
        var optionId = 0;

        foreach (var recipe in state.Recipes.OrderBy(x => Loc.GetString(x.Category)).ThenBy(x => x.Difficulty).ThenBy(x => Loc.GetString(x.Name)))
        {
            var difficulty = new string('◆', Math.Clamp(recipe.Difficulty, 1, 5));
            var text = Loc.GetString("knapping-recipe-dropdown-entry",
                ("category", Loc.GetString(recipe.Category)),
                ("recipe", Loc.GetString(recipe.Name)),
                ("difficulty", difficulty));

            RecipeOption.AddItem(text, optionId);
            _recipeByOptionId[optionId] = recipe.Id;

            if (recipe.Id == state.SelectedRecipe)
                selectedOption = optionId;

            optionId++;
        }

        if (selectedOption >= 0)
            RecipeOption.SelectId(selectedOption);
        else if (optionId > 0)
            RecipeOption.SelectId(0);
    }

    private void UpdatePreview(KnappingBoundUserInterfaceState state)
    {
        var recipe = state.Recipes.FirstOrDefault(x => x.Id == state.SelectedRecipe);
        var count = Math.Min(_previewButtons.Count, state.Width * state.Height);

        for (var i = 0; i < count; i++)
        {
            var x = i % state.Width;
            var y = i / state.Width;
            var filled = recipe != null && PreviewCellFilled(recipe, x, y, state.Width, state.Height);

            ApplyTileVisual(_previewButtons[i], filled, true);
        }
    }

    private void UpdateModeButtons(KnappingBoundUserInterfaceState? state)
    {
        var carveText = state == null ? "knapping-mode-carve" : state.Text.CarveModeText;
        var restoreText = state == null ? "knapping-mode-restore" : state.Text.RestoreModeText;
        var restoreLockedText = state == null ? "knapping-mode-restore-locked" : state.Text.RestoreLockedText;

        CarveModeButton.Text = Loc.GetString(carveText);
        RestoreModeButton.Text = _allowRestore ? Loc.GetString(restoreText) : Loc.GetString(restoreLockedText);

        CarveModeButton.Disabled = _carveMode;
        RestoreModeButton.Disabled = !_allowRestore || !_carveMode;
    }

    private static void ApplyTileVisual(Button button, bool filled, bool preview)
    {
        button.Text = "X";
        button.Modulate = preview
            ? filled ? _previewFilledTint : _previewRemovedTint
            : filled ? _filledTint : _removedTint;
    }

    private static bool PreviewCellFilled(KnappingRecipeView recipe, int x, int y, int width, int height)
    {
        if (recipe.Pattern.Length == 0)
            return false;

        var patternHeight = recipe.Pattern.Length;
        var patternWidth = recipe.Pattern.Max(p => p.Length);

        var xOffset = Math.Max(0, (width - patternWidth) / 2);
        var yOffset = Math.Max(0, (height - patternHeight) / 2);

        var patternX = x - xOffset;
        var patternY = y - yOffset;

        if (patternX < 0 || patternY < 0 || patternY >= recipe.Pattern.Length)
            return false;

        if (patternX >= recipe.Pattern[patternY].Length)
            return false;

        var c = recipe.Pattern[patternY][patternX];
        return c is '#' or 'X' or 'x';
    }
}
