    /// <summary>
    /// Generates and binds the visual row for a station event catalog item.
    /// </summary>
    private void GenerateItem(ListData data, ListContainerButton button)
    {
        if (data is not StationEventListData row)
            return;

        var panel = new PanelContainer
        {
            PanelOverride = new StyleBoxFlat { BackgroundColor = row.BackgroundColor },
            HorizontalExpand = true
        };

        var root = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            SeparationOverride = 4,
            Margin = new Thickness(8)
        };

        var textColumn = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            SizeFlagsStretchRatio = 1
        };

        textColumn.AddChild(new Label
        {
            Text = $"{HumanizeId(row.Info.Id)} ({row.Info.Id})",
            FontColorOverride = Color.White
        });

        var runtimeLabel = new Label { Text = BuildRuntimeText(row.Info) };
        runtimeLabel.StyleClasses.Add(StyleNano.StyleClassLabelSubText);
        textColumn.AddChild(runtimeLabel);

        var metaLabel = new Label { Text = BuildSchedulingText(row.Info) };
        metaLabel.StyleClasses.Add(StyleNano.StyleClassLabelSubText);
        textColumn.AddChild(metaLabel);

        var runButton = new Button
        {
            Text = Loc.GetString("administration-ui-events-tab-force"),
            Disabled = !_admin.CanCommand("addgamerule")
        };
        // Same network path as Schedule, so the server applies the one AdminFlags.Fun check
        // instead of this going out as a console command.
        runButton.OnPressed += _ =>
        {
            _adminSystem.SendStationEventCommand(
                StationEventQueueCommand.Schedule,
                eventId: row.Info.Id,
                seconds: 0f);
            RefreshSnapshot();
        };
        if (runButton.Disabled)
            runButton.ToolTip = Loc.GetString("administration-ui-events-tab-force-disabled");

        var delayInput = new LineEdit
        {
            Text = _delayInputs.TryGetValue(row.Info.Id, out var savedDelay) ? savedDelay : DefaultDelayMinutes,
            PlaceHolder = Loc.GetString("administration-ui-events-tab-schedule-minutes-placeholder"),
            ToolTip = Loc.GetString("administration-ui-events-tab-schedule-minutes-tooltip"),
            MinWidth = 52
        };
        // Remembered per event so it survives the row being recycled.
        delayInput.OnTextChanged += changed => _delayInputs[row.Info.Id] = changed.Text;

        // Nudging by a minute is the common case; typing is still there for anything else.
        void StepDelay(float delta)
        {
            if (!float.TryParse(delayInput.Text, out var current))
                current = 0f;

            var next = Math.Clamp(current + delta, 0f, 24f * 60f);
            delayInput.Text = FormatNumber(next);
            _delayInputs[row.Info.Id] = delayInput.Text;
        }

        var minusButton = new Button
        {
            Text = "-",
            ToolTip = Loc.GetString("administration-ui-events-tab-schedule-minus-tooltip"),
            MinWidth = 28
        };
        minusButton.OnPressed += _ => StepDelay(-1f);

        var plusButton = new Button
        {
            Text = "+",
            ToolTip = Loc.GetString("administration-ui-events-tab-schedule-plus-tooltip"),
            MinWidth = 28
        };
        plusButton.OnPressed += _ => StepDelay(1f);
        var scheduleButton = new Button
        {
            Text = Loc.GetString("administration-ui-events-tab-schedule"),
            Disabled = !_admin.CanCommand("addgamerule") || !_hasScheduler
        };
        scheduleButton.OnPressed += _ =>
        {
            if (!float.TryParse(delayInput.Text, out var minutes))
                return;

            minutes = Math.Clamp(minutes, 0f, 24f * 60f);
            _adminSystem.SendStationEventCommand(
                StationEventQueueCommand.Schedule,
                eventId: row.Info.Id,
                seconds: minutes * 60f);
            RefreshSnapshot();
        };
        if (!_hasScheduler)
            scheduleButton.ToolTip = Loc.GetString("administration-ui-events-tab-schedule-no-scheduler");

        // The controls sit on their own row rather than beside the text: in a horizontal row
        // they got squeezed to nothing as soon as the menu was narrow, leaving unusable
        // slivers of button. Stacked, the layout holds at any width.
        var controls = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 4,
            HorizontalExpand = true
        };

        controls.AddChild(minusButton);
        controls.AddChild(delayInput);
        controls.AddChild(plusButton);
        controls.AddChild(scheduleButton);
        controls.AddChild(runButton);

        root.AddChild(textColumn);
        root.AddChild(controls);
        panel.AddChild(root);

        button.AddChild(panel);
        button.StyleClasses.Clear();
        button.ToolTip = row.Info.Id;
    }

    /// <summary>
    /// Populates the sort options dropdown with all available sorting criteria.
    /// </summary>
    private void PopulateSortOptions()
    {
        SortOptionButton.Clear();
