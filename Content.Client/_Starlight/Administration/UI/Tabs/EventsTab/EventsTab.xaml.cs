    /// <summary>
    ///     Minutes typed by the admin, per event.
    /// </summary>
    /// <remarks>
    ///     The ListContainer recycles its buttons and calls GenerateItem again on every
    ///     refresh, so a row's LineEdit is rebuilt once per second. Without keeping the text
    ///     here, whatever the admin typed was wiped back to the default before they could
    ///     press Schedule.
    /// </remarks>
    private readonly Dictionary<string, string> _delayInputs = new();

    private const string DefaultDelayMinutes = "5";

    /// <summary>
    ///     Trims a float down to something readable.
    /// </summary>
    /// <remarks>
    ///     Round duration and weights are floats, and weights in particular come out of a
    ///     power calculation, so printing them raw produced values like 1.2000000000476837.
    ///     Two decimals is plenty for a panel and drops the floating point noise.
    /// </remarks>
    private static string FormatNumber(float value) => value.ToString("0.##");

    /// <summary>
    ///     Wires a section header's toggle so the section can be folded away.
    /// </summary>
    /// <remarks>
    ///     Collapsing clears VerticalExpand as well as hiding the body, otherwise a folded
    ///     section would keep reserving its share of the height. The section's original expand
    ///     setting is captured rather than assumed: only the catalogue stretches, while the
    ///     active and queue lists size to their content, and forcing expand back on when
    ///     reopening them would leave the empty grey gap this was meant to remove.
    /// </remarks>
    private void SetUpSection(Control section, Control body, Button toggle)
    {
        var expandsWhenOpen = section.VerticalExpand;
        var expanded = true;

        void Apply()
        {
            body.Visible = expanded;
            section.VerticalExpand = expanded && expandsWhenOpen;
            toggle.Text = expanded ? "-" : "+";
        }

        Apply();
        toggle.OnPressed += _ =>
        {
            expanded = !expanded;
            Apply();
        };
    }

    /// <summary>
    /// Constructs and initializes the administration events tab, setting up UI bindings and section controllers.
    /// </summary>
    public EventsTab()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        _adminSystem = _entityManager.System<AdminSystem>();
        _adminSystem.StationEventsChanged += OnStationEventsChanged;

        SearchList.SearchBar = SearchLineEdit;
        SearchList.GenerateItem += GenerateItem;
        SearchList.DataFilterCondition += DataFilterCondition;

        AvailableOnlyButton.OnPressed += _ => Repopulate(_adminSystem.StationEventsSnapshot);
        RefreshButton.OnPressed += _ => RefreshSnapshot();
        SortOptionButton.OnItemSelected += OnSortItemSelected;
        SortDirectionButton.OnPressed += _ =>
        {
            _sortAscending = !_sortAscending;
            UpdateSortDirectionText();
            Repopulate(_adminSystem.StationEventsSnapshot);
        };

        SetUpSection(ActiveSection, ActiveScroll, ActiveToggleButton);
        SetUpSection(QueueSection, QueueScroll, QueueToggleButton);
        SetUpSection(CatalogSection, CatalogBody, CatalogToggleButton);

        PopulateSortOptions();
        UpdateSortDirectionText();

        if (_adminSystem.StationEventsSnapshot != null)
            Repopulate(_adminSystem.StationEventsSnapshot);
        else
            RefreshSnapshot();
    }

    /// <inheritdoc/>
    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);

        if (!disposing)
            return;

        _adminSystem.StationEventsChanged -= OnStationEventsChanged;
    }

    /// <summary>
    /// Handles station events snapshot updates received from the server.
    /// </summary>
    private void OnStationEventsChanged(StationEventsChangedEvent snapshot)
    {
        Repopulate(snapshot);
    }

    /// <inheritdoc/>
    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        // The TabContainer keeps hidden tabs in the tree, so this keeps running even while
        // the admin sits on another tab. Without this check, having the menu open on Players
        // still requested the events snapshot once per second.
        if (!Visible)
            return;

        _refreshAccumulator += args.DeltaSeconds;
        if (_refreshAccumulator < AutoRefreshInterval)
            return;

        RefreshSnapshot();
    }

    /// <summary>
    /// Re-renders the event catalog, queue, active list, and status summary from the given snapshot.
    /// </summary>
    private void Repopulate(StationEventsChangedEvent? snapshot)
    {
        if (snapshot == null)
        {
            SummaryLabel.Text = Loc.GetString("administration-ui-events-tab-loading");
            SearchList.PopulateList(new List<ListData>());
            return;
        }

        _hasScheduler = snapshot.HasScheduler;
        // Active first: what is happening right now is what an admin reacts to, and it is the
        // shorter list. Upcoming is for planning and can sit below.
        PopulateActiveEvents(snapshot);
        PopulateQueue(snapshot);

        var activeCount = snapshot.ActiveEvents.Count;
        var pendingCount = snapshot.Events.Sum(ev => ev.PendingCount);
        SummaryLabel.Text = Loc.GetString(
            "administration-ui-events-tab-summary",
            ("count", snapshot.Events.Count),
            ("active", activeCount),
            ("pending", pendingCount),
            ("players", snapshot.PlayerCount),
            ("minutes", FormatNumber(snapshot.RoundDurationMinutes)),
            ("enabled", snapshot.HasScheduler && snapshot.EventsEnabled
                ? Loc.GetString("administration-ui-events-tab-enabled")
                : Loc.GetString("administration-ui-events-tab-disabled")));

        var orderedEvents = SortEvents(snapshot.Events);

        var rows = orderedEvents
            .Where(ev => !AvailableOnlyButton.Pressed || ev.Available)
            .Select((ev, index) => new StationEventListData(
                ev,
                index % 2 == 0 ? _altColor : _defaultColor,
                BuildFilterString(ev)))
            .ToList<ListData>();

        SearchList.PopulateList(rows);
    }

    /// <summary>
    /// Populates the upcoming queued events section.
    /// </summary>
    private void PopulateQueue(StationEventsChangedEvent snapshot)
    {
        QueueList.RemoveAllChildren();

        // Presets such as Survival use a ramping scheduler, which exposes no queue. Rather
        // than implying everything is visible, say part of it is missing. This runs before the
        // no-scheduler check on purpose: a round with only ramping schedulers has nothing this
        // panel can queue into, and reporting that as "no scheduler" with no further comment
        // would claim events are not running when they are.
        if (snapshot.UnreadableSchedulers > 0)
        {
            QueueList.AddChild(new Label
            {
                Text = Loc.GetString("administration-ui-events-tab-queue-incomplete",
                    ("count", snapshot.UnreadableSchedulers)),
                ModulateSelfOverride = Color.Orange
            });
        }

        if (!snapshot.HasScheduler)
        {
            QueueStatusLabel.Text = Loc.GetString("administration-ui-events-tab-queue-no-scheduler");
            return;
        }

        QueueStatusLabel.Text = snapshot.Queue.Count == 0
            ? Loc.GetString("administration-ui-events-tab-queue-empty")
            : Loc.GetString("administration-ui-events-tab-queue-count", ("count", snapshot.Queue.Count));

        foreach (var queued in snapshot.Queue)
        {
            var panel = CreatePanel(queued.Automatic ? Color.FromHex("#24384A") : Color.FromHex("#3D3523"));
            // Text on top, controls underneath. Side by side, a long event name set the row's
            // minimum width and the buttons were squeezed out of view one by one as the window
            // narrowed, so the widest names lost their controls first.
            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                SeparationOverride = 4,
                Margin = new Thickness(7)
            };
            var details = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                HorizontalExpand = true
            };

            details.AddChild(new Label
            {
                Text = Loc.GetString(
                    queued.Automatic
                        ? "administration-ui-events-tab-queue-automatic"
                        : "administration-ui-events-tab-queue-manual",
                    ("event", HumanizeId(queued.EventId)),
                    ("id", queued.EventId)),
                // Clipped rather than allowed to push the row wider than the tab.
                ClipText = true
            });
            details.AddChild(new Label
            {
                Text = Loc.GetString("administration-ui-events-tab-queue-starts-in",
                    ("time", FormatSeconds(queued.TriggerInSeconds))),
                ModulateSelfOverride = Color.LightSteelBlue
            });
            // Without this, a queue holding one event in 4 minutes and another in 43 reads
            // as a bug.
            if (!string.IsNullOrEmpty(queued.Scheduler))
            {
                details.AddChild(new Label
                {
                    Text = Loc.GetString("administration-ui-events-tab-queue-scheduler",
                        ("scheduler", HumanizeId(queued.Scheduler))),
                    ModulateSelfOverride = Color.DarkGray
                });
            }
            details.AddChild(new ProgressBar
            {
                HorizontalExpand = true,
                MaxValue = Math.Max(queued.TotalDelaySeconds, 1f),
                Value = Math.Clamp(queued.TriggerInSeconds, 0f, Math.Max(queued.TotalDelaySeconds, 1f))
            });

            var actions = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 4,
                HorizontalExpand = true
            };

            row.AddChild(details);
            AddQueueButton(actions, Loc.GetString("administration-ui-events-tab-queue-minus-5"), queued.Id, StationEventQueueCommand.Adjust, -300f);
            AddQueueButton(actions, Loc.GetString("administration-ui-events-tab-queue-minus-1"), queued.Id, StationEventQueueCommand.Adjust, -60f);
            AddQueueButton(actions, Loc.GetString("administration-ui-events-tab-queue-plus-1"), queued.Id, StationEventQueueCommand.Adjust, 60f);
            AddQueueButton(actions, Loc.GetString("administration-ui-events-tab-queue-plus-5"), queued.Id, StationEventQueueCommand.Adjust, 300f);
            AddQueueButton(actions,
                Loc.GetString("administration-ui-events-tab-queue-now"),
                queued.Id,
                StationEventQueueCommand.RunNow);
            AddQueueButton(actions,
                Loc.GetString("administration-ui-events-tab-queue-cancel"),
                queued.Id,
                StationEventQueueCommand.Remove);
            row.AddChild(actions);

            panel.AddChild(row);
            QueueList.AddChild(panel);
        }
    }

    /// <summary>
    /// Populates the list of currently running station events.
    /// </summary>
    private void PopulateActiveEvents(StationEventsChangedEvent snapshot)
    {
        ActiveList.RemoveAllChildren();
        ActiveStatusLabel.Text = snapshot.ActiveEvents.Count == 0
            ? Loc.GetString("administration-ui-events-tab-active-empty")
            : Loc.GetString("administration-ui-events-tab-active-count", ("count", snapshot.ActiveEvents.Count));

        foreach (var active in snapshot.ActiveEvents)
        {
            var panel = CreatePanel(Color.FromHex("#47292B"));
            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                SeparationOverride = 4,
                Margin = new Thickness(7)
            };
            var details = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                HorizontalExpand = true
            };

            details.AddChild(new Label
            {
                Text = $"{HumanizeId(active.EventId)} ({active.EventId})",
                ClipText = true
            });

            if (HasValue(active.RemainingSeconds) && HasValue(active.DurationSeconds))
            {
                details.AddChild(new Label
                {
                    Text = Loc.GetString("administration-ui-events-tab-active-remaining",
                        ("remaining", FormatSeconds(active.RemainingSeconds)),
                        ("duration", FormatSeconds(active.DurationSeconds))),
                    ModulateSelfOverride = Color.LightSalmon
                });
                details.AddChild(new ProgressBar
                {
                    HorizontalExpand = true,
                    MaxValue = Math.Max(active.DurationSeconds, 1f),
                    Value = Math.Clamp(active.RemainingSeconds, 0f, Math.Max(active.DurationSeconds, 1f))
                });
            }
            else
            {
                details.AddChild(new Label
                {
                    Text = Loc.GetString("administration-ui-events-tab-active-open",
                        ("elapsed", FormatSeconds(active.ElapsedSeconds))),
                    ModulateSelfOverride = Color.LightSalmon
                });
            }

            var endButton = new Button
            {
                Text = Loc.GetString("administration-ui-events-tab-active-end"),
                Disabled = !_admin.CanCommand("endgamerule"),
                HorizontalExpand = true
            };
            endButton.OnPressed += _ =>
            {
                _adminSystem.SendStationEventCommand(
                    StationEventQueueCommand.EndActive,
                    activeEvent: active.Entity);
                RefreshSnapshot();
            };

            row.AddChild(details);
            row.AddChild(endButton);
            panel.AddChild(row);
            ActiveList.AddChild(panel);
        }
    }

