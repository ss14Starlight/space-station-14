    // Time parsing utils
    private static int ParseTimeString(string input) => ParseTimeInternal(input, new Dictionary<string, int> { ["s"] = 1, ["sec"] = 1, ["second"] = 1, ["seconds"] = 1, ["m"] = 60, ["min"] = 60, ["minute"] = 60, ["minutes"] = 60, ["h"] = 3600, ["hr"] = 3600, ["hour"] = 3600, ["hours"] = 3600, ["d"] = 86400, ["day"] = 86400, ["days"] = 86400 });
    
    private static int ParseBanTimeString(string input) => ParseTimeInternal(input, new Dictionary<string, int> { ["m"] = 1, ["min"] = 1, ["minute"] = 1, ["minutes"] = 1, ["h"] = 60, ["hr"] = 60, ["hour"] = 60, ["hours"] = 60, ["d"] = 1440, ["day"] = 1440, ["days"] = 1440 });

    private static int ParseTimeInternal(string input, Dictionary<string, int> multipliers)
    {
        if (string.IsNullOrWhiteSpace(input)) return 0;
        input = input.Trim().ToLower();
        if (int.TryParse(input, out var plainNumber)) return plainNumber;
        
        var numberPart = new StringBuilder();
        var suffixPart = new StringBuilder();
        var foundNonDigit = false;
        
        foreach (var c in input)
        {
            if (char.IsDigit(c) && !foundNonDigit) numberPart.Append(c);
            else { foundNonDigit = true; suffixPart.Append(c); }
        }
        
        var numberStr = numberPart.ToString();
        if (!int.TryParse(numberStr, out var number)) return 0;
        var suf = suffixPart.ToString().Trim();
        return multipliers.TryGetValue(suf, out var multiplier) ? number * multiplier : number;
    }

    private static string FormatSeconds(int seconds) => seconds == 0 ? "0s" : seconds < 60 ? $"{seconds}s" : seconds < 3600 ? $"{seconds / 60}m" : seconds < 86400 ? $"{seconds / 3600}h" : $"{seconds / 86400}d";

    private static string FormatMinutes(int minutes) => minutes == 0 ? "0m" : minutes < 60 ? $"{minutes}m" : minutes < 1440 ? $"{minutes / 60}h" : $"{minutes / 1440}d";

    private void RunTest()
    {
        var pattern = TesterPatternInput.Text;
        var text = TesterTextInput.Text;

        if (string.IsNullOrWhiteSpace(pattern))
        {
            TesterResultLabel.SetMessage(FormattedMessage.FromUnformatted(Loc.GetString("automod-tester-error-no-pattern")));
            return;
        }

        try
        {
            var regex = new Regex(pattern, RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);
            var match = regex.Match(text);
            if (match.Success)
                TesterResultLabel.SetMessage(FormattedMessage.FromUnformatted(Loc.GetString("automod-tester-match-found", ("match", match.Value))));
            else
                TesterResultLabel.SetMessage(FormattedMessage.FromUnformatted(Loc.GetString("automod-tester-no-match")));
        }
        catch (ArgumentException ex)
        {
            TesterResultLabel.SetMessage(FormattedMessage.FromUnformatted(Loc.GetString("automod-tester-error-invalid-regex", ("error", ex.Message))));
        }
    }

