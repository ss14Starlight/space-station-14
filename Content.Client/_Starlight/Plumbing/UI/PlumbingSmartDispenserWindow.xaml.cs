[GenerateTypedNameReferences]
public sealed partial class PlumbingSmartDispenserWindow : DefaultWindow
{
    private const int ReagentRowHeight = 40;
    private static readonly Vector2 _compactWindowSize = new(440, 560);
    private static readonly Vector2 _fullWindowSize = new(760, 560);

    [Dependency] private IPrototypeManager _prototypeManager = default!;
    [Dependency] private IEntityManager _entityManager = default!;

    private readonly SolutionContainerSystem _solutionSystem;
    private readonly PlumbingSmartDispenserSystem _smartDispenserSystem;
    private readonly List<ReagentEntry> _reagentEntries = [];
    private readonly Dictionary<string, ClickableBeakerBarChart> _bars = [];

    private bool _localStateDirty = true;
    private bool _showDispensePane;
    private bool _hasOutputContainer;
    private bool _hasLabeler;
    private EntityUid _owner;
    private EntityUid? _outputContainerEntity;
    private ReagentDispenserDispenseAmount _dispenseAmount;
    private int _reagentsHash;
    private int _outputHash;

    public event Action<string, FixedPoint2, NetEntity>? OnDispenseReagentPressed;

    public event Action<NetEntity>? OnClearPressed;

    public PlumbingSmartDispenserWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        ApplyWindowSizing(false);

        _solutionSystem = _entityManager.System<SolutionContainerSystem>();
        _smartDispenserSystem = _entityManager.System<PlumbingSmartDispenserSystem>();

        ClearButton.OnPressed += OnClearClicked;
    }

    /// <summary>
    /// Sets the owning dispenser entity for the window, call immediately after opening UI.
    /// </summary>
    public void SetOwner(EntityUid owner) => _owner = owner;

    protected override void FrameUpdate(FrameEventArgs args)
    {
        static bool SolutionChanged(Solution solution, ref int savedHash)
        {
            HashCode hashCode = default;

            foreach (var (id, quant) in solution.Contents)
            {
                hashCode.Add(id);
                hashCode.Add(quant);
            }

            int code = hashCode.ToHashCode();
            if (code != savedHash)
            {
                savedHash = code;
                return true;
            }

            return false;
        }

        // track the output container's hash too in case
        // they fill it from something else (we don't get an event)
        if (_outputContainerEntity.HasValue &&
            _smartDispenserSystem.GetFillSolutionFromContainer(_outputContainerEntity) is Solution fillSolution &&
            SolutionChanged(fillSolution, ref _outputHash))
            _localStateDirty = true;

        // always update the state when we have a labeler
        // (it's cheap + the labeler selected label doesn't give us an event when it changes)
        if (_localStateDirty || _hasLabeler)
            UpdateLocalState();

        if (_entityManager.TryGetComponent<PlumbingSmartDispenserComponent>(_owner, out var comp) &&
            _solutionSystem.TryGetSolution(_owner, comp.SolutionName, out _, out var solution))
        {
            // local state dirty causes reagents to refresh
            // because target item changing changes whether the buttons
            // are interactable
            if (SolutionChanged(solution, ref _reagentsHash) || _localStateDirty)
                RefreshReagentList((_owner, comp), solution);
        }

        _localStateDirty = false;
    }

    public void SetLocalDirty() => _localStateDirty = true;

    public void UpdateLocalState()
    {
        if (!_entityManager.TryGetComponent<PlumbingSmartDispenserLocalStateComponent>(_owner, out var state))
            return;

        _outputContainerEntity = state.OutputContainerEntity;
        _showDispensePane = state.OutputContainerEntity is { Valid : true };

        if (state.SelectedDispenseAmount != _dispenseAmount)
        {
            _dispenseAmount = state.SelectedDispenseAmount;
            AmountGrid.Selected = ((int) state.SelectedDispenseAmount).ToString();
        }

        DispensePane.Visible = _showDispensePane;
        DispensePaneDivider.Visible = _showDispensePane;
        ApplyWindowSizing(_showDispensePane);

        _hasLabeler = false;
        if (_entityManager.TryGetComponent<HandLabelerComponent>(_outputContainerEntity, out var labeler))
        {
            _hasLabeler = true;
            _hasOutputContainer = false;
            UpdateLabelerInfo((_outputContainerEntity.Value, labeler));
        }
        else if (_smartDispenserSystem.GetFillSolutionFromContainer(_outputContainerEntity) is Solution fillSolution)
        {
            _hasOutputContainer = true;
            UpdateContainerInfo(_outputContainerEntity, fillSolution);
        }
        else
        {
            _hasOutputContainer = false;
            UpdateContainerInfo(null, null);
        }

        View.SetEntity(_outputContainerEntity);

        ClearButton.Disabled = !_showDispensePane || !_hasOutputContainer;
    }

    private string? GetName(EntityUid? entity)
    {
        if (_entityManager.TryGetComponent<MetaDataComponent>(entity, out var meta))
            return meta.EntityName;

        return null;
    }

    private void ApplyWindowSizing(bool showDispensePane)
    {
        var size = showDispensePane ? _fullWindowSize : _compactWindowSize;
        MinSize = size;
        SetSize = size;
    }

    private void RefreshReagentList(Entity<PlumbingSmartDispenserComponent> ent, Solution solution)
    {
        var canDispense = _showDispensePane && (_hasOutputContainer || _hasLabeler);

        _reagentEntries.Clear();

        // build reagent list
        foreach (var reagent in solution.Contents)
        {
            if (reagent.Quantity <= FixedPoint2.Zero)
                continue;

            if (!_prototypeManager.TryIndex(reagent.Reagent.Prototype, out var proto))
                continue;

            if (!ent.Comp.ReagentLabels.TryGetValue(proto.ID, out var label) || string.IsNullOrWhiteSpace(label))
                label = proto.LocalizedName;

            ReagentEntry entry = new(
                proto.ID,
                label,
                reagent.Quantity,
                proto.SubstanceColor);

            _reagentEntries.Add(entry);
        }

        // Sort alphabetically by localized name or label for consistent display
        _reagentEntries.Sort((a, b) => string.Compare(a.LocalizedName, b.LocalizedName, StringComparison.OrdinalIgnoreCase));

        var totalVolume = FixedPoint2.Zero;

        bool orderChanged = _reagentEntries.Count != ReagentList.ChildCount;
        if (!orderChanged)
        {
            for (int i = 0; i < _reagentEntries.Count; i++)
            {
                if (_reagentEntries[i].ReagentId != ((ClickableBeakerBarChart)ReagentList.Children[i]).ReagentId)
                {
                    orderChanged = true;
                    break;
                }
            }
        }

        if (orderChanged)
            ReagentList.RemoveAllChildren();

        foreach (var entry in _reagentEntries)
        {
            if (!_bars.TryGetValue(entry.ReagentId, out var chart))
            {
                chart = new()
                {
                    Capacity = (float)ent.Comp.MaxPerReagent,
                    HorizontalExpand = true,
                    MinHeight = ReagentRowHeight,
                    MaxHeight = ReagentRowHeight,
                };

                chart.OnChartPressed += OnDispenseClicked;

                _bars.Add(entry.ReagentId, chart);
            }

            if (orderChanged)
                ReagentList.AddChild(chart);

            totalVolume += entry.Quantity;

            chart.ReagentId = entry.ReagentId;
            chart.Disabled = !canDispense;

            var tooltip = Loc.GetString(
                "plumbing-smart-dispenser-row-tooltip",
                ("reagent", entry.LocalizedName),
                ("stored", entry.Quantity),
                ("max", ent.Comp.MaxPerReagent));

            chart.SetDetails(
                entry.ReagentId,
                Loc.GetString("plumbing-smart-dispenser-reagent-entry",
                    ("reagent", entry.LocalizedName),
                    ("amount", entry.Quantity)),
                entry.Quantity.Float(),
                entry.Color,
                tooltip: tooltip);
        }

        if (_reagentEntries.Count == 0)
            StatusLabel.Text = Loc.GetString("plumbing-smart-dispenser-empty");
        else
            StatusLabel.Text = Loc.GetString("plumbing-smart-dispenser-total",
                ("total", totalVolume),
                ("count", _reagentEntries.Count));
    }

    private void OnDispenseClicked(string reagentId)
    {
        if (!_entityManager.TryGetComponent<PlumbingSmartDispenserLocalStateComponent>(_owner, out var localState) ||
            !_entityManager.TryGetNetEntity(localState.OutputContainerEntity, out var targetEntity))
            return;

        OnDispenseReagentPressed?.Invoke(reagentId, FixedPoint2.New((int)localState.SelectedDispenseAmount), targetEntity.Value);
    }

    private void OnClearClicked(BaseButton.ButtonEventArgs args)
    {
        if (!_entityManager.TryGetComponent<PlumbingSmartDispenserLocalStateComponent>(_owner, out var localState) ||
            !_entityManager.TryGetNetEntity(localState.OutputContainerEntity, out var targetEntity))
            return;

        OnClearPressed?.Invoke(targetEntity.Value);
    }

    private void UpdateLabelerInfo(Entity<HandLabelerComponent> labeler)
    {
        ContainerInfo.RemoveAllChildren();
        ContainerInfoName.Text = GetName(labeler.Owner) ?? string.Empty;
        string label = labeler.Comp.AssignedLabel;

        if (label.Length > 24)
            label = label[..24] + "...";

        ContainerInfoFill.Text = label;
    }

    private void UpdateContainerInfo(EntityUid? outputContainer, Solution? outputSolution)
    {
        ContainerInfo.RemoveAllChildren();

        if (outputSolution == null)
        {
            ContainerInfoName.Text = string.Empty;
            ContainerInfoFill.Text = string.Empty;
            ContainerInfo.AddChild(new Label { Text = Loc.GetString("plumbing-smart-dispenser-no-container") });
            return;
        }

        ContainerInfoName.Text = GetName(outputContainer) ?? string.Empty;
        ContainerInfoFill.Text = $"{outputSolution.Volume}/{outputSolution.MaxVolume}u";

        foreach (var (reagent, quantity) in outputSolution.Contents ?? [])
        {
            var localizedName = _prototypeManager.TryIndex(reagent.Prototype, out ReagentPrototype? proto)
                ? proto.LocalizedName
                : reagent.Prototype.Id;

            var row = new BoxContainer
            {
                Orientation = LayoutOrientation.Horizontal,
            };

            row.AddChild(new Label
            {
                Text = $"{localizedName}: ",
            });

            row.AddChild(new Label
            {
                Text = Loc.GetString("reagent-dispenser-window-quantity-label-text", ("quantity", quantity)),
                StyleClasses = { StyleClass.LabelWeak },
            });

            ContainerInfo.AddChild(row);
        }
    }

    private readonly struct ReagentEntry(string reagentId, string localizedName, FixedPoint2 quantity, Color color)
    {
        public readonly string ReagentId = reagentId;
        public readonly string LocalizedName = localizedName;
        public readonly FixedPoint2 Quantity = quantity;
        public readonly Color Color = color;
    }
}
