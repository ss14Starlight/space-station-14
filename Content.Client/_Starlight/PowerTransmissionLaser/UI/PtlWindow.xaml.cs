using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Starlight.PowerTransmissionLaser.UI;

[GenerateTypedNameReferences]
public sealed partial class PtlWindow : DefaultWindow
{
    public bool Enabled;

    private bool _updatingFromServer;
    private float _minPowerMw;
    private float _maxPowerMw;
    private float _targetPowerMw;

    public event Action<float>? PowerApplied;

    public PtlWindow()
    {
        RobustXamlLoader.Load(this);
        SetEnabled(false);

        ApplyPowerButton.OnPressed += _ => TryApplyPowerFromInput();
        PowerLineEdit.OnTextEntered += _ => TryApplyPowerFromInput();
        PowerLineEdit.OnFocusExit += _ => TryApplyPowerFromInput();

        SetPowerBounds(0f, 5f);
        SetTargetPowerMw(1f);
        SetBattery(0, 0);
        SetTotalSpesos(0);
    }

    public void SetEnabled(bool enabled)
    {
        Enabled = enabled;
        EnabledButton.Text = enabled ? Loc.GetString("ptl-ui-stop") : Loc.GetString("ptl-ui-start");
    }

    public void SetPowerBounds(float minMw, float maxMw)
    {
        _minPowerMw = minMw;
        _maxPowerMw = maxMw;
    }

    public void SetTargetPowerMw(float mw)
    {
        if (MathHelper.CloseTo(_targetPowerMw, mw))
            return;

        _targetPowerMw = mw;
        PowerLabel.Text = Loc.GetString("ptl-ui-power", ("mw", mw));

        _updatingFromServer = true;
        PowerLineEdit.Text = mw.ToString("0.###");
        _updatingFromServer = false;
    }

    private void TryApplyPowerFromInput()
    {
        if (_updatingFromServer)
            return;

        if (!float.TryParse(PowerLineEdit.Text, out var mw))
        {
            // Revert to last known good value.
            _updatingFromServer = true;
            PowerLineEdit.Text = _targetPowerMw.ToString("0.###");
            _updatingFromServer = false;
            return;
        }

        mw = Math.Clamp(mw, _minPowerMw, _maxPowerMw);

        if (Math.Abs(mw - _targetPowerMw) < 0.0001f)
            return;

        _targetPowerMw = mw;
        PowerLabel.Text = Loc.GetString("ptl-ui-power", ("mw", mw));
        _updatingFromServer = true;
        PowerLineEdit.Text = mw.ToString("0.###");
        _updatingFromServer = false;

        PowerApplied?.Invoke(mw);
    }

    public void SetBattery(float currentJ, float maxJ)
        => BatteryLabel.Text = Loc.GetString("ptl-ui-battery", ("current", currentJ), ("max", maxJ));

    public void SetTotalSpesos(int total)
        => TotalSpesosLabel.Text = Loc.GetString("ptl-ui-total-spesos", ("total", total));
}
