using Content.Client.UserInterface.Controls;
using Content.Shared._Starlight.Power.CombustionTurbine;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Starlight.Power.CombustionTurbine;

[GenerateTypedNameReferences]
public sealed partial class CombustionTurbineConsoleWindow : FancyWindow
{
    public event Action<bool>? OnToggle;
    public event Action<float>? OnIntakeChanged;

    private static readonly Color _goodColor = Color.FromHex("#4fb54f");
    private static readonly Color _warnColor = Color.FromHex("#d6a83a");
    private static readonly Color _badColor = Color.FromHex("#d14343");

    private float _intakeVolume;

    public CombustionTurbineConsoleWindow()
    {
        RobustXamlLoader.Load(this);

        OnButton.OnPressed += _ => OnToggle?.Invoke(true);
        OffButton.OnPressed += _ => OnToggle?.Invoke(false);

        IntakeSlider.OnValueChanged += _ => IntakeText.Text = FormatIntake(IntakeSlider.Value);
        IntakeSlider.OnReleased += _ => OnIntakeChanged?.Invoke(IntakeSlider.Value / 100f);
    }

    public void UpdateState(CombustionTurbineConsoleState state)
    {
        ControlsBox.Visible = state.Connected;
        StatusLabel.Text = Loc.GetString(state.Connected
            ? "combustion-turbine-console-status-connected"
            : state.GeneratorMissing
                ? "combustion-turbine-console-status-no-generator"
                : "combustion-turbine-console-status-unlinked");

        if (!state.Connected)
            return;

        OnButton.Pressed = state.Enabled;
        OffButton.Pressed = !state.Enabled;
        StarterLabel.Visible = state.StarterRunning;

        GovernorLabel.Visible = state.Enabled && state.Governor < 0.99f;
        GovernorLabel.Text = Loc.GetString("combustion-turbine-console-governor",
            ("value", (int) MathF.Round(state.Governor * 100f)));
        GovernorLabel.FontColorOverride = _warnColor;

        OverheatLabel.Visible = state.Overheating;
        OverheatLabel.FontColorOverride = _badColor;

        RpmBar.MaxValue = MathF.Max(1f, state.MaxRpm);
        RpmBar.Value = state.Rpm;
        RpmText.Text = Loc.GetString("combustion-turbine-console-rpm-value",
            ("rpm", (int) state.Rpm),
            ("max", (int) state.MaxRpm));

        IntegrityBar.Value = state.Integrity;
        IntegrityBar.Modulate = state.Integrity < 30f ? _badColor : state.Integrity < 90f ? _warnColor : _goodColor;
        IntegrityText.Text = FormatPercent(state.Integrity);

        PowerText.Text = Loc.GetString("combustion-turbine-console-power-value", ("power", state.Power));

        TemperatureText.Text = Loc.GetString("combustion-turbine-console-temperature-value",
            ("temperature", (int) state.InletTemperature),
            ("max", (int) state.MaxTemperature));
        TemperatureText.FontColorOverride = state.InletTemperature > state.MaxTemperature ? _badColor : null;

        InletPressureText.Text = FormatPressure(state.InletPressure);
        ChamberPressureText.Text = FormatPressure(state.ChamberPressure);
        OutletPressureText.Text = FormatPressure(state.OutletPressure);
        FlowText.Text = Loc.GetString("combustion-turbine-console-flow-value", ("flow", state.MolesPerSecond.ToString("F1")));

        _intakeVolume = state.IntakeVolume;

        if (!IntakeSlider.Grabbed)
        {
            IntakeSlider.SetValueWithoutEvent(state.IntakeRatio * 100f);
            IntakeText.Text = FormatIntake(state.IntakeRatio * 100f);
        }
    }

    private string FormatIntake(float percent)
        => Loc.GetString("combustion-turbine-console-intake-value",
            ("value", (int) MathF.Round(percent)),
            ("volume", (int) MathF.Round(_intakeVolume * percent / 100f)));

    private static string FormatPercent(float value)
        => Loc.GetString("combustion-turbine-console-percent", ("value", (int) MathF.Round(value)));

    private static string FormatPressure(float kpa)
        => Loc.GetString("combustion-turbine-console-pressure-value", ("pressure", kpa.ToString("F1")));
}
