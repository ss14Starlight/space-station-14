using Content.Shared._Starlight.Lathe;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._Starlight.Lathe;

[GenerateTypedNameReferences]
public sealed partial class LatheLinkingDisplay : PanelContainer
{

    [Dependency] private IEntityManager _entityManager = default!;

    private readonly LatheLinkingUIController _controller;
    private EntityUid _entity;

    public LatheLinkingDisplay()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _controller = UserInterfaceManager.GetUIController<LatheLinkingUIController>();
        LinkingTransferButton.OnPressed += _ => SetMode(false);
        LinkingEjectButton.OnPressed += _ => SetMode(true);
    }

    public void SetEntity(EntityUid entity) => _entity = entity;

    public void SetMode(bool eject) => _controller.SendToggleMessage(_entity, eject);

    protected override void FrameUpdate(FrameEventArgs args)
    {
        if (_entityManager.TryGetComponent<LatheLinkingComponent>(_entity, out var linking))
        {

            ButtonBox.Visible = true;
            LinkingEjectButton.ToolTip = Loc.GetString("lathe-menu-linking-eject-tooltip",
                ("lathename", _entityManager.GetComponent<MetaDataComponent>(_entity).EntityName));
            if (linking.LinkedEntity != null)
                LinkingTransferButton.Text = _entityManager.GetComponent<MetaDataComponent>(linking.LinkedEntity.Value)
                    .EntityName;
            else
            {
                LinkingEjectButton.Disabled = true;
                LinkingTransferButton.Disabled = true;
            }
            if (linking.Ejecting)
            {
                LinkingEjectButton.Pressed = true;
                LinkingTransferButton.Pressed = false;
            }
            else
            {
                LinkingTransferButton.Pressed = true;
                LinkingEjectButton.Pressed = false;
            }
        }
    }
}

